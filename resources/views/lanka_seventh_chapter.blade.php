     <p>Затем бодхисаттва-махасаттва Махамати вновь обратился к Благословенному:</p>

    <p>— Благословенный, Тобой предсказано, что даже архаты достигнут высшего пробуждения. Ты учишь, что все существа пребывают в природе Татхагаты и потому не подлежат окончательному угасанию. Ты говоришь: «С той ночи, когда Татхагата пробудился, и до той ночи, когда Он уйдёт в паринирвану, — Им не будет произнесено ни единого слога». Ты учишь, что Татхагаты всегда в <em>самадхи</em>, не рассуждают и не мыслят, а дела Будды совершают Их Явленные Тела.</p>

    <p>Но тогда почему говорится о мгновенности сознаний? Почему Ваджрапани всегда неотступно следует за Тобой? Почему говорится об отсутствии начала сансары и одновременно о прекращении? И как быть с [историями о] Чанче, Сундарике, монахине и вымытой чаше — всё это выглядит как кармические преграды?<a href="#citation-485" id="ref-485" class="citation-mark"><sup>485</sup></a> Если эти омрачения не изжиты, как Ты обрёл Всеведение?</p>

    <p>Благословенный ответил:</p>

    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>Слушай же внимательно. Мои предсказания шравакам даны ради их воодушевления [к вступлению] на путь бодхисаттвы. В разных мирах есть те, кто жаждет нирваны шраваков; чтобы отвратить их от этого малого вкуса, Мои Явленные Тела, а не Тела Дхармы, дают им предсказания.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>У шраваков и пратьекабудд очищено лишь омрачение <em>клеш</em> (<em>kleśāvaraṇa</em>) через видение отсутствия «я» личности. Но омрачение познаваемого (<em>jñeyāvaraṇa</em>) очищается лишь через видение отсутствия «я» дхарм. Полное же освобождение от преград наступает лишь при прекращении отпечатков (<em>vāsanā</em>) в <em>Алайя-виджняне</em>.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>Опираясь на изначальную устойчивость дхарм (<em>dharmasthititā</em>) и в силу того, что в [этом учении] нет ни первого, ни последнего, Татхагата проповедует Дхарму теми же слогами, что были произнесены прежде, — не рассуждая и не мысля.<a href="#citation-486" id="ref-486" class="citation-mark"><sup>486</sup></a> Он не рассуждает и не мыслит, ибо очистился от четырёх видов отпечатков, преодолел две смерти<a href="#citation-487" id="ref-487" class="citation-mark"><sup>487</sup></a> и устранил двойное омрачение — клеш и познаваемого.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>Махамати, семь видов сознания — мгновенны; они порождены отпечатками, лишены благого и незагрязнённого начала и сами по себе не вращаются в сансаре. Татхагатагарбха же, Махамати, вращается в сансаре, будучи причиной и Нирваны, и блаженства, и страдания. Но невежды, чей разум уведён в сторону [ложным пониманием] <em>шуньяты</em>, не ведают этого.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>Махамати, Ваджрапани следует по пятам лишь за явленными (<em>nirmita</em>) и воплощёнными (<em>nairmāṇika</em>) Татхагатами, но не за Подлинными Татхагатами (<em>maula-tathāgata</em>), Архатами, Совершенно Пробуждёнными. Ибо Подлинный Татхагата, Махамати, свободен от любых мерил и чувств невежд, шраваков, пратьекабудд и тиртхиков. Благородные йогины приходят к Нему через стойкость прямого постижения и знания Дхармы; поэтому Ваджрапани нет нужды сопровождать Его.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>Все явленные Будды не рождены из кармы. В них нет Татхагаты как сущности, но и вне них Татхагаты нет. Подобно гончару, использующему круг, глину и усилие, явленный Будда совершает дела ради существ и проповедует через признаки; но он не излагает Высший Метод (<em>svanaya</em>) — сферу личного благородного постижения.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>Более того, Махамати, из-за прекращения шести видов сознания невежды впадают в нигилизм (<em>uccheda</em>), а из-за непонимания <em>Алайи</em> — в воззрение о вечности (<em>śāśvata</em>). Нет предела прошлого у различения собственного ума; но через прекращение самого этого различения обнаруживается освобождение. С устранением четырёх видов отпечатков устраняются и все пороки.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>Об этом сказано так:</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>1. Три Колесницы и Единая Колесница;</li>
            <li>у Будд же нет [окончательного] угасания (<em>nirvṛti</em>).</li>
            <li>Все предсказаны к состоянию Будды —</li>
            <li>так проповедано Теми, кто оставил пороки.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>2. Знание, ведущее к постижению,</li>
            <li>и нирвана без остатка (<em>nirupādi-gati</em>) —</li>
            <li>[всё это] проповедано как скрытый смысл (<em>saṃdhi</em>)</li>
            <li>ради воодушевления тех, кто пал духом.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>3. Знание порождено Буддами, и ими же указан Путь.</li>
            <li>Лишь по нему идут [все существа] и ни по какому иному;</li>
            <li>посему у них (Будд) нет угасания.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>4. Отпечатки [привязанности к] становлению,</li>
            <li>чувственным желаниям, миру форм и ложным воззрениям —</li>
            <li>вот четыре вида [омрачений].</li>
            <li>Они рождены в ментальном сознании (<em>manovijñāna</em>)</li>
            <li>и пребывают в <em>Алайе</em> и <em>манасе</em> (<em>manas</em>).</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>5. Из-за ментального сознания, глаза и прочих [органов чувств]</li>
            <li>возникает [ложное воззрение] об уничтожении и непостоянстве.</li>
            <li>Вечность же [воображается] из-за безначального [неведения] —</li>
            <li>такова Нирвана тех, кто во власти крайних воззрений.</li>
        </ul>
    </blockquote>

    <p class="text-center font-bold mt-8">Так завершается седьмая глава махаянской «Ланкаватара-сутры», называемая «О явленных телах Будды».</p>
