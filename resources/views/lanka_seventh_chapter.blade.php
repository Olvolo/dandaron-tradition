    <h4 class="text-center text-gray-800 font-bold text-xl my-4">ПРИМЕЧАНИЯ</h4>

    <hr class="my-8 border-t-4 border-gray-500">
    <p class="my-2" id="citation-485"><sup>485</sup> Четыре кармические преграды Будды — традиционные эпизоды, упоминаемые в махаянских сутрах как кажущиеся кармические последствия, хотя на самом деле они — умелые средства (<em>upāya</em>) для назидания:</p>
    <p class="my-2 ml-4"><strong>Чанча</strong> — дочь брахмана, которая оклеветала Будду, обвинив его в связи с ней; позже раскаялась и умерла.</p>
    <p class="my-2 ml-4"><strong>Сундари</strong> — монахиня, убитая последователями других учений; её тело было подброшено в парке джайнов, чтобы обвинить сангху.</p>
    <p class="my-2 ml-4"><strong>Монахиня</strong> — возможно, отсылка к другой истории, где монахиня была вовлечена в ложное обвинение против Будды.</p>
    <p class="my-2 ml-4"><strong>Вымытая чаша</strong> — Будда якобы нарушил правило, вымыв свою чашу в реке, что считалось неподобающим.<a href="#ref-485" class="text-blue-500 hover:underline ml-2">↩</a></p>
    <p class="my-2" id="citation-486"><sup>486</sup> <em>Pūrvadharmasthititā</em> — «изначальная устойчивость дхарм» — дхармы пребывают в своей природе независимо от того, появляется Будда или нет.</p>
    <p class="my-2"><em>Apūrvacaramasya abhāvāt</em> — «в силу отсутствия первого и последнего» — в учении Будды нет ничего нового (<em>apūrva</em>) и нет ничего окончательного (<em>carama</em>): оно не создаётся заново каждый раз и не завершается. Дхарма была, есть и будет — Будда лишь указывает на то, что существует изначально.</p>
    <p class="my-2">Смысл всей фразы: поскольку дхармы изначально устойчивы и поскольку в учении нет ни первого, ни последнего слова, Татхагата проповедует теми же слогами, что были произнесены прежде — не создавая ничего нового, не рассуждая и не мысля.<a href="#ref-486" class="text-blue-500 hover:underline ml-2">↩</a></p>
    <p class="my-2" id="citation-487"><sup>487</sup> «Две смерти» (<em>cyutidvaya</em>) — смерть от кармы и смерть от омрачений. Татхагата преодолел обе, ибо Его явление не обусловлено ни кармой, ни клешами.<a href="#ref-487" class="text-blue-500 hover:underline ml-2">↩</a></p>
