<p class="my-2" id="citation-445"><sup>445</sup> <em>Viviktadarśana</em>, «Видение отрешённости» — видение вещей в их уединённости, свободной от наложений понятий. Это прямое усмотрение того, что вещи не таковы, какими их воображают, — и вместе с тем не являются совершенным ничто. Именно это видение предшествует повороту различения.<a href="#ref-445" class="citation-back">↩</a></p>

