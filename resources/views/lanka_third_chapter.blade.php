<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Глава 3, Подглава 1 (Тело, созданное умом)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>Затем Благословенный вновь обратился к бодхисаттве-махасаттве Махамати:</p>
    <p>— Я разъясню тебе, Махамати, признаки различения видов тела, созданного умом (<em>manomayakāya</em>). Слушай внимательно и запечатлей это в уме!</p>

    <p>— Да, Благословенный, — ответил бодхисаттва-махасаттва Махамати.</p>
    <p>Благословенный сказал:</p>
   <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Тело, созданное умом (<em>manomayakāya</em>), бывает трёх видов (<em>triprakāra</em>). Каких трёх?</li>
        <li>• Тело, рождённое из самадхи и блаженства поглощения;<a href="#citation-316" id="ref-316" class="citation-mark"><sup>316</sup></a></li>
        <li>• Тело, рождённое из постижения собственной природы дхарм;<a href="#citation-317" id="ref-317" class="citation-mark"><sup>317</sup></a></li>
        <li>• Тело, рождённое из врождённой деятельности <em>скандх</em> и их формирующих факторов.<a href="#citation-318" id="ref-318" class="citation-mark"><sup>318</sup></a></li>
        <li>Йогины постигают их последовательно, через распознавание признаков первой и последующих ступеней.<a href="#citation-319" id="ref-319" class="citation-mark"><sup>319</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Каково, Махамати, тело, рождённое из <em>самадхи</em> и блаженства поглощения?</li>
        <li>Это то, что достигается на третьей, четвёртой или пятой ступени через пребывание в уединении от многообразия собственного ума,<a href="#citation-320" id="ref-320" class="citation-mark"><sup>320</sup></a> когда волна движущегося сознания<a href="#citation-321" id="ref-321" class="citation-mark"><sup>321</sup></a> в океане ума (<em>cittodadhi</em>) прекращает своё течение, и благодаря постижению как отсутствия, так и наличия объектов, воспринимаемых собственным умом,<a href="#citation-322" id="ref-322" class="citation-mark"><sup>322</sup></a> ум порождает тело, созданное умом (<em>manomayaḥ kāyaḥ</em>).</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Каково тело, рождённое из постижения собственной природы дхарм?</li>
        <li>Это то, что возникает на восьмой ступени, когда ум, совершив поворот основы,<a href="#citation-323" id="ref-323" class="citation-mark"><sup>323</sup></a> постигает недвойственность магии, сновидений, отражений и прочего, свободную от ментальных образов,<a href="#citation-324" id="ref-324" class="citation-mark"><sup>324</sup></a> обретает <em>самадхи</em>, подобное магии (<em>māyopamasamādhi</em>), и множество других врат <em>самадхи</em> (<em>samādhimukha</em>), и тем самым получает тело, украшенное цветами <em>властей</em> (<em>vaśitā</em>) и <em>сверхзнаний</em> (<em>abhijñā</em>), стремительное как мысль (<em>manojavasadṛśa</em>), подобное магии, сновидению, отражению,<a href="#citation-325" id="ref-325" class="citation-mark"><sup>325</sup></a> лишённое материальной сущности (<em>abhautika</em>), но подобное материальному,<a href="#citation-326" id="ref-326" class="citation-mark"><sup>326</sup></a> проявляющее все формы и части тела во всём их многообразии,<a href="#citation-327" id="ref-327" class="citation-mark"><sup>327</sup></a> и следующее за всеми собраниями Будд во всех мирах.<a href="#citation-328" id="ref-328" class="citation-mark"><sup>328</sup></a> Поскольку оно следует ходу собственной природы дхарм,<a href="#citation-329" id="ref-329" class="citation-mark"><sup>329</sup></a> его называют телом, созданным умом.</li>
    </ul>

    <ul class="list-none mb-12 pl-2 space-y-1 ml-2">
        <li>Каково тело, рождённое из врождённой деятельности <em>скандх</em> и их формирующих факторов?</li>
        <li>Это то, что возникает благодаря постижению блаженства, являющегося признаком личного достижения всех дхарм Будды.<a href="#citation-330" id="ref-330" class="citation-mark"><sup>330</sup></a></li>
        <li>Поэтому, Махамати, тебе следует практиковать йогу распознавания признаков этих трёх тел.<a href="#citation-331" id="ref-331" class="citation-mark"><sup>331</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>1. Нет у Меня ни колесницы, ни великой колесницы,</li>
        <li>ни звука, ни букв,</li>
        <li>ни истины, ни освобождения,</li>
        <li>ни даже сферы, лишённой ментальных образов.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>2. Но если говорить о великой колеснице —</li>
        <li>это власть над <em>самадхи</em>,<a href="#citation-332" id="ref-332" class="citation-mark"><sup>332</sup></a></li>
        <li>тело, созданное умом, во всём своём многообразии,<a href="#citation-333" id="ref-333" class="citation-mark"><sup>333</sup></a></li>
        <li>украшенное цветами <em>властей</em>.<a href="#citation-334" id="ref-334" class="citation-mark"><sup>334</sup></a></li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>


<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.2 (Пять преступлений с немедленным воздаянием)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>Затем бодхисаттва-махасаттва Махамати вновь обратился к Благословенному:</p>
    <p>— Пять преступлений с немедленным воздаянием<a href="#citation-335" id="ref-335" class="citation-mark"><sup>335</sup></a> были указаны Благословенным. Каковы они, Благословенный, из-за совершения которых сын или дочь благородного рода попадает в Ави́чи?</p>

    <p>Благословенный ответил:</p>
    <p>— Слушай же внимательно, Махамати, и запечатлей это в уме! Я скажу тебе.</p>

    <p>— Да, Благословенный, — ответил бодхисаттва-махасаттва Махамати.</p>

    <p>Благословенный сказал:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Махамати, какие пять преступлений с немедленным воздаянием? Это:</li>
        <li>Убийство матери (<em>mātṛvadha</em>),</li>
        <li>Убийство отца (<em>pitṛvadha</em>),</li>
        <li>Убийство архата (<em>arhadvadha</em>),</li>
        <li>Раскол Сангхи (<em>saṃghabheda</em>),</li>
        <li>Намеренное пролитие крови Татхагаты (<em>tathāgatakāye duṣṭacittarudhirotpāda</em>).</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Но здесь, Махамати, всё понимается внутренне (<em>ādhyātmikam</em>):</li>
        <li>Что есть мать (<em>mātā</em>) среди существ? Это — жажда к новому рождению (<em>tṛṣṇā paunarbhavikī</em>), сопровождаемая наслаждением и привязанностью (<em>nandīrāgasahagatā</em>). Она рождается как мать.</li>
        <li>Что есть отец (<em>pitā</em>)? Это — неведение (<em>avidyā</em>), порождающее совокупность баз чувств (<em>āyatanagrāma</em>). Поэтому убийство матери и отца — это полное искоренение (<em>atyantamūlopaccheda</em>) этих двух корней.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Что есть убийство архата? Архат здесь — это спящие склонности (<em>anuśayāḥ</em>), подобные врагу (<em>ari</em>), — которые, подобно крысиному яду (<em>mūṣikāviṣa</em>), незаметно накапливаются, но внезапно обостряются (<em>prakopa</em>). Их полное уничтожение (<em>atyantasamuddhāta</em>) — и есть убийство архата.<a href="#citation-336" id="ref-336" class="citation-mark"><sup>336</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Что есть раскол Сангхи? Это — полное разрушение корня (<em>atyantamūlopaghāta</em>) совокупности <em>скандх</em> (<em>skandhasaṃghāta</em>), чьи признаки взаимно различны (<em>bhinna-anyonyalakṣaṇa</em>).<a href="#citation-337" id="ref-337" class="citation-mark"><sup>337</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Что есть намеренное пролитие крови Татхагаты? Это — полное пресечение (<em>atyantopaghāta</em>) злостных воображений (<em>duṣṭavikalpa</em>) у восьми совокупностей сознания  (<em>aṣṭau vijñānakāyāḥ</em>), которые постигают всё — общее и внешнее — как лишь воспринимаемое собственным умом (<em>svasāmānyabāhyasvacittadṛśyamātra</em>).<a href="#citation-338" id="ref-338" class="citation-mark"><sup>338</sup></a> Когда «кровь» злостного умысла полностью пролита из Будды-сознания (<em>vijñānabuddha</em>),<a href="#citation-339" id="ref-339" class="citation-mark"><sup>339</sup></a> высвобождаются три вида освобождения (<em>vimokṣatraya</em>) и непорочное состояние (<em>anāsrava</em>). Вот это и есть подлинное пролитие крови Татхагаты.
<a href="#citation-340" id="ref-340" class="citation-mark"><sup>340</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Эти пять преступлений с немедленным воздаянием, Махамати, — внутренние (<em>ādhyātmikāni</em>). Тот, кто их совершает, становится совершителем немедленного действия (<em>ānantaryakārī</em>) — ибо он и есть постигший Дхарму (<em>abhisamitadharmaḥ</em>).</li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>


<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.3 (Внешние преступления и сила благословения)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">

    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>Кроме того, Махамати, Я разъясню тебе внешние преступления с немедленным воздаянием (<em>bāhyāni ānantaryāṇi</em>).<a href="#citation-341" id="ref-341" class="citation-mark"><sup>341</sup></a> Благодаря этому наставлению ты и другие бодхисаттвы в грядущие времена не впадёте в заблуждение.</li>
            <li>Что же это за [преступления]? Это те самые, что описаны в учении (<em>deśanāpāṭha</em>). Тот, кто их совершает, не достигает ни одного из трёх видов освобождения — за исключением тех случаев, когда происходит постижение через магическое благословение.<a href="#citation-342" id="ref-342" class="citation-mark"><sup>342</sup></a></li>
            <li>Поистине, Махамати, даже шравака, обретший магическое благословение — будь то от бодхисаттвы или от Татхагаты, — способен к такому постижению.</li>
            <li>Если кто-либо совершил преступление и пребывает в раскаянии (<em>kaukṛtya</em>),<a href="#citation-343" id="ref-343" class="citation-mark"><sup>343</sup></a> то ради устранения его воззрения, полного раскаяния, и ради того, чтобы он снял это бремя (<em>nikṣiptadhura</em>) и более не удерживал в уме взгляда, отягощённого виной, — Я являю ему это постижение через магическое благословение, дабы вновь воодушевить его.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Махамати, для того, кто совершил внешнее преступление, не существует иного пути к окончательному постижению, кроме осознания того, что всё воспринимаемое — лишь плод собственного ума.</li>
        <li>Когда он видит тело, наслаждения, основания и пути существования как различения, свободные от схватывания «я» и «моего»,<a href="#citation-344" id="ref-344" class="citation-mark"><sup>344</sup></a> — тогда, встретив Благородного Друга (<em>kalyāṇamitra</em>) в переходный момент между формами существования (<em>anyagatisaṃdhau</em>), он освобождается от пороков собственного различающего ума (<em>svavikalpadoṣa</em>).</li>
        </ul>

        <p>Об этом сказано так:</p>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>3. Жажда (<em>tṛṣṇā</em>) названа матерью,</li>
        <li>а неведение (<em>avidyā</em>) — отцом.</li>
        <li>Сознание (<em>vijñāna</em>), постигающее объекты,</li>
        <li>именуется в учении «Буддой».</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>4. Архаты — это спящие склонности (<em>anuśayāḥ</em>),</li>
        <li>а Сангха — это пучок <em>скандх</em>.<a href="#citation-345" id="ref-345" class="citation-mark"><sup>345</sup></a></li>
        <li>Через разрыв их непрерывности</li>
        <li>карма становится немедленной.<a href="#citation-346" id="ref-346" class="citation-mark"><sup>346</sup></a></li>
        </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>


<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.4 (Как становится явной природа Будды)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>Затем Махамати вновь спросил:</p>
    <p>— Пусть Благословенный наставит меня: как, о Благословенный, становится явной природа Будды (<em>buddhatā</em>) у Благословенных Будд?</p>

    <p>Благословенный ответил:</p>
<blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Махамати, природа Будды у Благословенных Будд становится явной благодаря:</li>
        <li>— постижению двух видов отсутствия «я» (<em>nairātmya-dvaya</em>) — в личности и в дхармах;</li>
        <li>— полному распознаванию двух видов завес (<em>āvaraṇa-dvaya</em>);</li>
        <li>— обретению выхода (<em>cyuti</em>) из непостижимого превращения (<em>acintyapariṇāma</em>);</li>
        <li>— окончательному отбрасыванию двух видов омрачений (<em>kleśadvaya</em>).</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Махамати, именно через достижение этих состояний обретается пробуждение шраваков, пратьекабудд и Совершенно Пробуждённых. Именно поэтому, Махамати, Я проповедую Единую Колесницу (<em>ekayāna</em>).</li>
    </ul>

    <p>Об этом сказано так:</p>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>5. Благодаря [познанию] двух видов отсутствия «я»,</li>
        <li>[отбрасыванию] омрачений, двух видов завес,</li>
        <li>и благодаря обретению выхода (<em>cyuti</em>)</li>
        <li>из непостижимого превращения<a href="#citation-347" id="ref-347" class="citation-mark"><sup>347</sup></a> — является Татхагата.</li>
    </ul>
</blockquote>
    <p class="text-center font-bold">***</p>
</div>


<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.5 (Четыре равенства)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>Затем бодхисаттва-махасаттва Махамати вновь обратился к Благословенному:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Исходя из какого скрытого смысла (<em>saṃdhāya</em>), о Благословенный, находясь посреди собрания, Ты изрёк слова:</li>
        <li>«Я сам был всеми Буддами прошлого и прошёл через многообразие рождений в Джатаках. В те времена и в те сроки Я был царём Мандхатарой, слоном, попугаем, Индрой, Вьясой и Сунетрой», — и наставил в сотнях тысяч таких Джатак?»</li>
    </ul>
    </blockquote>

    <p>Благословенный ответил:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Исходя из четырёх видов равенства (<em>caturvidhāṃ samatāṃ</em>), Махамати, Татхагаты, Архаты, Совершенно Пробуждённые, находясь в собрании, провозглашают:</li>
        <li>«В те времена и в те сроки Я был Кракуччхандой, Канакамуни и Кашьяпой».</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Что же это за четыре вида равенства? Это:</li>
        <li>• Равенство букв (<em>akṣarasamatā</em>);</li>
        <li>• Равенство речи (<em>vāksamatā</em>);</li>
        <li>• Равенство тела (<em>kāyasamatā</em>);</li>
        <li>• Равенство Дхармы (<em>dharmasamatā</em>).</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Махамати, что есть равенство букв? Те самые буквы, что составляют моё имя «Будда», — это те же самые буквы, что составляют имена тех Будд, Благословенных. Эти буквы, Махамати, не имеют различий в своей природе как буквы.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Что есть равенство речи Татхагат? Моя речь развёртывается через шестьдесят четыре вида качеств чистого голоса (<em>brahmasvararutaghoṣa</em>), и точно так же у тех Татхагат речь развёртывалась через шестьдесят четыре вида качеств чистого голоса — без убавления или прибавления, не имея различий в своей природе, подобно голосу птицы Калавинка и чистому голосу Брахмы.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Что есть равенство тела? Я и те Татхагаты равны и не имеем различий в Теле Дхармы (<em>dharma-kāya</em>), а также в теле, обладающем признаками и знаками формы (<em>rūpa-lakṣaṇānuvyañjana-kāya</em>), кроме тех случаев, когда форма определяется [способностями] тех, кого надлежит наставить (<em>vaineyavaśamupādāya</em>). В разных мирах существ Татхагаты являют многообразие форм.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Что есть равенство Дхармы? И они, и Я — постигшие тридцать семь факторов пробуждения (<em>bodhipakṣyadharmān</em>).</li>
    </ul>

    <ul class="list-none mb-12 pl-2 space-y-1 ml-2">
        <li>Исходя из этого четырёхкратного равенства, Татхагаты провозглашают [своё единство] в собрании.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>6. Я — Кашьяпа, Кракуччханда и Конакамуни.</li>
        <li>Я возглашаю это сыновьям Победителей,</li>
        <li>утвердившись в [этом] равенстве.<a href="#citation-348" id="ref-348" class="citation-mark"><sup>348</sup></a></li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>


<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.6 (Речь Будды — это безмолвие)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>Затем Махамати вновь спросил:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>О Благословенный, Тобой было сказано:</li>
        <li>«В ту ночь, когда Татхагата обрёл пробуждение, и в ту ночь, когда Он уйдёт в паринирвану, — в этот промежуток Татхагатой не было произнесено и не будет изречено ни единого звука. Речь Будды — это безмолвие».<a href="#citation-349" id="ref-349" class="citation-mark"><sup>349</sup></a></li>
        <li>Исходя из какого скрытого смысла (<em>saṃdhāya</em>) это было сказано Татхагатой?</li>
    </ul>
    </blockquote>

    <p>Благословенный ответил:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Исходя из двух аспектов Дхармы (<em>dharmadvaya</em>),<a href="#citation-350" id="ref-350" class="citation-mark"><sup>350</sup></a> Махамати, было сказано это Мною:</li>
        <li>• Исходя из личной природы реальности (<em>pratyātma-dharmatā</em>);</li>
        <li>• Исходя из древней установленной природы реальности (<em>paurāṇa-sthiti-dharmatā</em>).</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Что есть личная природа реальности? То, что было постигнуто теми Татхагатами, — постигнуто и Мною: без убавления и без прибавления. Это сфера личного постижения (<em>svapratyātmagati</em>), свободная от речевых различений (<em>vāgvikalpa-rahita</em>) и свободная от двойственности языковых путей.<a href="#citation-351" id="ref-351" class="citation-mark"><sup>351</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Что есть древняя установленная природа реальности? Махамати, эта природа реальности — древняя. Подобно залежам золота, серебра или жемчуга, пребывает этот Мир Дхармы (<em>dharmadhātu</em>). Являются ли Татхагаты в мир или не являются, — эта природа дхарм, эта установленность дхарм (<em>dharmasthititā</em>), этот порядок дхарм (<em>dharmaniyāmatā</em>) пребывает неизменно.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Это подобно пути в древний город.<a href="#citation-352" id="ref-352" class="citation-mark"><sup>352</sup></a> Представь, Махамати, человека, который, блуждая в лесу, обнаружил бы древний город с ровными дорогами и вошёл бы в него. Войдя туда и поселившись, он вкусил бы радостей городской жизни. Как ты думаешь, Махамати, — разве этот человек создал тот путь или тот город?</li>
    </ul>
    </blockquote>

    <p>Махамати ответил:</p>
    <p>— Нет, Благословенный.</p>

    <p>Благословенный сказал:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-12 pl-2 space-y-1 ml-2">
        <li>Точно так же, Махамати: то, что было постигнуто Мною и теми Татхагатами, — это вечно пребывающая природа, порядок дхарм, Таковость (<em>tathatā</em>), Истинность (<em>bhūtatā</em>), Реальность (<em>satyatā</em>).<a href="#citation-353" id="ref-353" class="citation-mark"><sup>353</sup></a> Именно по этой причине Мною сказано: в промежутке между ночью пробуждения и ночью ухода в паринирвану Татхагатой не было и не будет произнесено ни единого слова.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>7. В промежутке между ночью постижения и</li>
        <li>ночью ухода в паринирвану</li>
        <li>Мною не было провозглашено ничего.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>8. Исходя из установленности</li>
        <li>личной природы реальности, Я изрёк это.</li>
        <li>Между теми Буддами и Мною</li>
        <li>нет ни малейшего различия.</li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>


<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.7 (Признаки небытия и бытия)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>Затем бодхисаттва-махасаттва Махамати вновь обратился к Благословенному:</p>
    <p>— Пусть Благословенный наставит меня в признаках небытия и бытия (<em>nāstyastitva-lakṣaṇa</em>)<a href="#citation-354" id="ref-354" class="citation-mark"><sup>354</sup></a> всех дхарм, дабы я и другие бодхисаттвы, оставив крайности «есть» и «нет», быстро обрели непревзойдённое совершенное пробуждение.</p>

    <p>Благословенный ответил:</p>
    <p>— Слушай же внимательно, Махамати, и запечатлей это в уме! Я скажу тебе.</p>

    <p>— Да, Благословенный, — ответил бодхисаттва-махасаттва Махамати.</p>

    <p>Благословенный сказал:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Этот мир опирается на двойственность: на бытие (<em>astitva</em>) и на небытие (<em>nāstitva</em>). Запутавшись в воззрении и склонности к «бытию» и «небытию», существа ищут спасения там, где его нет.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Как мир опирается на бытие? Считая, что мир возникает из реально существующих причин и условий, а не из отсутствующих; и что нечто возникающее рождается из уже существующего. Так человек становится приверженцем учения о реальности причин и самого мира.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Как он опирается на небытие? Приняв наличие страсти, гнева и неведения, он затем воображает то их бытие, то их небытие. Или же, видя, что признаки вещей лишены содержания (<em>vivikta</em>),<a href="#citation-355" id="ref-355" class="citation-mark"><sup>355</sup></a> он не признаёт их существования; и зная, что Будды и шраваки свободны от страсти и гнева, он считает, будто они лишились чего-то реально существовавшего.</li>
        <li>Кто же здесь является нигилистом (<em>vaināśika</em>)?<a href="#citation-356" id="ref-356" class="citation-mark"><sup>356</sup></a></li>
    </ul>
    </blockquote>

    <p>Махамати ответил:</p>
    <p>— Тот, кто сначала признаёт страсть и гнев, а затем отрицает их.</p>

    <p>Благословенный сказал:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Верно, Махамати! Но нигилистом становится и тот, кто считает, будто Будды и шраваки утратили реально существовавшие омрачения. Почему? Потому что омрачения не обнаруживаются ни внутри, ни снаружи — они бестелесны. Будды и шраваки по природе своей освобождены, ибо в них нет ни уз, ни причин для уз. Тот, кто утверждает наличие уз [в них], — также заблуждается.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Именно исходя из этого Мною было сказано:</li>
        <li>«Лучше придерживаться воззрения о личности (<em>pudgaladṛṣṭi</em>)<a href="#citation-357" id="ref-357" class="citation-mark"><sup>357</sup></a> величиной с гору Сумеру, чем впадать в нигилистическое воззрение о пустоте<a href="#citation-358" id="ref-358" class="citation-mark"><sup>358</sup></a>, присущее тому, кто горделиво отрицает бытие и небытие».</li>
    </ul>

    <ul class="list-none mb-12 pl-2 space-y-1 ml-2">
        <li>Тот, кто горделиво отрицает бытие и небытие, — нигилист. Он запутался в воззрениях о собственных и общих признаках вещей, не признавая, что всё есть лишь воспринимаемое собственным умом. Не признавая этого и видя во внешних объектах нечто вечное, он отрицает, что <em>скандхи</em>, <em>дхату</em> и <em>аятаны</em> распадаются в мгновенной преемственности, воображая их лишёнными мысленных построений и букв<a href="#citation-359" id="ref-359" class="citation-mark"><sup>359</sup></a> — и тем самым вновь становится нигилистом.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>9. «Есть» и «нет» — это две крайности,</li>
        <li>существующие лишь до тех пор,</li>
        <li>пока длится сфера восприятия ума.</li>
        <li>Когда же сфера восприятия пресекается,</li>
        <li>различающий ум<a href="#citation-360" id="ref-360" class="citation-mark"><sup>360</sup></a> утихает.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>10. Когда ум не цепляется за объекты,</li>
        <li>нет ни прекращения, ни небытия.</li>
        <li>Существует основа Таковости (<em>tathatā-vastu</em>),</li>
        <li>являющаяся сферой [постижения] Благородных.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>11. Кто говорит, что рождается то, чего не было,</li>
        <li>и гибнет то, что было, —</li>
        <li>кто через причины мыслит «есть» и «нет», —</li>
        <li>тот не пребывает в Моём учении.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>12. Ни тиртхиками, ни Буддами, ни Мною, ни кем-либо иным</li>
        <li>бытие не устанавливается через причины.</li>
        <li>Если бытие [как неизменную сущность] невозможно установить,</li>
        <li>как же тогда может возникнуть небытие?</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>13. Если причинами не установлено бытие,</li>
        <li>то чьё небытие мы обсуждаем?</li>
        <li>Из-за ложного воззрения об [учении о] возникновении</li>
        <li>люди различают «есть» и «нет».</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>14. У того, для кого ничто не возникает</li>
        <li>и ничто не прекращается,—</li>
        <li>у того не появляется [мысли] «есть» или «нет»,</li>
        <li>ибо он зрит мир как свободный от [подобных различений].</li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>


<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.8 (Признаки метода высшей истины)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>Затем бодхисаттва-махасаттва Махамати вновь обратился к Благословенному:</p>
    <p>— Пусть Благословенный наставит меня! Пусть Сугата, Татхагата, Архат, Совершенно Пробуждённый, лучший из говорящих, наставит меня в признаках метода высшей истины (<em>siddhānta-naya-lakṣaṇa</em>). Благодаря ясному различению, пронизывающему [ум] (<em>suprativibhāgaviddhena</em>), я и другие бодхисаттвы достигнем глубины высшей истины и быстро обретём непревзойдённое пробуждение, став независимыми от любых логиков и тиртхиков.</p>

    <p>Благословенный ответил:</p>
    <p>— Слушай же внимательно, Махамати, и запечатлей это в уме! Я скажу тебе.</p>

    <p>— Да, Благословенный, — ответил бодхисаттва-махасаттва Махамати.</p>

    <p>Благословенный сказал:</p>

    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Существует два вида метода для всех шраваков, пратьекабудд и бодхисаттв: метод высшей истины (<em>siddhānta-naya</em>) и метод наставления (<em>deśanā-naya</em>).<a href="#citation-361" id="ref-361" class="citation-mark"><sup>361</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Что есть метод высшей истины? Махамати, это признак особого личного постижения (<em>pratyātma-adhigama</em>). Он свободен от речевых различений и букв, он вводит в сферу непорочного состояния (<em>anāsrava-dhātu</em>). Это признак собственного вхождения в личную глубину и ступени [бодхисаттвы], он свободен от всех рассуждений (<em>tarka</em>), тиртхиков и Мары. Лишь сокрушив тиртхиков и Мару, сияет личный путь. Таков признак метода высшей истины.</li>
    </ul>

    <ul class="list-none mb-12 pl-2 space-y-1 ml-2">
        <li>Что есть метод наставления? Это многообразное наставление в девятичастном Учении,<a href="#citation-362" id="ref-362" class="citation-mark"><sup>362</sup></a> свободное от крайностей тождества и отличия, бытия и небытия. С помощью искусных средств (<em>upāya-kuśala</em>) оно вводит существ в видение [истины]. Смотря по тому, к чему существо расположено с верой (<em>adhimucyate</em>), — то пусть ему и проповедует [учитель]. Таков признак метода наставления. Так тебе и другим бодхисаттвам следует практиковать.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>15. Те, кто знают различие между высшей истиной (<em>siddhānta</em>),</li>
        <li>методом (<em>naya</em>) и учением личного постижения (<em>pratyātmaśāsana</em>),</li>
        <li>не попадают под власть рассуждений (<em>tarka</em>).</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>16. Бытие не существует так, как его воображают невежды.</li>
        <li>Почему логики не желают освобождения через небытие?</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>17. Те, кто зрят сотворённое (<em>saṃskṛta</em>)</li>
        <li>как связанное с возникновением и распадом,</li>
        <li>лишь питают две крайние [двойственности],</li>
        <li>не видя истины из-за своего извращённого [восприятия].</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>18. Есть лишь одна Истина — Нирвана,</li>
        <li>свободная от <em>манаса</em> (<em>manavarjitam</em>).</li>
        <li>Следует зреть воображённый мир подобным магии или</li>
        <li>стволу бананового дерева (<em>kadalīskandha</em>)<a href="#citation-363" id="ref-363" class="citation-mark"><sup>363</sup></a> — пустому внутри.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>19. Нет ни страсти, ни гнева, ни неведения, ни личности.</li>
        <li><em>Скандхи</em>, возникшие из жажды, существуют,</li>
        <li>но подобно сновидениям.</li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>

<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.9 (Признаки ложного воображения)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>Затем бодхисаттва-махасаттва Махамати вновь обратился к Благословенному:</p>
    <p>— Пусть Благословенный, пусть Сугата наставит меня в признаках ложного воображения (<em>abhūta-parikalpa</em>).<a href="#citation-364" id="ref-364" class="citation-mark"><sup>364</sup></a> Как, что, посредством чего и чьё, о Благословенный, это ложное воображение приходит в движение? «Ложное воображение, ложное воображение» — так говорится, Благословенный. Для какой реальности «ложное воображение» является обозначением? И что именно различая, [ум] впадает в ложное воображение?</p>

    <p>Благословенный ответил:</p>
    <p>— Хорошо, хорошо, Махамати! Истинно хорошо, что ты считаешь этот смысл достойным вопроса. Ты действуешь ради блага многих, ради счастья многих, из сострадания к миру, ради пользы и счастья богов и людей. Слушай же внимательно, Махамати, и запечатлей это в уме! Я скажу тебе.</p>

    <p>— Да, Благословенный, — ответил бодхисаттва-махасаттва Махамати.</p>

    <p>Благословенный сказал ему:</p>

    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Различение (<em>vikalpa</em>), Махамати, приходит в движение из-за привязанности к ложному воображению пёстрого многообразия объектов.<a href="#citation-365" id="ref-365" class="citation-mark"><sup>365</sup></a> У людей, привязанных к разделению на «схватываемое» и «схватывающего», чьи умы не утверждены в осознании того, что всё есть лишь воспринимаемое собственным умом, и кто пал в крайности воззрений о бытии и небытии, — у них развёртывается совокупность сознания и психических факторов (<em>cittacaittakalāpaḥ</em>), именуемая «различением». Это происходит из-за подпитки отпечатками (<em>vāsanā</em>) ложных взглядов тиртхиков, из-за привязанности к восприятию внешних многообразных объектов, из-за привязанности к многообразным явлениям как существующим или несуществующим,<a href="#citation-366" id="ref-366" class="citation-mark"><sup>366</sup></a> а также из-за привязанности к «я» и «моему».</li>
    </ul>
    </blockquote>

    <p>Махамати спросил:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Но если различение у людей развёртывается из-за привязанности к ложному многообразию объектов, из-за падения в крайности «есть» и «нет», из-за подпитки ложными взглядами тиртхиков о субъекте и объекте и из-за непостижения того, что всё — лишь воспринимаемое собственным умом, — то послушай, Благословенный:</li>
        <li>Подобно тому, как внешние объекты с их многообразными признаками свободны от бытия и небытия и лишены [объективных] признаков воззрения — точно так же и Высшая Истина (<em>paramārtha</em>) должна быть свободна от признаков первичных частиц (<em>paramāṇu</em>), органов чувств, частей, примеров и причин. Почему же тогда в одном случае различение развёртывается, воображая многообразие ложных объектов, но не развёртывается в другом случае, воображая признаки Высшей Истины? Не следует ли из Твоих слов, Благословенный, учение о порочной причине (<em>viṣama-hetu-vāda</em>),<a href="#citation-367" id="ref-367" class="citation-mark"><sup>367</sup></a> раз Ты говоришь, что в одном случае различение действует, а в другом — нет? Ведь привязанность к опоре на «есть» и «нет» и развёртывание ложного различения подобны многообразию форм магической куклы, которая [в реальности] обладает лишь одной природой. Разве Ты не впадаешь в воззрение локаятиков (<em>lokāyatika / cārvāka</em>),<a href="#citation-368" id="ref-368" class="citation-mark"><sup>368</sup></a> когда говоришь о прекращении различения признаков многообразия бытия и небытия?</li>
    </ul>
    </blockquote>

    <p>Благословенный ответил:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-12 pl-2 space-y-1 ml-2">
        <li>Махамати, различение на самом деле не приходит в движение и не прекращается. Почему? Потому что при осознании того, что всё есть лишь Только-сознание, и при отсутствии внешних видимых объектов, не существует ни бытия, ни небытия самого различения.</li>
        <li>У невежд же оно воображается как многообразие различений собственного ума.<a href="#citation-369" id="ref-369" class="citation-mark"><sup>369</sup></a></li>
        <li>Я говорю, что различение, предваряемое активностью (<em>kriyāpravṛttipūrvakaḥ</em>),<a href="#citation-370" id="ref-370" class="citation-mark"><sup>370</sup></a> возникает из-за привязанности к признакам многообразия бытия.</li>
        <li>Но как иначе, Махамати, обычные люди, осознав, что их различение — лишь Только-сознание, отбросив взгляды на «я» и «моё», освободившись от пороков [веры] в причинно-следственные связи и совершив поворот основы (<em>parāvṛtta-cittāśraya</em>), — как иначе они могли бы обучиться на всех ступенях (<em>bhūmi</em>) и достичь сферы личного постижения Татхагаты, где прекращаются воззрения и различения, направленные на пять <em>дхарм</em>, три <em>природы</em> и объекты?</li>
        <li>Именно по этой причине, Махамати, Мною сказано:</li>
        <li>Различение развёртывается из привязанности к многообразию ложных объектов; но через постижение истинной природы (<em>yathābhūta</em>) объектов как многообразия собственного различения приходят к освобождению.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>20. Те, для кого мир развёртывается через</li>
        <li>причины (<em>kāraṇa</em>)  и условия (<em>pratyaya</em>),</li>
        <li>и кто связан четырьмя крайностями (<em>catuṣkoṭika</em>), —</li>
        <li>те не сведущи в Моём методе (<em>mannaya</em>).</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>21. Мир не рождается ни как несуществующий,</li>
        <li>ни как существующий,</li>
        <li>ни как одновременно существующий и несуществующий,</li>
        <li>[ни как ни существующий и ни несуществующий].</li>
        <li>Как же невежды измышляют его через причины и условия?</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>22. Когда мир зрят ни как существующий,</li>
        <li>ни как несуществующий,</li>
        <li>ни как существующий-и-несуществующий [одновременно],</li>
        <li>тогда ум поворачивается вспять (<em>vyāvartate cittam</em>)</li>
        <li>и постигается отсутствие «я» (<em>nairātmya</em>).</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>23. Все явления не рождены (<em>anutpanna</em>),</li>
        <li>поскольку возникают лишь в силу условий.</li>
        <li>Ибо все условия сами являются следствием иных причин,</li>
        <li>но из следствия бытие (<em>bhava</em>) не рождается.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>24. Одно следствие не рождает другое следствие —</li>
        <li>иначе возникла бы двойственность в следствии.</li>
        <li>Но даже при допущении этой двойственности</li>
        <li>отсутствие следствия не обнаруживается.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>25. Когда созерцают обусловленное (<em>saṃskṛta</em>) как свободное</li>
        <li>от опоры (<em>ālamba</em>, объекта) и опирающегося (<em>ālambya</em>, субъекта),</li>
        <li>то любой образ (<em>nimitta</em>) — это лишь «только-ум».</li>
        <li>Такой «только-ум» Я и провозглашаю.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>26. «Только» (<em>mātra</em>) — это пребывание </li>
        <li>в собственной природе (<em>svabhāva-saṃsthāna</em>),</li>
        <li>свободной от внешних условий и бытия.</li>
        <li>Это — конечное состояние, наивысшее;</li>
        <li>это Я называю «только» (<em>mātra</em>).</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>27. «Я» (<em>ātman</em>) существует лишь как условное обозначение (<em>prajñapti</em>),</li>
        <li>но не как нечто реально существующее (<em>dravya</em>).</li>
        <li>Подобно этому и <em>скандхи</em> суть «скандхи»</li>
        <li>лишь по наименованию, но не по своей сути (<em>dravya</em>).</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>28. Существует четыре вида равенства (<em>samatā</em>):</li>
        <li>равенство признаков, равенство причин,</li>
        <li>равенство миров-вместилищ и четвёртое —</li>
        <li>равенство в отсутствии «я» — для практикующих йогу.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>29. Отбрасывание всех воззрений,</li>
        <li>свобода от воображаемого и воображающего,</li>
        <li>не-обнаружение [объектов] и не-возникновение —</li>
        <li>это Я называю «только-ум».</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>30. Ни бытие, ни небытие, свободное от бытия и небытия, —</li>
        <li>Таковость, свободная [даже] от [идеи] ума, —</li>
        <li>это Я называю «только-ум».</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>31. Таковость (<em>tathatā</em>), <em>шуньята</em> (<em>śūnyatā</em>),</li>
        <li><em>Предел истинности</em> (<em>koṭi</em>), нирвана, <em>дхармадхату</em>,</li>
        <li>тело, созданное умом (<em>manomaya-kāya</em>), и само сознание —</li>
        <li>всё это Я называю «только-ум».</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>32. Связанный отпечатками различений (<em>vikalpavāsanā</em>),</li>
        <li>многообразие, возникающее из ума,</li>
        <li>являющийся людям как внешнее —</li>
        <li>таков мирской «только-ум».</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>33. Внешних видимых объектов не существует —</li>
        <li>видится лишь пёстрота ума.</li>
        <li>Тело, объекты наслаждения и опора-обитель —</li>
        <li>всё это Я называю «только-ум».<a href="#citation-371" id="ref-371" class="citation-mark"><sup>371</sup></a></li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>

<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.10 (Произнесённое и смысл)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>Затем Бодхисаттва-махасаттва Махамати вновь обратился к Благословенному:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>О Благословенный, Тобой было сказано:</li>
        <li>«Бодхисаттве-махасаттве и другим не следует понимать сказанное буквально».</li>
        <li>Как же, Благословенный, бодхисаттва становится тем, кто не понимает сказанное буквально?</li>
        <li>Что есть произнесённое (<em>ruta</em>) и что есть смысл (<em>artha</em>)?</li>
    </ul>
    </blockquote>

    <p>Благословенный ответил:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Слушай же внимательно, Махамати, — и не запечатлевай [буквально] в уме!</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Что есть произнесённое (<em>ruta</em>)?</li>
        <li>Это различение, возникающее из сцепления речи и знаков;</li>
        <li>это взаимный обмен речью, использующий зубы, челюсти, нёбо, язык, губы и ротовую полость,</li>
        <li>чьей причиной являются отпечатки (<em>vāsanā</em>) различений.</li>
        <li>Это именуется произнесённым.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Что же, Махамати, есть смысл (<em>artha</em>)?</li>
        <li>Это путь, ведущий в «город нирваны»,</li>
        <li>по которому идут в одиночестве и тайне,</li>
        <li>обладая мудростью, сотканной из слушания, размышления и созерцания.</li>
        <li>Он предваряется поворотом основы (<em>āśraya-parāvṛtti</em>) отпечатков.</li>
        <li>Исследуя признаки этого особого смысла,</li>
        <li>[пребывая] в сфере личного постижения на различных ступенях (<em>bhūmi</em>),</li>
        <li>бодхисаттва-махасаттва становится искусным в смысле.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Кроме того, Махамати, бодхисаттва-махасаттва, искусный в произнесённом и смысле, зрит, что произнесённое и смысл — не иное и не не-иное. Ведь если бы, Махамати, смысл был полностью иным по отношению к произнесённому, он мог бы являться и без него. Но этот смысл постигается именно посредством произнесённого — подобно тому как сокровище [видится] благодаря светильнику.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Представь, Махамати: некий человек, взяв светильник, осматривает свои сокровища [и говорит]: «Вот моё сокровище, оно такого рода и находится в этом месте».</li>
        <li>Точно так же, Махамати, посредством светильника произнесённого, порождённого речевым различением, бодхисаттвы-махасаттвы входят в сферу личного благородного постижения, которая сама по себе свободна от любых речевых различений.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Кроме того, Махамати, такие учения, как:</li>
        <li>«дхармы не прекращаются и не возникают»,</li>
        <li>«они по природе своей пребывают в нирване»,</li>
        <li>«[учение о] трёх колесницах и единой колеснице»,</li>
        <li>а также [учения о] пяти [<em>дхармах</em>] и [трёх] <em>природах сознания</em> (<em>citta-svabhāva</em>) —</li>
        <li>если привязываться к ним, понимая буквально,</li>
        <li>то из-за такой привязанности впадают в крайности наложения (<em>samāropa</em>) или отрицания (<em>apavāda</em>).</li>
    </ul>

    <ul class="list-none mb-12 pl-2 space-y-1 ml-2">
        <li>Это подобно тому, как [невежды] воображают иначе то, что уже само по себе установлено иначе [чем есть]: магическое многообразие следует видеть таким, какое оно есть,</li>
        <li>но невежды воображают его иначе — в отличие от Благородных.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>34. Вообразив [вещи] буквально, невежды</li>
        <li>накладывают [свои представления] на природу реальности.</li>
        <li>Из-за этого наложения они падают в обитель ада.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>35. В <em>скандхах</em> не обнаруживается «я»,</li>
        <li>и в «я» нет никаких <em>скандх</em>.</li>
        <li>Они не таковы, какими их воображают,</li>
        <li>но нельзя сказать и то, что их вовсе нет.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>36. Если бы бытие всех явлений было именно таким,</li>
        <li>каким его воображают невежды —</li>
        <li>то есть если бы явления были таковы, какими видятся, —</li>
        <li>то все существа были бы зрячими в Истине.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>37. Из-за отсутствия [собственной природы]</li>
        <li>у всех явлений нет загрязнения;</li>
        <li>из-за того же — нет и очищения.</li>
        <li>Они не таковы, какими видятся,</li>
        <li>но нельзя сказать и то, что их вовсе нет.</li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>


<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.11 (Признаки различения между мудростью и сознанием)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Кроме того, Махамати, Я разъясню тебе признаки различения между мудростью и сознанием (<em>jñāna-vijñāna-lakṣaṇa</em>). Благодаря ясному постижению этих признаков ты и другие бодхисаттвы быстро обретёте непревзойдённое пробуждение.</li>
        <li>Махамати, существует три вида мудрости: мирская (<em>laukika</em>), надмирская (<em>lokottara</em>) и высшая надмирская (<em>lokottaratama</em>).</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>[Знай же различие]:</li>
        <li>Сознание (<em>vijñāna</em>) — это то, что возникает и распадается. Мудрость (<em>jñāna</em>) — это то, что не возникает и не распадается.</li>
        <li>Сознание — павшее в [область] признаков и их отсутствия (<em>nimitta-animitta</em>); его причиной является многообразие «есть» и «нет». Мудрость же по своей природе выходит за пределы признаков.</li>
        <li>Сознание обладает признаком накопления (<em>upacaya</em>). Мудрость обладает признаком убывания (<em>apacaya</em>).</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Мудрость в целом проявляется трояко:</li>
        <li>— как постижение собственных и общих признаков (<em>svalakṣaṇa-sāmānyalakṣaṇa</em>),</li>
        <li>— как постижение возникновения и исчезновения,</li>
        <li>— и как постижение не-возникновения и не-прекращения.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>• Мирская мудрость принадлежит тиртхикам и невеждам, привязанным к крайностям бытия и небытия.</li>
        <li>• Надмирская мудрость принадлежит шравакам и пратьекабуддам, которые всё ещё привязаны к [анализу] собственных и общих признаков.</li>
        <li>• Высшая надмирская мудрость принадлежит Буддам и бодхисаттвам. Она развёртывается через исследование дхарм в состоянии без-образности (<em>nirābhāsa</em>), через видение не-прекращения и не-возникновения, через выход за пределы «есть» и «нет» и через обретение отсутствия «я» на ступени Татхагаты.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Кроме того, Махамати, мудрость (<em>jñāna</em>) обладает признаком отсутствия привязанности (<em>asaṅga</em>), тогда как сознание (<em>vijñāna</em>) обладает признаком привязанности к многообразию объектов.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Кроме того, Махамати, сознание обладает признаком связи с возникновением и уничтожением трёх привязанностей,<a href="#citation-372" id="ref-372" class="citation-mark"><sup>372</sup></a> тогда как мудрость по своей природе свободна от привязанностей.</li>
    </ul>

    <ul class="list-none mb-12 pl-2 space-y-1 ml-2">
        <li>Кроме того, Махамати, мудрость обладает признаком недостижимости (<em>aprāpti</em>),<a href="#citation-373" id="ref-373" class="citation-mark"><sup>373</sup></a> являясь сферой личного благородного постижения; она подобна отражению луны в воде: в неё нельзя войти и из неё нельзя выйти.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>38. Умом (<em>citta</em>) накапливается карма;</li>
        <li>познанием (<em>jñāna</em>) она устанавливается;</li>
        <li>мудростью (<em>prajñā</em>) же достигается</li>
        <li>состояние без-образности (<em>nirābhāsa</em>) и сияние.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>39. Ум связан с объектом;</li>
        <li>познание проявляется в рассуждении;</li>
        <li>мудрость же возникает в особом состоянии,</li>
        <li>лишённом ментальных образов.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>40. Ум, манас и сознание по природе своей</li>
        <li>не содержат ни восприятия, ни различения —</li>
        <li>и всё же шраваки приписывают самим дхармам</li>
        <li>природу различения, не видя этой изначальной чистоты.</li>
        <li>Не таковы Сыны Победителей.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>41. В умиротворении особого терпения-принятия (<em>kṣāntiviśeṣa</em>)</li>
        <li>рождается благая Мудрость Татхагаты.</li>
        <li>Она постигает особый смысл,</li>
        <li>будучи свободной от всякой двойственной активности.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>42. Моя мудрость трояка;</li>
        <li>[в высшем своём проявлении] благодаря ней сияют Благородные.</li>
        <li>Но в низших проявлениях через неё воображаются</li>
        <li>признаки и скрывается истинная природа вещей. </li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>43. Мудрость, свободная от двух колесниц</li>
        <li>и от небытия, — такова [подлинная].</li>
        <li>Но у шраваков мудрость развёртывается</li>
        <li>через привязанность к реальному бытию.</li>
        <li>Мудрость же Татхагаты постигается</li>
        <li>через вхождение в [реальность] Только-сознания.<a href="#citation-374" id="ref-374" class="citation-mark"><sup>374</sup></a></li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>


<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.12 (Воззрения о превращениях)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">

    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Кроме того, Махамати, у тиртхиков существует девять видов воззрений, основанных на идее превращения (<em>pariṇāma</em>).<a href="#citation-375" id="ref-375" class="citation-mark"><sup>375</sup></a> Это:</li>
        <li>• Превращение взаиморасположения (<em>saṃsthāna-pariṇāma</em>);</li>
        <li>• Превращение признака (<em>lakṣaṇa-pariṇāma</em>);</li>
        <li>• Превращение причины (<em>hetu-pariṇāma</em>);</li>
        <li>• Превращение логического обоснования (<em>yukti-pariṇāma</em>);</li>
        <li>• Превращение воззрения (<em>dṛṣṭi-pariṇāma</em>);</li>
        <li>• Превращение возникновения (<em>utpāda-pariṇāma</em>);</li>
        <li>• Превращение бытия (<em>bhāva-pariṇāma</em>);</li>
        <li>• Превращение проявления через условия (<em>pratyayābhivyakti-pariṇāma</em>);</li>
        <li>• Превращение проявления через действие (<em>kriyābhivyakti-pariṇāma</em>).</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Опираясь на эти девять воззрений, Махамати, все тиртхики утверждают, что явления возникают и преобразуются в рамках крайностей бытия и небытия.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Махамати, что касается превращения взаиморасположения (<em>saṃsthāna-pariṇāma</em>), то это — воображение иного состояния взаиморасположения, подобно тому как золото кажется превращённым в браслеты (<em>kaṭaka</em>), ожерелья (<em>rucaka</em>), знаки свастики (<em>svastika</em>) и прочие формы.</li>
        <li>Представь, Махамати: хотя золото предстаёт в этих разнообразных формах, само золото по своей сути не претерпевает превращения.<a href="#citation-376" id="ref-376" class="citation-mark"><sup>376</sup></a></li>
        <li>Точно так же, Махамати, превращение всех вещей воображается тиртхиками и другими на основе причинно-следственной связи. Но вещи не таковы [как они воображают], и они не становятся иными, опираясь на воображение. Весь спектр превращений — таких как молоко, простокваша, вино и созревание плодов — следует воспринимать подобным образом.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Хотя тиртхики воображают превращение каждого из них как реальное изменение, на самом деле ничто не превращается — ввиду отсутствия внешних объектов как существующих или несуществующих, поскольку всё есть лишь воспринимаемое собственным умом.</li>
    </ul>

    <ul class="list-none mb-12 pl-2 space-y-1 ml-2">
        <li>Знай же, Махамати: так развёртывается воображение собственного ума у невежд. Здесь нет ни одной дхармы, которая приходила бы в движение или прекращалась. Это подобно видению образов во сне или в магической иллюзии. Поистине, Махамати, [всё это лишь] кажимость возникновения и исчезновения, подобная рождению сына у бесплодной женщины или рождению мёртвого.<a href="#citation-377" id="ref-377" class="citation-mark"><sup>377</sup></a></li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>44. Те, кто воображают превращение,</li>
        <li>время, взаиморасположение, первоэлементы,</li>
        <li>объекты и органы чувств, а также</li>
        <li>промежуточное состояние (<em>antarābhava</em>) как реальные, —</li>
        <li>те не являются мудрыми.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>45. Победители (Будды) не воображают мир</li>
        <li>как нечто реально возникшее в зависимости от условий.</li>
        <li>Напротив, они зрят этот мир лишь как условия (<em>pratyaya</em>),</li>
        <li>подобный городу гандхарвов (миражу).</li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>

<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.13 (Узлы)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>Затем бодхисаттва-махасаттва Махамати вновь обратился к Благословенному:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>— Пусть Благословенный, Татхагата, Архат, Совершенно Пробуждённый наставит меня в том, как ум завязывает узлы,<a href="#citation-378" id="ref-378" class="citation-mark"><sup>378</sup></a> цепляясь за смысл дхарм, — и как эти узлы распутываются. Благодаря ясному постижению этого я и другие бодхисаттвы станем искусными в распутывании узлов и не попадём в ловушку буквального понимания.</li>
        <li>Сокрушив мудростью различение речи и знаков, мы сможем посещать собрания во всех землях будд, обладая <em>силами</em>, <em>сверхзнаниями</em>, <em>властью</em>, <em>дхарани</em> и <em>мудрами</em>, испуская разнообразные лучи чудесных проявлений, с умом, прочно утверждённым на десяти ступенях, подобные в своём спонтанном действии луне, солнцу, драгоценному камню и великим элементам; на всех ступенях — со взглядами, свободными от признаков собственного различения, видя все дхармы как сновидение и магию, — и уже войдя в основу ступени Будды.</li>
        <li>Тогда, наставляя каждого согласно его достоинству и уровню, мы утвердим всех в том, что все дхармы — как сновидение, как магия — свободны от крайностей «есть» и «нет», лишены воображения возникновения и прекращения и опираются лишь на условную природу речи, а не на реальность звуков.</li>
    </ul>
    </blockquote>

    <p>Благословенный ответил:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Хорошо, Махамати! Слушай же внимательно.</li>
        <li>Махамати, бесчисленны узлы привязанности (<em>abhiniveśa-saṃdhi</em>). Это:</li>
        <li>• Узел привязанности к буквальному смыслу (<em>yathāruta-artha</em>);</li>
        <li>• Узел привязанности к признакам (<em>lakṣaṇa</em>);</li>
        <li>• Узел привязанности к условиям (<em>pratyaya</em>);</li>
        <li>• Узел привязанности к бытию и небытию (<em>bhāva-abhāva</em>);</li>
        <li>• Узел различения возникновения и не-возникновения (<em>utpāda-anutpāda</em>);</li>
        <li>• Узел различения прекращения и не-прекращения (<em>nirodha-anirodha</em>);</li>
        <li>• Узел различения высшей и низших колесниц (<em>yāna-ayāna</em>);</li>
        <li>• Узел различения обусловленного и необусловленного (<em>saṃskṛta-asaṃskṛta</em>);</li>
        <li>• Узел различения ступеней и их отсутствия (<em>bhūmi-abhūmi</em>);</li>
        <li>• Узел воображаемого собственного постижения (<em>svavikalpa-abhisamaya</em>);</li>
        <li>• Узел различения основ тиртхиков — «есть» и «нет» (<em>sadasat-pakṣa-tīrthya-āśraya</em>);</li>
        <li>• Узел различения постижения Трёх колесниц или Единой колесницы (<em>triyāna-ekayāna-abhisamaya</em>).</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Эти и иные узлы, Махамати, — это узлы собственного различения невежд. Связывая себя ими, невежды, подобно шелковичным червям, опутывают себя и других нитью узлов собственных взглядов, находя удовольствие в этой самой нити.<a href="#citation-379" id="ref-379" class="citation-mark"><sup>379</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Но на самом деле, Махамати, нет ни узлов, ни признаков связывания, ибо все дхармы воспринимаются как свободные (<em>vivikta</em>). Прекратив развёртывание различений, бодхисаттва пребывает в созерцании этой изначальной свободы всех дхарм.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Кроме того, Махамати, благодаря постижению того, что внешнее бытие и небытие — лишь признаки, воспринимаемые собственным умом (<em>svacitta-dṛśya</em>); благодаря следованию состоянию без-образности (<em>nirābhāsa</em>) и Только-сознания; и благодаря видению того, что все явления свободны от уз различения бытия и небытия, — обнаруживается, что у дхарм нет ни узла, ни признака развязывания.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Здесь, Махамати, никто не связывается и никто не освобождается.</li>
        <li>Связывание и освобождение существуют лишь для ума, впавшего в заблуждение.</li>
        <li>Почему это так?</li>
        <li>Потому что при исследовании дхарм не обнаруживается (<em>anupalabdhi</em>) никакого связывания бытия и небытия.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Кроме того, Махамати, у невежд и обычных людей есть три узла: привязанность, отвращение и заблуждение. Также есть жажда к новому рождению (<em>tṛṣṇā paunarbhavikī</em>), сопровождаемая наслаждением и привязанностью; именно связываясь с ней, возникают узлы путей перерождения.</li>
        <li>Махамати, из-за этого непрерывного связывания существа вращаются в пяти путях. Но когда эта связь пресекается, более не обнаруживается ни признака связывания, ни признака развязывания.</li>
    </ul>

    <ul class="list-none mb-12 pl-2 space-y-1 ml-2">
        <li>Кроме того, Махамати, узел возникает из-за привязанности к действию, обусловленному тройным соединением (объекта, органа чувств и сознания). Из-за непрерывности потоков сознания и привязанности к их движению возникает узел бытия (<em>bhava-saṃdhi</em>).</li>
        <li>Однако благодаря отстранению от тройного соединения и созерцанию трёх видов освобождения,<a href="#citation-380" id="ref-380" class="citation-mark"><sup>380</sup></a> никакие узлы более не завязываются.</li>
    </ul>
        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>46. Истинно, ложное воображение (<em>abhūta-parikalpa</em>)</li>
        <li>именуется признаком связывания (<em>saṃdhi-lakṣaṇa</em>).</li>
        <li>Благодаря полному постижению его подлинной природы,</li>
        <li>сеть узлов (<em>saṃdhi-jāla</em>) проясняется.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>47. Подобно шелковичным червям, невежды,</li>
        <li>не ведающие о [природе] узлов, опутывают</li>
        <li>сами себя нитями собственных различений —</li>
        <li>из-за захвата бытия (<em>bhāva</em>), познания (<em>jñāna</em>) и речи (<em>ruta</em>).<a href="#citation-381" id="ref-381" class="citation-mark"><sup>381</sup></a></li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>


<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.14 (14. О природе воображаемого)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>Махамати вновь спросил:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Благословенный, Тобой было сказано: «Через какие бы различения ни воображались те или иные объекты — в них нет собственной природы (<em>svabhāva</em>). Это лишь воображаемое (<em>parikalpita</em>)».</li>
        <li>Но если это так, Благословенный, и всё вокруг — лишь воображаемое, а не точное определение собственной природы явлений через признаки, то не следует ли из Твоих слов, что загрязнение  (<em>saṃkleśa</em>) и очищение (<em>vyavadāna</em>) отсутствуют? Ведь [получается], что все дхармы лишь сотканы из воображаемой природы.</li>
    </ul>
    </blockquote>

    <p>Благословенный ответил:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Это именно так, Махамати, как ты говоришь. Но природа явлений не такова, какой её воображают невежды и обычные люди. Это действительно лишь воображаемое, Махамати, а не точное определение собственной природы явлений через признаки.</li>
        <li>Однако, Махамати, природа явлений такова, какой её постигают Благородные (<em>ārya</em>) — через благородное знание, благородное видение и око мудрости (<em>prajñā-cakṣus</em>).<a href="#citation-382" id="ref-382" class="citation-mark"><sup>382</sup></a></li>
    </ul>
    </blockquote>

    <p>Махамати сказал:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Но если, Благословенный, природа явлений такова, какой её постигают Благородные своим знанием, видением и оком мудрости (не плотским и не божественным оком), и она вовсе не такова, какой её воображают обычные люди, — то как же, Благословенный, произойдёт поворот (прекращение) различения (<em>vikalpa-vyāvṛtti</em>) у этих людей, если они не постигают реальность, как она пребывает в состоянии Благородного?</li>
        <li>Ведь они, Благословенный, не находятся ни в заблуждении, ни вне его (ни в извращённом, ни в не-извращённом восприятии). Почему? Потому что они не постигают природу реальности Благородных, видя лишь развёртывание признаков бытия и небытия.</li>
        <li>Более того, Благословенный, если бы и Благородные воображали объект, он не был бы таким [как они воображают], ибо собственные признаки недоступны сфере восприятия. Таким образом, и для них природа объектов казалась бы лишь воображаемой природой (<em>parikalpita-svabhāva</em>), из-за обозначения причин и не-причин.</li>
        <li>Так возникает бесконечный регресс (<em>anavasthā</em>) из-за непостижения природы объектов. Ведь воображаемая природа не является причиной истинной природы явлений.</li>
        <li>Как же воображаемое может быть не таким, каким оно воображается? Ведь признак воображения — это одно, а признак собственной природы — совершенно другое. Эти два признака — воображения и природы — имеют совершенно разные причины.</li>
        <li>И если обычные люди воображают их, они [всё равно] не будут такими [как реальность].</li>
        <li>Или же это [Твоё] утверждение делается лишь ради того, чтобы повернуть вспять различение существ, говоря им: «Всё не таково, каким оно воображается в различении»?<a href="#citation-383" id="ref-383" class="citation-mark"><sup>383</sup></a></li>
        <li>Что же это, Благословенный? Устраняя у существ воззрение о бытии и небытии, не насаждаешь ли Ты вновь воззрение о бытии, заставляя их цепляться за объект, который является сферой благородного знания? И не уничтожаешь ли Ты тем самым наставление о свободной природе дхарм, указывая на природу объекта благородного знания?</li>
    </ul>
    </blockquote>

    <p>Благословенный ответил:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Махамати, Я не уничтожаю наставление о свободной природе дхарм и не насаждаю воззрение о бытии, разъясняя природу объекта Благородных.</li>
        <li>Напротив, Махамати, ради устранения почвы для страха — у тех существ, что с безначальных времён привязаны к признакам существования явлений, — Я даю наставление о свободной природе дхарм через воззрение, связанное с привязанностью к природе объекта благородного знания.<a href="#citation-384" id="ref-384" class="citation-mark"><sup>384</sup></a></li>
        <li>Махамати, Я не проповедую [объективную] природу явлений. Но [Я учу так], дабы они сами стали пребывать в свободной дхарме, постигнув её истинную суть.</li>
        <li>Благodаря видению отсутствия признаков в заблуждении, они входят в [понимание] того, что всё — лишь воспринимаемое собственным умом. Оставив воззрения о внешнем бытии и небытии, они станут пребывать в свободной дхарме, постигнув истинную суть через три вида освобождения.</li>
        <li>Благodаря видению отсутствия признаков в заблуждении и запечатлев истинную суть тремя видами освобождения, они станут пребывать в непосредственном созерцании природы явлений через разум, обретший личное постижение, — свободные от воззрений о бытии и небытии.</li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>

<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.15 (15. Провозглашение не-рождённости)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">

    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Кроме того, Махамати, бодхисаттве не следует провозглашать: «Все дхармы не рождены». Почему? Потому что само это провозглашение становится носителем собственной природы и порождает цепочку причин.<a href="#citation-385" id="ref-385" class="citation-mark"><sup>385</sup></a></li>
        <li>Провозглашая и доказывая «все дхармы не рождены», бодхисаттва теряет саму эту позицию утверждения — ибо она рушится в момент её высказывания: она возникает в зависимости от своей противоположности.</li>
        <li>Если же сказать, что и сама эта позиция «не рождена» — как часть всех дхарм, — то признак не-рождённости не возникает и у неё самой, и тогда высказывание «все дхармы не рождены» снова теряется.</li>
        <li>Это утверждение — часть всех явлений, а у явлений признаки бытия и небытия не возникают. Если же через утверждение «не-рождённости» провозглашать не-рождённость всех явлений — позиция вновь рушится.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Поэтому не следует опираться на признаки бытия, небытия или не-рождённости. Само утверждение обладает признаком не-рождённой природы — и именно поэтому его не следует выдвигать.</li>
        <li>Из-за множества изъянов в звеньях рассуждения, их взаимной обусловленности и искусственности — не следует провозглашать ни «все дхармы не рождены», ни «все дхармы пусты», ни «все дхармы лишены собственной природы».</li>
    </ul>

    <ul class="list-none mb-12 pl-2 space-y-1 ml-2">
        <li>Вместо этого, Махамати, бодхисаттве следует говорить обо всех явлениях как о магии и сновидении<a href="#citation-386" id="ref-386" class="citation-mark"><sup>386</sup></a> — исходя из того, что они и видимы, и невидимы. Поскольку все дхармы ослепляют взор и разум, говорить о них следует именно так — кроме тех случаев, когда нужно уберечь невежд от страха. Ведь невежды — обычные люди, павшие в воззрения о бытии и небытии, и если они устрашатся — удалятся от Махаяны.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>48. Нет ни собственной природы (<em>svabhāva</em>), ни обозначения (<em>vijñapti</em>),</li>
        <li>нет ни объекта (<em>vastu</em>), ни <em>Алайи</em> —</li>
        <li>всё это воображается невеждами и лже-логиками, чей ум мёртв.<a href="#citation-387" id="ref-387" class="citation-mark"><sup>387</sup></a></li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>49. Утверждение «все дхармы не рождены» служит лишь</li>
        <li>для опровержения того, что признаётся всеми тиртхиками.</li>
        <li>Ибо никакие вещи не рождаются ни для кого,</li>
        <li>поскольку они всегда обусловлены.<a href="#citation-388" id="ref-388" class="citation-mark"><sup>388</sup></a></li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>50. Пусть мудрость не различает тезис «все дхармы не рождены»:</li>
        <li>ибо само это утверждение имеет причину и доказательство,</li>
        <li>и разум тех, кто его выдвигает, утрачивается.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>51. Подобно тому как люди с тимирой ложно</li>
        <li>видят пучок волос в воздухе, так и это</li>
        <li>различение вещей ложно воображается невеждами.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>52. Три мира — лишь условное обозначение (<em>prajñapti-mātra</em>);</li>
        <li>в них нет объектной реальности.</li>
        <li>Логики же воображают бытие</li>
        <li>на основе условных обозначений и объектов.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>53. Признак, объект, обозначение и даже трепетание ума (<em>mano-vispandita</em>)<a href="#citation-389" id="ref-389" class="citation-mark"><sup>389</sup></a> —</li>
        <li>преодолев всё это, Мои Сыновья (бодхисаттвы)</li>
        <li>шествуют свободными от различений.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>54. Как жажда воды там, где её нет, или мираж в небе —</li>
        <li>таково видимое для невежд,</li>
        <li>Благородные же видят его совершенно иначе.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>55. Видение Благородных чисто,</li>
        <li>оно рождается из трёх врат освобождения.</li>
        <li>Оно свободно от [двойственности] возникновения и распада и</li>
        <li>пребывает в сфере без-образности (<em>nirābhāsa</em>).</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>56. Без-образность у йогинов невозможна при простом отсутствии вещей.</li>
        <li>Плод Благородных рождается из равенства бытия и небытия —</li>
        <li>ибо как может простое отсутствие создать равенство?<a href="#citation-390" id="ref-390" class="citation-mark"><sup>390</sup></a></li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>57. Когда ум перестаёт разделять внешнее и внутреннее в их движении,</li>
        <li>наступает растворение [заблуждения] и видение равностного ума.<a href="#citation-391" id="ref-391" class="citation-mark"><sup>391</sup></a></li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>


<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.16 (16. О ложном знании)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>Махамати вновь спросил:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Благословенный, Тобой было сказано: «Когда познание (<em>jñāna</em>) не обнаруживает объект, оно утверждается в Только-проявлении (<em>vijñaptimātra</em>).<a href="#citation-392" id="ref-392" class="citation-mark"><sup>392</sup></a> Поскольку у сознания-восприятия (<em>vijñapti</em>) нет схватываемого объекта (<em>grāhya</em>), не возникает и схватывающего субъекта (<em>grāhaka</em>). Из-за этого отсутствия захвата не развёртывается познание, именуемое различением».</li>
        <li>Но что это значит? Познание не обнаруживает объект потому, что не способно постичь многообразие его признаков? Или потому, что сама природа вещей подавляет их различение? Или из-за физических преград — стен, перегородок, насыпи, земли, воды, ветра, огня, слишком большого расстояния или чрезмерной близости? Или из-за ущербности органов чувств — как у детей, слепых, глухих, стариков или йогинов?</li>
        <li>Если познание не видит объект из-за неспособности его различить — это не познание, а невежество (<em>ajñāna</em>). Если же оно не видит из-за преград или дефектов чувств — это тоже невежество: существующий объект не обнаруживается из-за скудости разума.<a href="#citation-393" id="ref-393" class="citation-mark"><sup>393</sup></a></li>
    </ul>
    </blockquote>

    <p>Благословенный ответил:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-12 pl-2 space-y-1 ml-2">
        <li>Нет, Махамати, это не невежество. Это именно познание. Когда Я говорил об этом, то имел в виду иное.</li>
        <li>Благодаря постижению того, что всё — лишь воспринимаемое собственным умом, и видению отсутствия внешнего бытия и небытия, познание более не находит объекта как чего-то внешнего. Из-за этого не-обнаружения прекращается движение «познающего» и «познаваемого». Вступив в три вида освобождения, само познание также перестаёт обнаруживаться.</li>
        <li>Логики же, чей ум пропитан безначальным разрастанием понятий (<em>prapañca</em>) о бытии и небытии, не понимают этого. Не понимая, они будут объяснять Только-сознание через простое прекращение различения внешних форм — опираясь на бытие и небытие этих форм как на основу. Привязанные к «я» и «моему», не постигая, что мир — лишь проявление собственного ума, они продолжают делить «знание» и «объект». Из-за этого деления они не находят опоры и впадают в воззрение об уничтожении.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>58. Если объект (<em>ālambya</em>) присутствует,</li>
        <li>но познание его не видит, —</li>
        <li>то это невежество (<em>ajñāna</em>), а не познание.</li>
        <li>Таков метод рассуждения логиков (<em>tārkikāṇām</em>).</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>59. Если познание не видит объект из-за отсутствия</li>
        <li>различающих признаков, из-за преград,</li>
        <li>большого расстояния или чрезмерной близости, —</li>
        <li>это именуется ложным познанием (<em>mithyā-jñāna</em>).</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>60. Если познание не возникает из-за дефектов чувств —</li>
        <li>как у слепых, глухих, стариков, детей или йогинов, —</li>
        <li>притом что объект познания присутствует, —</li>
        <li>это также именуется ложным познанием.</li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>


<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.17 (17. Методы наставления и высшей истины)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Кроме того, Махамати, невежды и обычные люди, танцующие в спектакле (<em>nāṭake nṛtyantaḥ</em>) своих собственных различений, порождённых порочностью безначальной вязкой вербальной раздутости (<em>prapañca-dauṣṭhulya</em>), — они не искусны в методе высшей истины и наставления. Привязанные к признакам внешнего бытия, которое есть лишь воспринимаемое собственным умом, они цепляются за букву вспомогательных наставлений (<em>upāya-deśanā-pāṭha</em>), но не постигают метод высшей истины, очищенный от четырёх логических крайностей.</li>
    </ul>
    </blockquote>

    <p>Махамати сказал:</p>
    <p>— Это именно так, Благословенный. Наставь же меня в признаках метода наставления и метода высшей истины, дабы я и другие бодхисаттвы в грядущие времена не были введены в заблуждение лже-логиками, тиртхиками и последователями колесниц шраваков и пратьекабудд.</p>

    <p>Благословенный ответил:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-12 pl-2 space-y-1 ml-2">
        <li>— Слушай же внимательно. У Татхагат прошлого, будущего и настоящего есть два вида метода Дхармы: метод наставления (<em>deśanā-naya</em>) и метод утверждения в высшей истине (<em>siddhānta-pratyavasthāna-naya</em>).</li>
        <li>Метод наставления в текстах — это изложение разнообразных сутр, которое даётся существам в соответствии с их склонностями и верой.</li>
        <li>Что же, Махамати, есть метод высшей истины? Это то, посредством чего йогины совершают поворот (прекращение) различения того, что видится собственным умом. Это: не падение в стороны тождества, отличия, того и другого или ни того, ни другого; выход за пределы ума, интеллекта и сознания (<em>citta-mano-vijñāna</em>); сфера личного благородного постижения, свободная от причин, доводов, воззрений и признаков. Это то, что недоступно ни лже-логикам, ни тиртхикам, ни шравакам, павшим в крайности бытия и небытия. Вот это Я называю высшей истиной (<em>siddhānta</em>). В этом методе тебе и другим бодхисаттвам следует практиковать.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>61. Мой метод двояк:</li>
        <li>высшая истина (<em>siddhānta</em>) — для йогинов,</li>
        <li>наставление (<em>deśanā</em>) — для невежд.</li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>


<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.18 (18. О локаятиках)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>Бодхисаттва-махасаттва Махамати вновь обратился к Благословенному:</p>
    <p>— О Благословенный, Тобой было сказано: «Не следует общаться, служить и почитать локаятика, блистающего разнообразными изречениями.<a href="#citation-394" id="ref-394" class="citation-mark"><sup>394</sup></a> Ибо тот, кто служит ему, обретает лишь мирские блага (<em>lokāmiṣa</em>), но не обретает Дхарму».<a href="#citation-395" id="ref-395" class="citation-mark"><sup>395</sup></a> Почему это было сказано Тобой?</p>

    <p>Благословенный ответил:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Махамати, локаятик блистает разнообразными изречениями, используя причудливые доводы, слова и знаки, дабы ослепить невежд. Его слова не ведут к истине и не приносят пользы; это лишь детский лепет. Он завлекает искусным красноречием, но сам не входит в истинный метод. Не постигнув дхармы и пав в крайности, он вводит в заблуждение других и губит себя.</li>
        <li>Из-за того, что он не освободился от уз, влекущих его по путям перерождений (<em>gatisaṃdhi</em>), из-за непостижения того, что мир — лишь воспринимаемое собственным умом, и из-за привязанности к внешней природе вещей — у него не происходит поворот различения (<em>vikalpasya vyāvṛtti</em>). Поэтому он не избавлен от рождения, старости, болезней и смерти, — хотя и ослепляет невежд своими доводами и примерами.</li>
        <li>Индра, Махамати, обладая острым умом и знанием многих шастр, составил своё учение о звуках. Его ученик в облике змея-нага, явившись в небесное собрание, заключил пари с Индрой. Состязаясь в доводах локаятиков, он победил царя богов и сокрушил его колесницу.<a href="#citation-396" id="ref-396" class="citation-mark"><sup>396</sup></a></li>
        <li>Если даже боги и асуры могут быть ослеплены разнообразными речами, привязывая [слушателей] через воззрения о прибыли и убытке, — то что говорить о людях?</li>
        <li>Поэтому, Махамати, локаятиков следует избегать, ибо они — причина страданий и новых рождений. Учение локаятиков ограничено лишь восприятием тела, разума и объектов.<a href="#citation-397" id="ref-397" class="citation-mark"><sup>397</sup></a> Локаята, Махамати, [уже насчитывает] сто тысяч [ветвей]. В грядущие же времена их свод учения распадётся, ибо он будет основан на ложных доводах и лишён истинных учеников. Тиртхики будут проповедовать локаяту в разных формах, будучи привязанными к собственным причинам, но они не знают своего истинного метода — они лишь излагают локаяту на сотни ладов, не понимая из-за заблуждения: «вот это и есть локаята».</li>
    </ul>
    </blockquote>

    <p>Махамати спросил:</p>
    <p>— Благословенный, если все тиртхики, привязанные к своим идеям, лишь излагают локаяту с помощью разнообразных изречений, слов и примеров — не проповедуешь ли и Ты, Благословенный, ту же локаяту, используя разнообразные изречения ради приходящих к Тебе из разных стран богов, асуров и людей? И не является ли Твоё собственное учение лишь частью наставлений всех тиртхиков?</p>


    <p>Благословенный ответил:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Махамати, Я не проповедую локаяту и не учу о прибыли и убытке (<em>āya-vyaya</em>).<a href="#citation-398" id="ref-398" class="citation-mark"><sup>398</sup></a> Напротив, Махамати, Я учу о том, что свободно от прибыли и убытка.</li>
        <li>«Прибыль» (<em>āya</em>), Махамати — это груда возникновений, появляющаяся из накопления. «Убыток» (<em>vyaya</em>) — это разрушение. Свобода же от прибыли и убытка — иное имя для не-возникновения (<em>anutpāda</em>).</li>
        <li>Я не учу в рамках различений, присущих тиртхикам. Почему? Потому что внешние объекты отсутствуют, и нет привязанности к ним. Благодаря утверждению в том, что всё — лишь воспринимаемое собственным умом, прекращается беспокойное суетливое движение различения (<em>vikalpasya didhāvṛttino'pravṛtti</em>).</li>
        <li>Поскольку нет сферы внешних признаков, а есть лишь осознание того, что всё воспринимаемое — проявление собственного ума, различение этих проявлений не развёртывается. Когда же различение не развёртывается, происходит вхождение в три вида освобождения — без-признаковость (<em>animitta</em>), пустоту (<em>śūnyatā</em>) и без-устремлённость (<em>apraṇihita</em>). Именно это Я называю освобождением.</li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>

<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.19 (19. Диалог с брахманом-локаятиком)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <p>— Я помню, Махамати, как однажды пребывал в неком месте, и ко мне подошёл брахман-локаятик. Подойдя и не дожидаясь приглашения, он спросил:</p>

    <p>— О Готама, всё ли сотворено (<em>kṛtaka</em>)?</p>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-8">
        <li>Я ответил:</li>
        <li>— О брахман, если «всё сотворено», то это — первая локаята.</li>
        <li>— Тогда всё несотворено (<em>akṛtaka</em>)?</li>
        <li>— Если всё несотворено, это — вторая локаята.</li>
        <li>— Всё непостоянно?</li>
        <li>— Это — третья локаята.</li>
        <li>— Всё вечно?</li>
        <li>— Это — четвёртая локаята.</li>
        <li>— Всё возникающее?</li>
        <li>— Это — пятая локаята.</li>
        <li>— Всё невозникающее?</li>
        <li>— Это — шестая локаята.</li>
    </ul>

    <p>Брахман продолжал:</p>
    <p>— Всё ли едино? Всё ли различно? Всё ли и то, и другое? Всё ли ни то, ни другое? Зависит ли всё от причин?</p>

    <p>Я ответил:</p>
    <p>— И это, брахман, одиннадцатая локаята.</p>

    <p>Тогда он спросил о невысказанном и высказанном, о наличии или отсутствии «Я», об этом мире и ином мире, об освобождении, о мгновенности, о пространстве, неподлежащем исчислению прекращении и Нирване — сотворены они или нет, и есть ли промежуточное состояние (<em>antarābhava</em>).<a href="#citation-399" id="ref-399" class="citation-mark"><sup>399</sup></a></p>

    <p>Я сказал ему:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>О брахман, если ты рассуждаешь так, то всё это — лишь твоя локаята, но не Моё [учение].</li>
        <li>Я же, брахман, учу, что три мира порождены безначальной инерцией отпечатков рассудочного разрастания понятий.</li>
        <li>Различение (<em>vikalpa</em>), брахман, развёртывается не из-за обнаружения внешних объектов, а из-за неосознания того, что всё — лишь воспринимаемое собственным умом. Мой путь не таков, как у тиртхиков, [учащих] о соединении «я», чувств и объектов.</li>
        <li>Я, брахман, не учу ни о наличии причин, ни об их отсутствии. Но, указывая на само различение как на двойственность «различающего-различаемого», Я учу взаимозависимому возникновению (<em>pratītyasamutpāda</em>).<a href="#citation-400" id="ref-400" class="citation-mark"><sup>400</sup></a> Но такие, как ты, не понимают этого, ибо поток их сознания вовлечён в схватывание «я».</li>
        <li>Что же касается Нирваны, пространства (<em>ākāśa</em>) и прекращения, недостигаемого через рассуждение (<em>apratisaṃkhyānirodha</em>) — сама их сущность не обнаруживается средствами рассудка; как же тогда можно спрашивать, сотворены они или нет?</li>
    </ul>
    </blockquote>

    <p>Брахман-локаятик вновь спросил:</p>
    <p>— О Готама, обусловлен ли этот тройственный мир неведением, жаждой и кармой, или же он беспричинен?</p>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-8">
        <li>[Будда ответил]:</li>
        <li>— Обе эти [позиции], брахман, — это локаята.</li>
        <li>— Но, Готама, разве все вещи не обладают собственными и общими признаками (<em>svasāmānyalakṣaṇa</em>)?</li>
        <li>— И это, брахман, — лишь локаята. До тех пор, брахман, пока длится трепетание мысли (<em>mano-vispandita</em>) различения (<em>vikalpa</em>), [привязанного] к внешним объектам, — до тех пор это локаята.<a href="#citation-401" id="ref-401" class="citation-mark"><sup>401</sup></a></li>
    </ul>

    <p>Брахман-локаятик вновь спросил меня:</p>
    <p>— О Готама, есть ли хоть что-то, что не является локаятой? Ведь всё, что проповедуют тиртхики с помощью разнообразных слов и примеров, — это лишь моё [учение].</p>


    <ul class="list-none mb-8 pl-2 space-y-1 ml-8">
        <li>[Я ответил]:</li>
        <li>— Есть, брахман, то, что не является твоим, что не непроповедуемо, не лишено разнообразных слов и знаков и не лишено смысла.</li>
        <li>— Что же это за «не-локаята» (<em>alokāyata</em>), которая не является общепринятым учением?</li>
        <li>— Есть, брахман, не-локаята, в которую не проникает разум твой и всех тиртхиков, привязанных к ложному размножествлению различений о внешнем бытии. Это — не-развёртывание различения (<em>vikalpasya apravṛtti</em>). Благодаря осознанию того, что всё — лишь воспринимаемое собственным умом, различение бытия и небытия не приходит в движение. Из-за отсутствия захвата внешних объектов различение наблюдается пребывающим в своём собственном месте (<em>svasthāne avatiṣṭhate dṛśyate</em>). Это и есть Моя «не-локаята», и она — не твоя.<a href="#citation-402" id="ref-402" class="citation-mark"><sup>402</sup></a></li>
        <li>«Пребывать в своём месте» — значит не приходить в движение [к объекту]. Это именуется не-возникновением и прекращением различения. Вот это, брахман, и не является локаятой.</li>
        <li>Вкратце, брахман: там, где есть приход и уход сознания (<em>vijñāna</em>), умирание и рождение, стремление, привязанность, влечение, воззрения и захватывание, цепляние за многообразные признаки и привязанность к жажде и её причинам — всё это, брахман, твоя локаята, но не Моя.</li>
    </ul>

    <p>Так, Махамати, Я ответил брахману-локаятику, и он, погрузившись в молчание, удалился.</p>
    </blockquote>

    <p class="text-center font-bold">***</p>
</div>


<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.20 (20. Диалог с царём нагов)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>Затем царь нагов из тёмного лагеря (<em>kṛṣṇapakṣika</em>), приняв облик брахмана, подошёл к Благословенному и сказал:</p>
    <p>— Послушай, Готама, ведь «иного мира» (<em>paraloka</em>)<a href="#citation-403" id="ref-403" class="citation-mark"><sup>403</sup></a> вовсе не существует!</p>

    <p>Благословенный ответил:</p>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-8">
        <li>— Если так, юноша, то откуда же ты пришёл сюда?</li>
        <li>— Я пришёл со Светлого острова (<em>śvetadvīpa</em>), Готама.</li>
        <li>— Но ведь этот остров и есть для тебя «иной мир», брахман.</li>
    </ul>

    <p>Тогда этот юноша замолчал, будучи уличённым (<em>nigṛhīta</em>). Он исчез, так и не спросив Меня о Моём методе, лишь бормоча про себя: «Этот жалкий сын Шакьев проповедует прекращение различения — будто достаточно осознать, что всё видимое есть лишь проявление собственного ума».<a href="#citation-404" id="ref-404" class="citation-mark"><sup>404</sup></a></p>

    <p class="text-center font-bold">***</p>
</div>


<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.21 (21. Предел локаяты)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>— И теперь ты, Махамати, спрашиваешь Меня: по какой причине служение локаятику, блестящему изысканными речами, приносит лишь мирскую наживу (<em>āmiṣa</em>), но не приносит Дхарму?</p>

    <p>Махамати спросил:</p>
    <p>— Но что означают эти понятия, Благословенный: «Дхарма» и «нажива» (<em>āmiṣa</em>)?</p>

    <p>Благословенный ответил:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Хорошо, хорошо, Махамати! Твоё исследование этих двух понятий послужит грядущим поколениям. Слушай же внимательно.</li>
        <li>Махамати, что же такое наживка (<em>āmiṣa</em>)? Это — прикосновение, притяжение, приятное ощущение, захват, наслаждение вкусом, привязанность к внешним объектам и впадение в две крайности [бытия и небытия].<a href="#citation-405" id="ref-405" class="citation-mark"><sup>405</sup></a></li>
        <li>Это — повторное проявление <em>скандх</em> из-за ложных воззрений; это развёртывание рождения, старости, болезней, смерти, скорби, плача, страданий, уныния и отчаяния, порождаемых жаждой к новому рождению (<em>tṛṣṇā paunarbhavikī</em>).</li>
        <li>Вот что именуется Мною и другими Благословенными Буддами «наживкой». Именно это обретает тот, кто служит локаятику: накопление наживы,<a href="#citation-406" id="ref-406" class="citation-mark"><sup>406</sup></a> но не накопление Дхармы.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Махамати, что же такое накопление Дхармы (<em>dharmasaṃgraha</em>)? Это:</li>
        <li>• Постижение двух видов отсутствия «я» — у дхарм и у личности — через осознание их как [проявлений] собственного ума.</li>
        <li>• Не-развёртывание различения (<em>vikalpasya apravṛtti</em>), благодаря видению признаков отсутствия «я».</li>
        <li>• Прекращение ума, рассудка и сознания (<em>citta-mano-vijñāna-vyāvṛtti</em>) через высшее познание ступеней [бодхисаттвы].</li>
        <li>• Вхождение в поток мудрости всех Будд и обретение посвящения (<em>abhiṣeka</em>).</li>
        <li>• Отказ от всякой опоры в виде умозрительных положений (<em>anadhiṣṭhā-pada-parigraha</em>).</li>
        <li>• Спонтанное владычество (<em>anābhoga-vaśavartitā</em>) над всеми явлениями.<a href="#citation-407" id="ref-407" class="citation-mark"><sup>407</sup></a></li>
        <li>Всё это именуется Дхармой, ибо оно свободно от всех [ложных] воззрений, [размножествления] понятий, различений и падения в две крайности бытия.</li>
    </ul>

    <ul class="list-none mb-12 pl-2 space-y-1 ml-2">
        <li>Поистине, Махамати, речи тиртхиков заставляют невежд падать в две крайности — уничтожения (<em>uccheda</em>) и вечности (<em>śāśvata</em>), — но не мудрецов. Из-за принятия учения об отсутствии причин возникает воззрение о вечности; из-за отсутствия причины разрушения [того, что было создано] возникает воззрение об уничтожении.<a href="#citation-408" id="ref-408" class="citation-mark"><sup>408</sup></a> Я же называю Дхармой видение возникновения, пребывания и распада (<em>utpāda-sthiti-bhaṅga</em>). Таково, Махамати, различение между Дхармой и наживой, в котором тебе и другим бодхисаттвам следует упражняться.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>62. Следует усмирять существ методами</li>
        <li>привлечения (<em>saṃgraha</em>) и обуздывать их нравственностью.</li>
        <li>Мудростью (<em>prajñā</em>) следует разрушать [ложные] воззрения,</li>
        <li>а освобождениями (<em>vimokṣa</em>) — взращивать [их дух].</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>63. Всё то, что ложно проповедуется тиртхиками — это Локаята.</li>
        <li>Из-за привязанности к реальности причин и следствий,</li>
        <li>в их учениях нет высшей истины (<em>siddhānta</em>).</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>64. Я один проповедую своим ученикам высшую истину,</li>
        <li>свободную от [двойственности] причины и следствия</li>
        <li>и очищенную от локаяты.<a href="#citation-409" id="ref-409" class="citation-mark"><sup>409</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>65. Всё — лишь сознание, а не видимый объект.</li>
        <li>Сознание же зрится двояко —</li>
        <li>как «схватываемое» и «схватывающий»,</li>
        <li>будучи при этом свободным</li>
        <li>от [крайностей] вечности и уничтожения.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>66. До тех пор, пока движется (развёртывается) сознание —</li>
        <li>до тех пор длится Локаята.</li>
        <li>При не-развёртывании (<em>apravṛtti</em>)</li>
        <li>различения зрят мир как собственный ум.<a href="#citation-410" id="ref-410" class="citation-mark"><sup>410</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>67. «Приход» (прибыль) — это завершение плода причин.</li>
        <li>«Уход» (убыток) — это видение распада.</li>
        <li>Благодаря полному постижению [природы] прихода и ухода,</li>
        <li>различение (<em>vikalpa</em>) не приходит в движение.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>68. «Вечное и невечное», «сотворённое и несотворённое»,</li>
        <li>«это и то» — всё подобное является методом Локаяты.</li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>

<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.22 (22. Как тиртхики воображают Нирвану)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>Затем бодхисаттва-махасаттва Махамати вновь обратился к Благословенному:</p>
    <p>— О Благословенный, «Нирвана, Нирвана» — так говорится. Для какой реальности «Нирвана» является обозначением, если учесть всё то многообразие различений, что строят тиртхики?</p>

    <p>Благословенный ответил:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Слушай же внимательно, Махамати. Некоторые тиртхики, Махамати, [считают так]: через пресечение <em>скандх</em>, <em>дхату</em> и <em>аятан</em>, через бесстрастие к объектам и через видение непостоянства всех вещей — поток сознания и психических факторов перестаёт развёртываться. Не вспоминая о прошлых, будущих и настоящих объектах,<a href="#citation-411" id="ref-411" class="citation-mark"><sup>411</sup></a> они уподобляют это угасанию светильника, семени или огня,<a href="#citation-412" id="ref-412" class="citation-mark"><sup>412</sup></a> когда прекращается привязанность, и различение более не приходит в движение. Таково их понимание Нирваны. Однако, Махамати, из-за воззрения об уничтожении они не достигают Нирваны.<a href="#citation-413" id="ref-413" class="citation-mark"><sup>413</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Другие, Махамати, описывают освобождение как переход в иное место — в состояниях прекращения различения объектов — подобно движению ветра. Другие тиртхики утверждают, что освобождение — это уничтожение видения связи между познающим и познаваемым. Иные воображают Нирвану как прекращение различения через видение вечного и мимолётного.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Другие, не зная, что всё — лишь проявление собственного ума, учат, что различение многообразных признаков порождает страдание и рождение. Боясь этих признаков, они видят Нирвану в наслаждении состоянием без признаков. Иные воображают Нирвану в неуничтожимости всех внутренних и внешних дхарм, утверждая их существование в прошлом, настоящем и будущем. Другие воображают Нирвану через неуничтожимость <em>атмана</em>, <em>саттвы</em>, <em>дживы</em>, <em>поши</em>, <em>пуруши</em>, <em>пудгалы</em> и всех дхарм.<a href="#citation-414" id="ref-414" class="citation-mark"><sup>414</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Другие тиртхики, чей разум помрачён, воображают Нирвану через видение различия между Первоматерией (<em>prakṛti</em>) и Духом (<em>puruṣa</em>), или через изменение качеств-гун.<a href="#citation-415" id="ref-415" class="citation-mark"><sup>415</sup></a> Иные — через исчерпание заслуг и грехов. Другие — через уничтожение омрачений мудростью. Третьи — через видение мира как творения Ишвары.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Некоторые полагают, что мир возникает из взаимного столкновения элементов, а не из причин; привязанные к этому по неведению, они воображают Нирвану. Другие видят её в постижении истинного пути. Иные — в единстве или различии качеств и их носителя. Другие, глядя на пестроту павлина, разнообразие драгоценных камней или остроту шипов, полагают, что это и есть собственная природа (<em>svabhāva</em>) вещей, и воображают в этом Нирвану.<a href="#citation-416" id="ref-416" class="citation-mark"><sup>416</sup></a> Иные — в постижении двадцати пяти <em>таттв</em>.<a href="#citation-417" id="ref-417" class="citation-mark"><sup>417</sup></a> Другие — в следовании шести наставлениям царя-хранителя (<em>prajāpāla</em>).<a href="#citation-418" id="ref-418" class="citation-mark"><sup>418</sup></a> Некоторые видят Нирвану во власти Времени над миром и в постижении этой власти.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Иные воображают Нирвану через бытие, другие — через небытие, третьи — через познание обоих, четвёртые — через видение неразличимости бытия и Нирваны.<a href="#citation-419" id="ref-419" class="citation-mark"><sup>419</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Но есть и те, Махамати, кто возглашают подобно львиному рыку. Они воображают Нирвану через осознание того, что всё — лишь воспринимаемое собственным умом (<em>svacitta-dṛśya-mātra</em>), через отсутствие привязанности к внешнему бытию и небытию, через свободу от четырёх логических крайностей, через видение реальности такой, какова она есть, без падения на сторону субъекта или объекта, через отказ от любых мерил и суждений, через обретение личного благородного постижения и двоякого отсутствия «я», через очищение от двух видов омрачений и двух видов преград, через восхождение по ступеням к уровню Татхагаты, через достижение <em>самадхи</em>, подобного магии, и через прекращение ума, рассудка и сознания (<em>citta-mano-vijñāna-vyāvṛtti</em>).<a href="#citation-420" id="ref-420" class="citation-mark"><sup>420</sup></a></li>
    </ul>

    <ul class="list-none mb-12 pl-2 space-y-1 ml-2">
        <li>Все прочие учения логиков и тиртхиков лишены смысла и отвергаются мудрецами. Все они, Махамати, воображают Нирвану, оставаясь в плену крайностей. Если проверить каждое из их учений разумом, оно окажется ложным — оно не таково, каким воображается. Ни одно из них не содержит Нирваны, ибо ум [тех, кто их придерживается] продолжает трепетать и метаться. Тебе же, Махамати, и другим бодхисаттвам следует отбросить все эти воззрения тиртхиков о Нирване.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>69. Тиртхики по отдельности воображают</li>
        <li>различные воззрения о Нирване,</li>
        <li>но всё это — лишь воображение (<em>kalpanāmātra</em>);</li>
        <li>в них нет пути к освобождению.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>70. Не освободившись ни от уз,</li>
        <li>ни от самого связывания</li>
        <li>и не имея истинных средств,</li>
        <li>тиртхики воображают освобождение,</li>
        <li>но освобождение [в их словах] не обнаруживается.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>71. Метод тиртхиков видится разбитым на множество ветвей;</li>
        <li>потому у них нет освобождения.</li>
        <li>Зачем же оно воображается этими заблудшими?</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>72. Все тиртхики ослеплены</li>
        <li>дурным воззрением о причине и следствии;</li>
        <li>потому у тех, кто проповедует крайности</li>
        <li>бытия и небытия, нет освобождения.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>73. Невежды, увлечённые болтовнёй и</li>
        <li>размножествлением идей (<em>jalpa-prapañca</em>),</li>
        <li>не направляют свой великий разум к Истине.</li>
        <li>Ибо болтовня есть источник страдания</li>
        <li>в тройственном мире (<em>traidhātuka-duḥkha-yoni</em>),</li>
        <li>Истина же — причина уничтожения страдания.<a href="#citation-421" id="ref-421" class="citation-mark"><sup>421</sup></a></li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>74. Как в зеркале видится образ,</li>
        <li>но его там нет, так в зеркале отпечатков (<em>vāsanā-darpaṇa</em>)</li>
        <li>ум видится невеждами двояко — как субъект и объект.<a href="#citation-422" id="ref-422" class="citation-mark"><sup>422</sup></a></li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>75. Из-за непостижения того, что всё —</li>
        <li>лишь проявления ума, рождается двойственное различение.</li>
        <li>Благодаря постижению проявлений ума</li>
        <li>различение не приходит в движение.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>76. Сам ум предстаёт как многообразие,</li>
        <li>будучи свободным от признака и носителя признака.</li>
        <li>Он принимает форму видимого, но видимого [объекта]</li>
        <li>не существует так, как его воображают невежды.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>77. Тройственный мир — лишь различение,</li>
        <li>внешнего объекта не существует.</li>
        <li>Различение видится как многообразие [форм],</li>
        <li>но невежды не распознают этого.<a href="#citation-423" id="ref-423" class="citation-mark"><sup>423</sup></a></li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>78. В каждой сутре различение</li>
        <li>проповедовалось под разными именами;</li>
        <li>но означаемое (<em>abhidheya</em>),</li>
        <li>отделённое от обозначения (<em>abhidhāna</em>),</li>
        <li>не обнаруживается как признак.<a href="#citation-424" id="ref-424" class="citation-mark"><sup>424</sup></a></li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>

<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.23 (Пробуждённость самого Будды)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>Затем бодхисаттва-махасаттва Махамати обратился к Благословенному:</p>
    <p>— Пусть Благословенный, Татхагата, Архат, Совершенно Пробуждённый наставит меня в пробуждённости самого Будды, дабы я и другие бодхисаттвы-махасаттвы, став искусными в природе Татхагаты, пробудили себя и других.</p>

    <p>Благословенный ответил:</p>
    <p>— В таком случае, Махамати, спрашивай сам. Как тебе угодно, так Я и отвечу.</p>

    <p>Махамати спросил:</p>
    <p>— О Благословенный, является ли Татхагата, Архат, Совершенно Пробуждённый сотворённым (<em>kṛtaka</em>) или несотворённым (<em>akṛtaka</em>)? Является ли Он следствием или причиной, носителем признака или самим признаком, обозначением или обозначаемым, разумом или объектом познания? Отличен ли Благословенный от этих понятий или тождественен им?<a href="#citation-425" id="ref-425" class="citation-mark"><sup>425</sup></a></p>


    <p>Благословенный ответил:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Махамати, согласно таким определениям, Татхагата, Архат, Совершенно Пробуждённый — не сотворён и не несотворён, не является ни следствием, ни причиной. Почему? Потому что это привело бы к двойной ошибке (<em>ubhaya-doṣa</em>).</li>
        <li>Ведь если бы Татхагата был сотворён, Он был бы непостоянен. Будь Он непостоянен, всё сотворённое было бы Татхагатой. Это неприемлемо ни для Меня, ни для других Татхагат.</li>
        <li>Если же Он несотворён, то из-за отсутствия обретаемой сути все накопленные заслуги [пути] оказались бы напрасными. Он был бы подобен рогам зайца или сыну бесплодной женщины, так как несотворённое [абсолютно] не существует.<a href="#citation-426" id="ref-426" class="citation-mark"><sup>426</sup></a></li>
        <li>То, что не является ни следствием, ни причиной, — ни существует, ни не существует. А то, что ни существует, ни не существует, — лежит вне четырёх логических крайностей (<em>cātuṣkoṭika</em>). Эти четыре крайности — лишь мирские условности. То же, что лежит за их пределами, оказывается лишь пустым звуком (<em>vāgmātra</em>), подобно «сыну бесплодной женщины». Ведь «сын бесплодной женщины» — лишь слово; он не подпадает под логические крайности. Поскольку он вне их, он не является мерилом для мудрых. Именно так мудрецы должны понимать всё, что касается Татхагаты.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Что же до Моих слов: «Все дхармы лишены «я» (<em>nirātmānaḥ</em>)», — то и этот смысл, Махамати, нужно постичь верно. Отсутствие «я» (<em>nairātmya</em>) означает отсутствие [неизменной] сущности «я». Все дхармы обнаруживаются через свою собственную природу, а не через природу другого — подобно корове и лошади.</li>
        <li>Представь, Махамати: природа коровы не является природой лошади, а природа лошади — природой коровы. Они не определяются ни бытием, ни небытием, но проявляются в своих собственных признаках (<em>svalakṣaṇa</em>). Точно так же, Махамати, и все дхармы не лишены проявления в своих собственных признаках. Они зрятся! Но невежды понимают «отсутствие "я"» через различение (<em>vikalpa</em>), а не через не-различение. Именно так следует понимать <em>шуньяту</em>, не-возникновение и отсутствие «я» всех дхарм.<a href="#citation-427" id="ref-427" class="citation-mark"><sup>427</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Подобно этому, Татхагата и не отличен от <em>скандх</em>, и не тождественен им. Если бы Он был тождественен <em>скандхам</em>, Он был бы непостоянен, так как <em>скандхи</em> сотворены. Если же Он был бы отличен, то при наличии этой двойственности [Он был бы чем-то внешним], подобно двум рогам одного быка.<a href="#citation-428" id="ref-428" class="citation-mark"><sup>428</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>В этом мире [представление о] <strong>тождестве</strong> (<em>ananyatva</em>) всех вещей возникает из видения сходства, а [представление о] <strong>различии</strong> (<em>anyatva</em>) — из видения [разницы] короткого и длинного. Ведь правый рог коровы, Махамати, отличен от левого, а левый — от правого. Так же обстоит дело с коротким и длинным в их взаимности, и с многообразием цветов.</li>
        <li>Поэтому вещи отличны друг от друга [лишь] во взаимном соотнесении. Однако Татхагата не отличен от <em>скандх</em>, <em>дхату</em> и <em>аятан</em>, [но и не тождественен им]. Точно так же Татхагата не отличен и не тождественен <strong>освобождению</strong> (<em>vimokṣa</em>). Само слово «освобождение» служит обозначением Татхагаты.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Если бы Татхагата был отличен от освобождения, Он обладал бы признаками формы (<em>rūpa-lakṣaṇa</em>). Обладая признаками формы, Он был бы непостоянен. Если же Он был бы тождественен [ему], то для йогинов не существовало бы разделения в признаках достижения [плода]. Но йогины, Махамати, видят это разделение. Потому Он не отличен и не тождественен. Так же и познание (<em>jñāna</em>) не отлично и не тождественно объекту познания (<em>jñeya</em>).</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>То, что не является ни вечным, ни невечным, ни следствием, ни причиной, ни обусловленным, ни необусловленным, ни разумом, ни объектом познания, ни носителем признака, ни признаком, ни <em>скандхами</em>, ни чем-то отличным от <em>скандх</em>, ни обозначаемым, ни обозначением, ни связанным с единством, отличием, тем и другим или ни тем, ни другим, — всё это свободно от любых мерил и суждений (<em>sarva-pramāṇa-vinivṛtta</em>).</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>То, что свободно от всех мерил, является лишь указанием (<em>vāgmātra</em>)<a href="#citation-429" id="ref-429" class="citation-mark"><sup>429</sup></a> — то есть выходит за пределы любого утверждения. То, что есть лишь слово, — не рождено. То, что не рождено, — не прекращается. То, что не прекращается, — подобно пространству (<em>ākāśa-sama</em>). А пространство, Махамати, не является ни следствием, ни причиной. То, что не является ни следствием, ни причиной, — безопорно (<em>nirālambya</em>). То, что безопорно, — выходит за пределы всякого размножествления (<em>sarva-prapañca-atīta</em>).</li>
    </ul>

    <ul class="list-none mb-12 pl-2 space-y-1 ml-2">
        <li>То, что выходит за пределы всякого размножествления, — это и есть Татхагата. Это, Махамати, и есть Совершенное Пробуждение. Такова природа Будды, свободная от всех мерил и [ограничений] органов чувств.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>79. Свободный от мерил (<em>pramāṇa</em>) и чувств,</li>
        <li>Он не является ни следствием, ни причиной.</li>
        <li>Он лишён [двойственности] разума и познаваемого,</li>
        <li>свободен от признака и носителя признака.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>80. Опираясь на <em>скандхи</em>, Пробуждённый</li>
        <li>не может быть кем-либо и где-либо «увиден».</li>
        <li>Если же Он никем и нигде не «видим» как объект,</li>
        <li>то как же возможно Его постижение?</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>81. Он ни сотворён, ни несотворён,</li>
        <li>ни следствие, ни причина;</li>
        <li>Он — не <em>скандхи</em>и не <em>не-скандхи</em>,</li>
        <li>и Он не [возникает] из их смешения.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>82. Если нечто, воображаемое в том или ином виде,</li>
        <li>не обнаруживается [таким],</li>
        <li>не следует считать, что его вовсе нет.</li>
        <li>Такова истинная природа (<em>dharmatā</em>) всех явлений (<em>dharma</em>).<a href="#citation-430" id="ref-430" class="citation-mark"><sup>430</sup></a></li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>83. «Нет» предваряется «есть»,</li>
        <li>«есть» предваряется «нет».</li>
        <li>Поэтому не следует приходить к «нет»</li>
        <li>и не следует измышлять «есть».</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>84. Запутавшиеся в «я» и отсутствии «я»,</li>
        <li>цепляющиеся лишь за недостатки [чужих учений], —</li>
        <li>они погружены в две крайности.</li>
        <li>Погибая сами, эти невежды губят и других.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>85. Когда же узрят Мой метод,</li>
        <li>свободный от всех этих пороков, —</li>
        <li>тогда узрят истинно</li>
        <li>и не станут более поносить Путеводителей.</li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>


<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.24 (24. Имена Татхагаты, опора на смысл, а не на букву)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>Махамати вновь спросил:</p>
    <p>— Благословенный, в Твоих наставлениях упоминается «не-прекращение и не-возникновение», и говорится, что это — иное имя Татхагаты. Но что это означает? Является ли это простым отсутствием (<em>abhāva</em>) или особым синонимом Татхагаты? Ведь если все дхармы не рождены, то постижение Дхармы невозможно — из-за нерождённости всех дхарм. Если же это лишь синоним какой-то дхармы — пусть Благословенный скажет, какой именно.</p>

    <p>Благословенный ответил:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>— Слушай же внимательно, Махамати. Татхагата — это не «отсутствие», и учение о не-возникновении всех дхарм — не бессмысленное отрицание и не требует внешних условий для своего обоснования.</li>
        <li>Это — обозначение Татхагаты как Тела Дхармы (Дхармакаи), проявляемого умом (<em>manomaya-dharmakāya</em>) — области, недоступной ни тиртхикам, ни шравакам, ни пратьекабуддам, ни даже бодхисаттвам, утверждённым на [первых] семи ступенях. Это и есть не-возникновение Татхагаты. Это — синонимическое выражение.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Подобно тому, Махамати, как Индра называется Шакрой и Пурандарой, рука — «хастой» и «пани», тело — «тану» и «дехой», земля — «бхуми» и «васундхарой», пространство — «кхой» и «гаганой», — так одна реальность имеет множество имён. Но от множества имён сама суть не множится и не исчезает.</li>
        <li>Так и Я, Махамати, в этом мире Саха являюсь слуху невежд под сотнями тысяч имён. Они называют Меня этими именами, не понимая, что всё это — синонимы Татхагаты.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Одни знают Меня как Татхагату, другие — как Самовозникшего (<em>Svayaṃbhu</em>), как Наставника (<em>Nāyaka</em>), Ведущего (<em>Vināyaka</em>), Направляющего (<em>Pariṇāyaka</em>), Будду, Риши, Быка, Брахму, Вишну, Ишвару, Прадхану, Капилу, Бхутанту, Аришнанеми, Сому, Бхаскару, Раму, Вьясу, Шуку, Индру, Бали или Варуну. Другие же знают Меня как Не-возникновение (<em>anirodhānutpāda</em>), <em>Шуньяту</em>, Таковость (<em>tathatā</em>), Истинность, Подлинность, Предел истинности (<em>bhūtakoṭi</em>), <em>Дхармадхату</em>, Нирвану, Вечность, Равенство, Недвойственность, Не-прекращение, Беспризнаковость, Условие, Наставление о причине Пробуждения, Освобождение, Пути Истины, Всезнание, Победителя или [как] созданного умом.<a href="#citation-431" id="ref-431" class="citation-mark"><sup>431</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Именно так, Махамати, люди в этом и других мирах знают Меня под тремястами тысячами имён — не меньше и не больше — подобно луне в воде: ни вошедшей, ни вышедшей. Невежды же, запутавшиеся в двойственности, не понимают этого.</li>
        <li>Они почитают Меня, воздают Мне хвалу, уважают и поклоняются — но не искусны в смысле слов и понятий, не различая имён. Не зная собственного метода, цепляясь за букву наставлений, они воображают, что «не-возникновение» — это просто отсутствие, а не синоним имён Татхагаты. Они не понимают, что «Индра», «Шакра» и «Пурандара» — лишь синонимы, а не указания на разные сущности.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Они говорят: «Смысл — в самой букве, смысл не отличен от звука». Но это от незрелости разума. Они не знают, Махамати, что звук возникает и гибнет, а Смысл — не возникает и не гибнет. Звук ограничен знаком (<em>akṣara</em>), Смысл же — вне знаков.<a href="#citation-432" id="ref-432" class="citation-mark"><sup>432</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Татхагаты не проповедуют Дхарму, ограниченную буквами — ибо буквы не обладают реальностью ни в бытии, ни в небытии. Тот же, кто учит Дхарме, ограниченной буквами, — просто болтает, поскольку Дхарма вне знаков. Именно поэтому Мною и другими Буддами и бодхисаттвами сказано в наставлениях: Татхагаты не произнесли и не произносят ни единого звука. Почему? Потому что Дхарма — вне знаков.<a href="#citation-433" id="ref-433" class="citation-mark"><sup>433</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Однако без использования слов Учение бы исчезло. А без Учения не было бы ни Будд, ни пратьекабудд, ни шраваков, ни бодхисаттв. А без них — кому и что проповедовалось бы?</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Поэтому, Махамати, бодхисаттве следует не привязываться к букве наставлений. Буква наставлений изменчива. Учение Дхармы даётся существам в соответствии с их склонностями и верой — ради поворота ума, рассудка и сознания (<em>citta-mano-vijñāna-vyāvṛtti</em>) — а не исходя из утверждения кого-либо в личном благородном постижении, в осознании без-образности всех дхарм, в постижении того, что всё — лишь воспринимаемое собственным умом, и в прекращении двойственного различения.<a href="#citation-434" id="ref-434" class="citation-mark"><sup>434</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Поэтому, Махамати, бодхисаттве следует опираться на Смысл (<em>artha-pratiśaraṇa</em>), а не на Букву (<em>vyañjana-pratiśaraṇa</em>).<a href="#citation-435" id="ref-435" class="citation-mark"><sup>435</sup></a> Тот сын или дочь благородной семьи, кто следует лишь за буквой, губит себя и не пробуждает других. Поток их сознания, павший в ложные воззрения, вводится в заблуждение лже-тиртхиками — теми, кто не искусен в признаках всех дхарм и ступеней и не знает подлинного смысла слов.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Затем [те, кто опираются на Смысл], становятся искусными в уровнях всех Дхарм и их собственных признаках;<a href="#citation-436" id="ref-436" class="citation-mark"><sup>436</sup></a> они проникают в суть слов, синонимов и определений, становясь сведущими в логике бытия и смысла (<em>bhāvārthayukti</em>). Благодаря этому они радуют себя истинным блаженством беспризнаковости (<em>samyaganimittasukha</em>) и должным образом утверждают других в Махаяне.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Махамати, через истинное принятие Махаяны совершается принятие Будд, шраваков, пратьекабудд и бодхисаттв. Через принятие Будд и их учеников совершается принятие всех живых существ. Через принятие всех живых существ совершается принятие Благой Дхармы (<em>saddharma</em>).</li>
        <li>Через принятие Благой Дхармы, Махамати, совершается непрерывность Рода Будд (<em>buddhavaṃśa-anupaccheda</em>). Благодаря непрерывности Рода Будд обретаются особые обители (<em>āyatanaviśeṣa</em>).<a href="#citation-437" id="ref-437" class="citation-mark"><sup>437</sup></a> Пребывая в этих особых обителях, бодхисаттвы-махасаттвы, принимая рождения ради утверждения других в Махаяне и обладая десятью видами <em>власти</em> (<em>daśavaśitā</em>),<a href="#citation-438" id="ref-438" class="citation-mark"><sup>438</sup></a> принимают различные облики и формы (<em>vicitrarūpaveśa</em>). Постигая скрытые склонности (<em>anuśaya</em>)<a href="#citation-439" id="ref-439" class="citation-mark"><sup>439</sup></a> и признаки различных существ, они проповедуют им Дхарму в соответствии с их таковостью (<em>tathātva</em>).<a href="#citation-440" id="ref-440" class="citation-mark"><sup>440</sup></a></li>
        <li>В этом и заключается Таковость, неизменность и Истина. Истиной именуется признак отсутствия прибавления и убавления (<em>anāyūha-niryūha</em>), утихание всякого размножествления.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Потому, Махамати, ни сыну, ни дочери благородной семьи не следует быть искусными лишь в привязанности к смыслу по букве. Ибо Истина свободна от букв (<em>nirakṣara</em>). Не следует быть подобным тому, кто смотрит на палец. Представь, Махамати: кто-то пальцем указывает другому на некую вещь, а тот уставится на сам кончик пальца (<em>aṅgulyagra</em>).</li>
        <li>Точно так же, Махамати, невежды, подобные детям, умирают, будучи привязанными к кончику пальца «буквы», так и не оставив его ради постижения Высшего Смысла (<em>paramārtha</em>).</li>
        <li>Это подобно тому, как детям предлагают пищу: если кто-то станет есть её сырой (неприготовленной), его сочтут безумцем, ибо он не понимает постепенности приготовления. Так же, Махамати, и [учения] о не-возникновении и не-прекращении не сияют без должного приготовления. Здесь необходима подготовка, а не цепляние за себя, подобное взгляду на кончик пальца.<a href="#citation-441" id="ref-441" class="citation-mark"><sup>441</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Посему, Махамати, следует прилагать усилия к Смыслу (<em>artha</em>). Смысл, Махамати, — это свобода, причина Нирваны. Буква же связана с различением и влечёт за собой Сансару. Смысл обретается подле многознающих (<em>bahuśruta</em>). Но «многознание», Махамати, — это искусность в Смысле, а не искусность в буквах. Искусность в Смысле — это видение, не смешанное с речами тиртхиков, когда сам не падаешь и других не толкаешь к падению. При таком обладании Смыслом и рождается истинное многознание. Посему ищущему Смысл следует служить таким [учителям], а тех, кто привязан к букве, — избегать.</li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>


<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.25 (25. Вопрос Махамати о сходстве учений)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>Махамати, укреплённый благословением Будды (<em>buddhādhiṣṭhānādhiṣṭhita</em>), сказал:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>— Благословенный, Твоё учение о не-прекращении и не-возникновении (<em>anirodhānutpāda</em>) ничем не отличается [от других]. Почему? Потому что и у всех тиртхиков «первопричины» не рождены и не гибнут. И у Тебя, Благословенный, пространство, неподлежащее исчислению прекращение (<em>apratisaṃkhyā-nirodha</em>) и сфера Нирваны — не прекращаются и не возникают.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Тиртхики описывают возникновение мира из первопричин и условий. И Ты, Благословенный, описываешь возникновение мира из условий неведения, жажды, кармы и различения (<em>ajñāna-tṛṣṇā-karma-vikalpa</em>), порождая лишь иное название той же самой первопричины — «условия» (<em>tasyaiva kāraṇasya saṃjñāntaraviśeṣam utpādya pratyayā</em>). Так же и с внешними вещами: и они, и Ты учите их возникновению. Поэтому Твоё учение не имеет отличий от учений тиртхиков.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Атомы (<em>aṇu</em>), первоматерия (<em>pradhāna</em>), Ишвара и Праджапати вместе с девятью основами (<em>navadravyasahitā</em>)<a href="#citation-442" id="ref-442" class="citation-mark"><sup>442</sup></a> — у них [считаются] нерождёнными и негибнущими. И у Тебя все явления не рождаются и не гибнут, так как бытие и небытие [в высшем смысле] не обнаруживаются. Элементы не исчезают, их собственные признаки не возникают и не гибнут. Пребывая в своей природе, они её не покидают. Это многообразие элементов и их преобразований воображается и тиртхиками, и Тобой.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>По этой причине Твоё учение не имеет отличий. Скажи же, в чём заключается особенность (<em>viśeṣa</em>), выделяющая учение Татхагаты среди прочих? Ибо если отличий нет, то и тиртхиков следовало бы признать Буддами, раз они тоже учат не-возникновению. А ведь Тобой сказано, что невозможно и недопустимо (<em>asthānam anavakāśaṃ ca</em>), чтобы в одном мире возникло много Татхагат. Но при таком отсутствии отличий и при допущении [Твоей] реальности следствий — как существующих, так и несуществующих (<em>sadasatkāryaparigrahāt</em>),<a href="#citation-443" id="ref-443" class="citation-mark"><sup>443</sup></a> возникло бы множество Татхагат.</li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>


<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.26 (26. Ответ о сходстве учений)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>Благословенный ответил:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Махамати, Моё [учение о] не-прекращении и не-возникновении не тождественно учению тиртхиков, равно как и их теориям о возникновении и непостоянстве. Почему?</li>
        <li>У тиртхиков, Махамати, существует представление о собственной природе бытия (<em>bhāva-svabhāva</em>), которую они наделяют признаками нерождённости и неизменности. У Меня же нет падения в стороны бытия и небытия.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Мой метод, Махамати, свободен от крайностей «есть» и «нет», далёк от возникновения и распада. Это не "небытие" — ведь многообразие иллюзорных форм всё же является (подобно миражу). И это не «бытие», поскольку признаки форм не захватываются умом как нечто видимое или невидимое, схватываемое или несхватываемое. Поэтому все вещи — вне бытия и небытия.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Благодаря осознанию того, что всё — лишь воспринимаемое собственным умом (<em>svacitta-dṛśya-mātra</em>), различение (<em>vikalpa</em>) более не развёртывается, и мир предстаёт пребывающим в покое и бездеятельности (<em>niṣkriya</em>). Невежды воображают «деятеля», но не Благородные.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Это заблуждение относительно ложных объектов, Махамати, подобно городу гандхарвов (миражу)<a href="#citation-444" id="ref-444" class="citation-mark"><sup>444</sup></a> или магическим людям. Представь: некий глупец воображает, как в город гандхарвов входят или выходят из него магические люди и караваны: «Вот эти вошли, а те вышли». Но там никто не входит и не выходит! Это лишь движение воображаемого заблуждения.</li>
        <li>Точно так же, Махамати, это «возникновение и не-возникновение» — лишь заблуждение невежд. Здесь нет ничего обусловленного или необусловленного, как нет рождения у магического человека. Магический человек не рождается и не гибнет, ибо категории бытия и небытия к нему неприложимы.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Так и все дхармы лишены возникновения и распада. Лишь невежды, павшие в ложные представления, воображают рождение и смерть, но не Благородные. Это «ложное» (<em>vitatha</em>), Махамати, означает: вещи не таковы, какими их воображают, наделяя их реальной природой; но они и не иные. Если бы они были иными [совершенно отсутствующими], то привязанность к их природе была бы невозможна. И тогда не было бы ни видения отрешённости (<em>viviktadarśana</em>),<a href="#citation-445" id="ref-445" class="citation-mark"><sup>445</sup></a> ни видения неотрешённости (<em>aviviktadarśana</em>), ни поворота различения (<em>vikalpasya vyāvṛtti</em>).</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Потому, Махамати, видение отсутствия признаков (<em>animitta</em>) благодатно, а видение признаков — пагубно. Видение признаков — причина новых рождений. Отсутствие признаков — это не-развёртывание различения; это Я называю «не-возникновением» и «нирваной».</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Нирвана, Махамати, — это видение пребывания реальности как она есть, предваряемое поворотом (<em>parāvṛtti</em>) сознания и психических факторов. Обретение личного благородного постижения Татхагаты — вот что Я называю Нирваной.</li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
</div>


<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.27 (27. Не-возникновение и Единство Учения)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>Об этом сказано так:</p>

    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>86. Ради отвращения от идеи возникновения</li>
            <li>Я проповедую не-возникновение (<em>anutpāda</em>).</li>
            <li>Я провозглашаю учение о беспричинности (<em>ahetuvāda</em>),</li>
            <li>однако неразумные не способны его постичь.</li>
            <li>Всё это не рождено; становлений (<em>bhāva</em>) нет —</li>
            <li>и в то же время нельзя сказать, что их вовсе нет.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>87. [Махамати:]</li>
            <li>— Если явления, называемые подобными городу гандхарвов,</li>
            <li>сну и <em>майе</em>, видятся как беспричинные,</li>
            <li>то на каком основании Ты утверждаешь,</li>
            <li>что они нерождённы и пусты (<em>śūnya</em>)?</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>88. [Будда:]</li>
            <li>— Когда явление не обнаруживается отдельно от того,</li>
            <li>что мыслится как его целостное сочетание (<em>samavāya</em>),<a href="#citation-446" id="ref-446" class="citation-mark"><sup>446</sup></a></li>
            <li>тогда Я провозглашаю его пустым, нерождённым</li>
            <li>и лишённым собственной природы (<em>asvabhāva</em>).</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>89. То, что мыслится как целостное сочетание (<em>samavāya</em>),</li>
            <li>вследствие отсутствия видимого объекта, не существует.</li>
            <li>Однако это — не то уничтожение (<em>pralaya</em>),</li>
            <li>о котором говорят тиртхики.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>90. Подобно сну, пучку волос перед глазами, миражу,</li>
            <li>городу гандхарвов и мареву воды в пустыне —</li>
            <li>явления мира, хотя и беспричинны, всё же видятся.</li>
            <li>Такова многообразная игра мира.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>91. Опровергнув ложные воззрения</li>
            <li>посредством учения о беспричинности (<em>ahetuvāda</em>),</li>
            <li>следует утвердить не-возникновение (<em>anutpāda</em>).</li>
            <li>Когда не-возникновение утверждается должным образом,</li>
            <li>Моё наставление (<em>netrī</em>) не погибает.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>92. Когда провозглашается учение о беспричинности,</li>
            <li>у иноверцев (<em>tīrthya</em>) возникает страх:</li>
            <li>«Как? Кем? Откуда?</li>
            <li>Где может возникнуть нечто беспричинное?»</li>
            <li>Когда мудрецы видят обусловленное (<em>saṃskṛta</em>)</li>
            <li>как не возникающее ни из причин,</li>
            <li>ни беспричинно (само по себе), тогда отпадает воззрение,</li>
            <li>утверждающее возникновение и распад.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>93. [Махамати:]</li>
            <li>— Является ли не-возникновение (<em>anutpāda</em>) небытием (<em>abhāva</em>)?</li>
            <li>Или же оно — признак возникновения (<em>utpatti-lakṣaṇa</em>)?</li>
            <li>Или это имя для явления (<em>bhāva</em>)?</li>
            <li>Или оно бессмысленно? Скажи мне!</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>94. — Не-возникновение — это не бытие (<em>bhāva</em>),</li>
            <li>не является признаком обусловленного (<em>pratyaya-lakṣaṇa</em>),</li>
            <li>это не название для бытия,</li>
            <li>и само это название не лишено смысла.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>95. Там, где нет доступа (<em>agocara</em>) ни для шраваков и пратьекабудд,</li>
            <li>ни для тиртиков, ни даже для бодхисаттв,</li>
            <li>пребывающих на семи первых ступенях (<em>saptabhūmigatānām</em>), —</li>
            <li>там раскрывается признак не-возникновения (<em>anutpāda-lakṣaṇam</em>).</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>96. Устранение причин и условий (<em>hetu-pratyaya-vyāvṛtti</em>),</li>
            <li>отрицание [внешней] причины (<em>kāraṇasya niṣedhanam</em>)</li>
            <li>и установление «только-ума» (<em>cittamātra-vyavasthānam</em>) —</li>
            <li>вот что Я называю не-возникновением.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>97. Беспричинное разворачивание явлений (<em>ahetu-vṛtti</em>),</li>
            <li>свободную от воображаемого</li>
            <li>и самого воображения (<em>kalpya-kalpa-vivarjitām</em>),</li>
            <li>избавленное от крайностей «есть» и «нет» (<em>sadasat-pakṣa-nirmuktam</em>) —</li>
            <li>вот что Я называю не-возникновением.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>98. Освобождённое от ума и видимого (<em>citta-dṛśya-vinirmuktam</em>)</li>
            <li>лишённое двойственной природы (<em>svabhāvadvaya-varjitam</em>),</li>
            <li>поворот основы (<em>āśrayasya parāvṛttim</em>) —</li>
            <li>вот что Я называю не-возникновением.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>99. Ни внешнего бытия (<em>bāhya-bhāva</em>), ни небытия (<em>abhāva</em>),</li>
            <li>ни схватывания умом (<em>citta-parigraha</em>),</li>
            <li>[видение всего] как сна, волосков перед глазами, иллюзии,</li>
            <li>города гандхарвов и миража,</li>
            <li>а также отбрасывание всех воззрений (<em>sarva-dṛṣṭi-prahāṇa</em>) —</li>
            <li>вот что является признаком не-возникновения (<em>anutpāda-lakṣaṇa</em>).</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>100. Так следует созерцать все дхармы как пустые (<em>śūnyā</em>),</li>
            <li>лишенные собственной природы и прочее.</li>
            <li>Они никогда не пусты «самой по себе пустотой» (<em>śūnyayā</em>),</li>
            <li>но пусты именно в силу не-возникновения (<em>anutpāda-śūnyayā</em>).</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>101. Совокупность условий (<em>kalāpa</em>)</li>
            <li>разворачивается и прекращается.</li>
            <li>Но то, что мыслится как отличное от этой совокупности,</li>
            <li>— не рождается и не гибнет.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>102. Нигде и никогда не существует никакого «явления»,</li>
            <li>отделённого от совокупности условий.</li>
            <li>Представления же о единстве или разделённости —</li>
            <li>это лишь вымысел иноверцев (<em>tīrthyair-vikalpyate</em>).</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>103. Явление не рождается ни из существующего,</li>
            <li>ни из несуществующего,</li>
            <li>ни из их сочетания.</li>
            <li>Именно эта совокупность условий движется и [прекращается].</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>104. Всё это — лишь условные обозначения (<em>saṃketa-mātram</em>),</li>
            <li>возникающие из взаимозависимого сцепления (<em>anyonyāpekṣa-saṃkalāt</em>).</li>
            <li>Порождаемого явления воистину нет</li>
            <li>отдельно от сцепления условий.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>105. Не-возникновение (<em>anutpāda</em>) —</li>
            <li>не отсутствие порождаемого (<em>janya-abhāva</em>).</li>
            <li>Оно свободно от ошибок иноверцев.</li>
            <li>Я проповедую его как лишь сцепление (<em>saṃkalā-mātram</em>),</li>
            <li>но неразумные не способны это постичь.</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>106. Тот, для кого порождаемое явление (<em>janyo bhāvaḥ</em>)</li>
            <li>мыслится как существующее где-либо отдельно</li>
            <li>от сцепления (<em>saṃkalāyāḥ pṛthak</em>), —</li>
            <li>должен быть признан сторонником беспричинности (<em>ahetuvādī</em>),</li>
            <li>разрушающим само сцепление (<em>saṃkalāyā vināśakaḥ</em>).</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>107-108. Сцепление (<em>saṃkalā</em>) подобно светильнику:</li>
            <li>оно делает различимыми виды явлений (<em>dravya-jātīnāṃ vyañjakā</em>).</li>
            <li>Если же кто-либо полагает, что какое-либо явление</li>
            <li>существует отдельно от сцепления, —</li>
            <li>то то, что неразумными воображается</li>
            <li>как отделённое от сцепления, —</li>
            <li>лишено собственной природы (<em>asvabhāva</em>),</li>
            <li>нерождённо (<em>anutpanna</em>) и подобно пространству (<em>gaganopama</em>).<a href="#citation-447" id="ref-447" class="citation-mark"><sup>447</sup></a></li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>109. Это и есть «иное» не-возникновение, которое является</li>
            <li>природой достижения Благородных (<em>āryāṇāṃ prāpti-dharmatā</em>).</li>
            <li>Тот, кто постигает это не-возникновение,</li>
            <li>обретает стойкость в постижении не-возникновения (<em>anutpāda-kṣānti</em>).<a href="#citation-448" id="ref-448" class="citation-mark"><sup>448</sup></a></li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>110. Когда весь этот мир видится</li>
            <li>как лишь сцепление (<em>saṃkalā-mātra</em>), —</li>
            <li>«это только сцепление», —</li>
            <li>тогда ум входит в сосредоточение (<em>samādhi</em>).</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>111. Неведение, жажда, карма и прочее —</li>
            <li>это внутреннее сцепление (<em>adhyātmikā saṃkalā</em>).</li>
            <li>Глина, палка, гончарный круг, семя, элементы и прочее —</li>
            <li>это внешнее сцепление (<em>bāhiraṃ</em>).</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>112. Тот, для кого бытие возникает как нечто иное,</li>
            <li>из условий (<em>parataḥ pratyayaiḥ jāyate</em>), —</li>
            <li>для того это не есть лишь сцепление;</li>
            <li>такие не утверждены ни разумом, ни учением (<em>yukti-āgama</em>).<a href="#citation-449" id="ref-449" class="citation-mark"><sup>449</sup></a></li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>113. [Махамати:] — Если порождаемого бытия нет,</li>
            <li>то из какого условия возникает мысль (<em>buddhi</em>)?</li>
            <li>[Будда:] — Они взаимно обусловлены (<em>anyonyapratyayāḥ</em>);</li>
            <li>потому и называются «условиями» (<em>pratyayāḥ</em>).</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>114. Тепло, текучесть, движение, твёрдость —</li>
            <li>так неразумные измышляют «дхармы».</li>
            <li>Но это лишь совокупность условий (<em>kalāpa</em>), а не дхармы;</li>
            <li>потому воистину [всё] лишено собственной природы (<em>niḥsvabhāvatā</em>).</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>115. Подобно тому как врачи, сообразуясь с недугом больного,</li>
            <li>применяют различные способы лечения,</li>
            <li>— но сама наука (<em>śāstra</em>) не разделяется:</li>
            <li>различие существует лишь в недугах (<em>doṣa-bheda</em>).</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>116. Так и Я, [видя] потоки существ (<em>sattva-saṃtāna</em>),</li>
            <li>глубоко поражённые омрачениями (<em>kleśa-doṣa</em>),</li>
            <li>познав силу их способностей (<em>indriya-bala</em>),</li>
            <li>проповедую метод (<em>naya</em>) неразумным (<em>bāliśān</em>).</li>
        </ul>

        <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
            <li>117. Из-за различия в омрачениях (<em>kleśa</em>) и способностях</li>
            <li>Моё учение (<em>śāsana</em>) не распадается на части.</li>
            <li>Единой является Колесница (<em>yānam ekam</em>) —</li>
            <li>Благой Восьмеричный Путь (<em>aṣṭāṅgika-mārga</em>).<a href="#citation-450" id="ref-450" class="citation-mark"><sup>450</sup></a></li>
        </ul>

    </blockquote>

    <p class="text-center font-bold">***</p>

