<p class="my-2" id="citation-323"><sup>323</sup> <em>cittāśrayaparāvṛtti</em><a href="#ref-323" class="citation-back">↩</a></p>
<p class="my-2" id="citation-324"><sup>324</sup> <em>māyādidharmanirābhāsapravicayāvabodha</em> — «постижение через исследование недвойственности магии, сновидений, отражений и прочего, свободной от ментальных образов». Речь идёт о прямом, свободном от образов (<em>nirābhāsa</em>) постижении того, что все явления подобны магическим иллюзиям — без построения этого знания через понятия.<a href="#ref-324" class="citation-back">↩</a></p>
