<p class="my-2" id="citation-335"><sup>335</sup> <em>pañcānantaryāṇi</em> — пять преступлений с немедленным воздаянием (<em>ānantarya</em>) — стандартный список абхидхармы: убийство матери, отца, архата, раскол Сангхи, пролитие крови Татхагаты. Они называются «немедленными», поскольку влекут перерождение в аду Авичи сразу после смерти, без промежуточного существования (<em>antarābhava</em>). <strong><em>Ланкаватара</em></strong> переосмысляет этот список в психологических терминах йогачары.<a href="#ref-335" class="citation-back">↩</a></p>
<p class="my-2" id="citation-336"><sup>336</sup> Убийство архата — игра слов: <em>arhat</em> народная этимология восходит к <em>ari-han</em> — «убивающий врагов» (<em>ari</em> — враг, <em>han</em> — убивать), но здесь «врагами» названы сами спящие склонности (<em>anuśayāḥ</em>), подобные крысиному яду (<em>mūṣikāviṣa</em>), которые внезапно обостряются/вспыхивают (<em>prakopa</em>). Их уничтожение означает прекращение самой возможности проявления клеш.<a href="#ref-336" class="citation-back">↩</a></p>
<p class="my-2" id="citation-337"><sup>337</sup> В обычном смысле <em>saṃghabheda</em> — внесение раскола в монашескую общину. Здесь же игра слов: <em>saṃgha</em> (община) ↔ <em>saṃghāta</em> («сборка», совокупность). Подлинная «община», подлежащая расколу, — это совокупность <em>скандх</em>, воспринимаемая как единое «я».<br>
<em>Bhinna-anyonyalakṣaṇa</em> — «взаимно различные признаки» — указывает, что <em>скандхи</em> (форма, ощущение, восприятие и т.д.) не образуют единого целого, и лишь кажутся таковыми из-за умственного наложения границ.<br>
<em>Atyantamūlopaghāta</em> — «полное разрушение корня» — означает окончательное устранение самой способности ума овеществлять эту сборку. Таким образом, «грех» становится актом освобождения.<a href="#ref-337" class="citation-back">↩</a></p>
<p class="my-2" id="citation-338"><sup>338</sup> <em>svasāmānyabāhyasvacittadṛśyamātra</em> — термин означает: «постижение только общих (<em>sāmānya</em>) характеристик внешнего (<em>bāhya</em>) как того, что является воспринимаемым (<em>dṛśya</em>) собственным умом (<em>svacitta</em>)».<a href="#ref-338" class="citation-back">↩</a></p>
<p class="my-2" id="citation-339"><sup>339</sup> Термин специфичен для <strong><em>Ланкаватары</em></strong>. «Будда-сознание» указывает на то, что природа Будды реализуется через преобразование (<em>parāvṛtti</em>) восьми сознаний и не является внешней сущностью. «Пролитие крови» Будды-сознания — метафора очищения восьми сознаний от злостных воображений, высвобождающего саму возможность этого преобразования.<a href="#ref-339" class="citation-back">↩</a></p>
<p class="my-2" id="citation-340"><sup>340</sup> «Кровь» здесь — злостные воображения (<em>duṣṭavikalpa</em>), омрачающие восемь сознаний. «Пролить кровь Татхагаты» — значит полностью пресечь злостный умысел внутри собственного потока сознания, высвободив тем самым три вида освобождения и непорочное состояние. В этом смысле Будда-сознание (<em>vijñānabuddha</em>) — очищается.<a href="#ref-340" class="citation-back">↩</a></p>
<hr class="my-8 border-t-4 border-gray-500">

<p class="my-2" id="citation-341"><sup>341</sup> Внешние преступления — это буквальное понимание пяти преступлений с немедленным воздаянием: убийство матери, отца и т.д. В отличие от внутренних (<em>ādhyātmika</em>), они относятся к действиям в мире условной истины (<em>saṃvṛti</em>).<a href="#ref-341" class="citation-back">↩</a></p>
<p class="my-2" id="citation-342"><sup>342</sup> <em>nirmitādhiṣṭhānābhisamaya.</em> <em>Nirmita</em> — «проявленное, магически созданное»; <em>adhiṣṭhāna</em> — «благословение, поддержка». В йогачаре <em>adhiṣṭhāna</em> — сила, передаваемая Татхагатой, позволяющая преодолеть кармические блокировки. <em>Nirmita</em> также связано с <em>nirmāṇakāya</em> — проявленным телом Будды, через которое действует эта поддержка.<a href="#ref-342" class="citation-back">↩</a></p>
<p class="my-2" id="citation-343"><sup>343</sup> Раскаяние (<em>kaukṛtya</em>) — здесь не добродетель, как это обычно понимается, а умственное бремя, препятствующее освобождению. Оно становится <em>dṛṣṭi</em> (воззрением), когда ум фиксируется на прошлом действии как на реальности.<a href="#ref-343" class="citation-back">↩</a></p>
<p class="my-2" id="citation-344"><sup>344</sup> <em>dehabhogapratiṣṭhāgativikalpātmātmīyagrāhaviviktadarśana.</em> Термин означает: «видение тела (<em>deha</em>), наслаждений (<em>bhoga</em>), оснований (<em>pratiṣṭhā</em>), путей существования (<em>gati</em>) и различений (<em>vikalpa</em>) как свободных от схватывания «я» и «моего» (<em>ātmātmīyagrāha</em>)».<a href="#ref-344" class="citation-back">↩</a></p>
<p class="my-2" id="citation-345"><sup>345</sup> <em>skandhakadambakaḥ.</em> «Пучок <em>скандх</em>» — образ, подчёркивающий живую, хаотичную природу совокупности <em>скандх</em>. <em>Kadamba</em> — дерево, чьи цветы растут пучками, образуя шар; метафора указывает на множественность, лишённую единства.<a href="#ref-345" class="citation-back">↩</a></p>
<p class="my-2" id="citation-346"><sup>346</sup> <em>nirantara-antara-cchedāt karmasyānantaraṃ bhavet</em><br>
<em>Ānantarya</em> буквально означает «без промежутка» (<em>a-antara</em>): действие влечёт плод без промежуточного состояния (<em>antarābhava</em>) между смертью и следующим рождением. Обычно между действием и его созреванием есть интервал — но пять тяжких преступлений порождают карму такой силы, что она срабатывает немедленно.<br>
Гатха указывает на механизм этой немедленности: <em>скандхи</em> и спящие склонности образуют непрерывный поток (<em>nirantara</em>), и именно разрыв этой непрерывности (<em>antara-ccheda</em>) производит немедленное кармическое следствие. Карма становится <em>ānantarya</em> не сама по себе, она прерывается силой разрушения иллюзии непрерывности <em>скандх</em> и омрачений.<br>
В свете общей логики подглавы: бодхисаттва, совершая «внутренние убийства» — искореняя жажду, неведение и спящие склонности, — создаёт именно такой разрыв. Тем самым разрушительная немедленность кармы оборачивается немедленностью освобождения.<a href="#ref-346" class="citation-back">↩</a></p>
<hr class="my-8 border-t-4 border-gray-500">
<p class="my-2" id="citation-347"><sup>347</sup> <em>Acintyapariṇāma</em> («непостижимое превращение») — процесс глубинного преобразования сознания-хранилища, при котором омрачённые семена замещаются чистыми и ум совершает поворот к своей изначальной природе (<em>parāvṛtti</em>). Он назван «непостижимым», поскольку происходит на уровне, недоступном рассудочному уму: его нельзя ни наблюдать, ни представить как объект.<br><br>
<em>Cyuti</em> («выход, уход») — момент завершения этого превращения: сознание более не удерживается в процессе очищения, его природа полностью преобразована.<br><br>
Если <em>pariṇāma</em> — горение, то <em>cyuti</em> — то, что остаётся, когда всё сгорело — чистый свет.<br><br>
В подглаве 3.2 <em>cyuti</em> означало пробуждение из неокончательной нирваны шравака к дальнейшему пути. Здесь же, в контексте <em>buddhatā</em>, это — окончательный выход в состояние Татхагаты.<a href="#ref-347" class="citation-back">↩</a></p>
<hr class="my-8 border-t-4 border-gray-500">
<p class="my-2" id="citation-348"><sup>348</sup> <em>caturvidhāṃ samatāṃ</em> («четырёхкратное равенство») — ключевой тезис, утверждающий нераздельность всех Татхагат в Таковости, вне категорий времени.<br><br>
• <em>akṣarasamatā</em>: буквы имени «Будда» лишены индивидуальной природы (<em>akṣarasvabhāva</em>) — они общие знаки, не принадлежащие ни одному конкретному существу.<br>
• <em>vāksamatā</em>: речь Дхармы одна и та же у всех Татхагат — выраженная в шестидесяти четырёх качествах чистого голоса (<em>brahmasvara</em>), она звучит без убавления и прибавления, подобно голосу птицы Калавинка.<br>
• <em>kāyasamatā</em>: в Теле Дхармы (<em>dharmakāya</em>) нет различий; в теле формы (<em>rūpakāya</em>) Татхагаты являются по-разному — но лишь сообразно способностям тех, кого надлежит наставить (<em>vaineyavaśa</em>).<br>
• <em>dharmasamatā</em>: все Татхагаты постигли одно и то же — тридцать семь факторов пробуждения; именно это тождество постижения и составляет суть <em>дхарма-саматы</em>.<br><br>
Слова «Я был Кракуччхандой» — прямое выражение этой нераздельности, высказанное из позиции Таковости, где нет ни прошлого, ни последовательности рождений.<a href="#ref-348" class="citation-back">↩</a></p>
<hr class="my-8 border-t-4 border-gray-500">
<p class="my-2" id="citation-349"><sup>349</sup> «Безмолвие есть речь Будды» — парадоксальный тезис, имеющий параллели в <strong><em>Вималакиртинирдеше</em></strong> (молчание Вималакирти как высшее выражение недвойственности) и в чань-буддизме. Здесь он обоснован через два аспекта: личная природа реальности невыразима в словах, и древняя природа дхарм не нуждается в создании — она лишь обнаруживается.<a href="#ref-349" class="citation-back">↩</a></p>
<p class="my-2" id="citation-350"><sup>350</sup> <em>dharmadvaya</em>,«Два аспекта Дхармы» — не следует путать с доктриной двух истин (<em>saṃvṛti/paramārtha</em>). Здесь речь идёт о двух основаниях:<br>— личном (<em>pratyātma</em>), связанном с непосредственным постижением,<br>— и изначальном (<em>paurāṇa</em>), связанном с природой реальности, пребывающей независимо от всякого познания.<a href="#ref-350" class="citation-back">↩</a></p>
<p class="my-2" id="citation-351"><sup>351</sup> <em>akṣaragatidvayavinirmukta</em>: «Свободное от двойственности языковых путей» — указывает на выход за пределы двойственности утверждения и отрицания, выраженной через язык. Буквы и звуки (<em>akṣara</em>) сами по себе не могут выразить Таковость, поскольку принадлежат миру различений.<a href="#ref-351" class="citation-back">↩</a></p>
<p class="my-2" id="citation-352"><sup>352</sup> Этот образ восходит к <strong><em>Саньютта-никае</em></strong> (SN 12.65), где Будда говорит, что он нашёл «древний путь», которым шли будды прошлого, — и не создал его, а лишь обнаружил. <strong><em>Ланкаватара</em></strong> развивает эту метафору, подчёркивая: истина пребывает независимо от её открытия.<a href="#ref-352" class="citation-back">↩</a></p>
<p class="my-2" id="citation-353"><sup>353</sup> Эти три термина образуют нарастающий ряд синонимов для обозначения неизменной природы реальности:<br>tathatā — «таковость»,<br>bhūtatā — «истинность, реальность как таковая»,<br>satyatā — «правдивость, подлинность».<br>Все три указывают на то, что постигается/обнаруживается Буддами не создаётся ими, вечно пребывающее.<a href="#ref-353" class="citation-back">↩</a></p>
<hr class="my-8 border-t-4 border-gray-500">
<p class="my-2" id="citation-354"><sup>354</sup> Двойственность «есть/нет» (<em>asti/nāsti</em>) — корень всех ложных воззрений. В <strong><em>Ланкаватаре</em></strong> она соответствует паре <em>samāropa/apavāda</em> (наложение и отрицание): <em>asti</em> — наложение реальности, <em>nāsti</em> — отрицание после наложения. Обе позиции предполагают <em>svabhāva</em> (собственную природу) у дхарм.<a href="#ref-354" class="citation-back">↩</a></p>
<p class="my-2" id="citation-355"><sup>355</sup> Хотя в тексте используется <em>vivikta</em>, а не <em>śūnya</em>, описываемая позиция соответствует неправильному пониманию <em>шуньяты</em> как абсолютного небытия — именно против такого понимания направлена и <strong><em>Муламадхьямакакарика</em></strong> Нагарджуны (XXIV.1): «Если всё пусто, нет ни возникновения, ни исчезновения — и [тогда] для тебя не существует ни Четырёх Благородных Истин».<a href="#ref-355" class="citation-back">↩</a></p>
<p class="my-2" id="citation-356"><sup>356</sup> Нигилист — не просто «отрицающий», он предполагает реальность того, что отрицает. Если бы страсть существовала, её можно было бы утратить. Но она — лишь проекция ума.<a href="#ref-356" class="citation-back">↩</a></p>
<p class="my-2" id="citation-357"><sup>357</sup> Эта мысль встречается уже в <strong><em>Каччаянасутте</em></strong>, где Будда отвергает обе крайности, но именно нигилизм (<em>ucchedavāda</em>) описывается как более губительный для практики, поскольку он отрицает саму возможность пути.<a href="#ref-357" class="citation-back">↩</a></p>
<p class="my-2" id="citation-358"><sup>358</sup> <em>Śūnyatādṛṣṭi</em> — «воззрение о пустоте/шуньяте» — здесь употреблено в отрицательном смысле как неправильное постижение <em>шуньяты</em>, как её рассудочное понимание, превращающая <em>шуньяту</em> в объект гордости и нигилистическое воззрение. Та же критика содержится в <strong><em>Муламадхьямакакарике</em></strong> (XIII.8): «Победоносные говорили, что <em>шуньята</em> устраняет все воззрения; те же, кто делает <em>шуньяту</em> воззрением, — неизлечимы». Таким образом, <strong><em>Ланкаватара</em></strong> предостерегает от превращения <em>шуньяты</em> в очередное устойчивое рассудочное понятие.<a href="#ref-358" class="citation-back">↩</a></p>
<p class="my-2" id="citation-359"><sup>359</sup> <em>kalpākṣararahitāni prativikalpayan</em> — «воображая [<em>скандхи</em>...] лишёнными мысленных построений и языковых обозначений». Нигилист рассматривает <em>скандхи</em>, <em>дхату</em> и <em>аятаны</em> и думает: они не имеют никакого содержания как понятия/идеи, никаких языковых обозначений — то есть они «чисты» от построений ума. На этом основании он отрицает их мгновенный распад в причинно-следственной цепи, поскольку если <em>скандхи</em> «лишены построений», то и закономерности их изменения не существует. Он полагает, что постиг реальность «по ту сторону слов», но само это полагание есть очередная идея. Подлинная свобода от рассудочных построений не достигается через очередное построение — «всё лишено построений».<a href="#ref-359" class="citation-back">↩</a></p>
<p class="my-2" id="citation-360"><sup>360</sup> <em>Samyakcitta</em> здесь — не «истинное сознание» в смысле <em>jñāna</em>, а ум в его рассудочной, строящей понятия деятельности, даже если она направлена на поиск истинности. Он всё ещё действует через двойственность. Слово <em>nirudhyate</em> не означает уничтожение чего-либо, это успокоение различающей активности (<em>vikalpa</em>) ума, когда объект восприятия исчезает. Это является моментом перехода от <em>vijñāna</em> к <em>jñāna</em>. Само сознание не прекращается, прекращается лишь его привязанность к двойственным построениям.<a href="#ref-360" class="citation-back">↩</a></p>
<hr class="my-8 border-t-4 border-gray-500">
<p class="my-2" id="citation-361"><sup>361</sup> Это различение параллельно тибетской паре <em>nges don / drang don</em> («окончательный смысл» / «интерпретируемый смысл»): одно — непосредственное постижение, другое — наставление, соответствующее уровню слушателей.<a href="#ref-361" class="citation-back">↩</a></p>
<p class="my-2" id="citation-362"><sup>362</sup> <em>navāṅgaśāsana</em> — девять жанров буддийского Писания: <em>утра, гейя, вьякарана, гатха, удана, итивуттака, джатака, абхутадхарма, ведалла</em> (или <em>вайпулья</em>). Список варьируется в зависимости от традиции: в палийской канонической классификации девятым жанром является <em>ведалла</em> (диалоги-катехизисы), в махаянских источниках часто используется <em>вайпулья</em> («пространные» сутры, включая <strong><em>Ланкаватару</em></strong>).<a href="#ref-362" class="citation-back">↩</a></p>
<p class="my-2" id="citation-363"><sup>363</sup> Ствол бананового дерева — метафора пустотности: слои снимаются один за другим, и в центре ничего нет.<a href="#ref-363" class="citation-back">↩</a></p>
<hr class="my-8 border-t-4 border-gray-500">
<p class="my-2" id="citation-364"><sup>364</sup> <em>abhūta-parikalpa</em> — «ложное построение несуществующего», «воображение несуществующего»; механизм познания, создающий иллюзию разделения единого опыта на внутреннего субъекта и внешний мир. Согласно <strong><em>Ланкаватаре</em></strong>, это творческая активность ума, которая наделяет пустотные образы ложной плотностью и именами. Постичь обманчивое воображение означает увидеть, что вся грандиозная архитектура вселенной соткана из самих действий различения. Когда этот процесс «построения» затихает, сознание перестает воплощать двойственность и возвращается к своей изначальной чистоте — Только-сознанию.<a href="#ref-364" class="citation-back">↩</a></p>
<p class="my-2" id="citation-365"><sup>365</sup> <em>arthavividhavaicitryābhūtaparikalpābhiniveśāt</em><a href="#ref-365" class="citation-back">↩</a></p>
<p class="my-2" id="citation-366"><sup>366</sup> <em>santāsantavicitrabhāvābhiniveśāt</em><a href="#ref-366" class="citation-back">↩</a></p>
<p class="my-2" id="citation-367"><sup>367</sup> <em>viṣama-hetu</em> — «порочная/несоразмерная причина» — термин индийской логики, обозначающий несостоятельную причину, действующую неравномерно, указывает на логическую ошибку, при которой одна и та же причина порождает противоречивые или избирательные следствия. Вопрос Махамати: если различение действует в одних случаях и не действует в других, оно не может быть надёжной причиной. На что Будда отвечает, что различение вообще не действует — оно лишь кажется действующим.<a href="#ref-367" class="citation-back">↩</a></p>
<p class="my-2" id="citation-368"><sup>368</sup> <em>lokāyatika</em> — школа <em>cārvāka</em> / <em>lokāyata</em> — индийский материализм, отрицавший карму, перерождение и освобождение. Упоминание здесь указывает: позиция, допускающая основополагающее различие между двумя случаями действия причины, скатывается к материалистической предопределённости.<a href="#ref-368" class="citation-back">↩</a></p>
<p class="my-2" id="citation-369"><sup>369</sup> <em>anyatra mahāmate bālānāṃ svacittavaicitryavikalpakalpitam</em><a href="#ref-369" class="citation-back">↩</a></p>
<p class="my-2" id="citation-370"><sup>370</sup> «Активность, предшествующая различению» — указание на то, что различение возникает не из ничего, а из кармической активности, уже заложенной в потоке сознания. В контексте системы трёх <em>природ</em> это указывает на уровень зависимой природы (<em>paratantra-svabhāva</em>).<a href="#ref-370" class="citation-back">↩</a></p>
<p class="my-2" id="citation-371"><sup>371</sup> Гатхи 20–33 тезисно выражают учение о <em>vijñaptimātratā</em> (Только-сознании):<br>
• Четыре крайности (<em>catuṣkoṭi</em>) отбрасываются как непригодная основа для понимания мира.<br>
• Причины и условия (<em>hetu-pratyaya</em>) оказываются следствиями (<em>kārya</em>), лишёнными самостоятельной природы; их бесконечная цепь указывает на отсутствие первопричины.<br>
• «Только» (<em>mātra</em>) означает пребывание в собственной природе (<em>svabhāva-saṃsthāna</em>), где разделение на субъект и объект уже не возникает.<br>
• Таковость — предел постижения <em>шуньяты</em>, <em>нирвана</em>, <em>дхармадхату</em>, <em>маномайя-кайя</em> — разные имена одной реальности, раскрывающейся в различных аспектах.<br>
• Мирское Только-сознание — проявление ума, воспринимаемое как внешнее под влиянием отпечатков различений (<em>vikalpa-vāsanā</em>).<br>
• Освобождение — распознавание того, что всё видимое уже есть проявление ума, свободного от наложения (<em>samāropa</em>) и отрицания (<em>apavāda</em>).<a href="#ref-371" class="citation-back">↩</a></p>
<hr class="my-8 border-t-4 border-gray-500">
<p class="my-2" id="citation-372"><sup>372</sup> <em>trisaṅga</em> («три привязанности») — в йогачаре под <em>trisaṅga</em> понимаются три корневые привязанности:<br>
• к чувственным желаниям (<em>kāmarāga</em>),<br>
• к существованию (<em>bhavarāga</em>),<br>
• к неведению (<em>avidyā</em>).<br>
Именно они порождают циклический поток сознания.<a href="#ref-372" class="citation-back">↩</a></p>
<p class="my-2" id="citation-373"><sup>373</sup> <em>aprāpti</em> («недостижимость») — термин указывает на отсутствие субъект-объектной структуры: мудрость не может быть «достигнута», потому что в ней нет «достижимого» и «достигающего». Она подобна отражению луны в воде — видима, но несхватываема.<a href="#ref-373" class="citation-back">↩</a></p>
<p class="my-2" id="citation-374"><sup>374</sup> «Две колесницы» (<em>yānadvaya</em>) — путь шраваков и путь пратьекабудд. Подлинная мудрость Татхагаты свободна от обеих, поскольку не ограничена ни анализом признаков, ни личным освобождением.<a href="#ref-374" class="citation-back">↩</a></p>
<hr class="my-8 border-t-4 border-gray-500">
<p class="my-2" id="citation-375"><sup>375</sup> <em>pariṇāmavāda</em> — общее обозначение для индийских философских систем, утверждающих, что мир возникает через реальное преобразование первоначала (<em>prakṛti, brahman, paramāṇu</em> и т.д.). Наиболее известны санкхья (где <em>prakṛti</em> превращается в <em>vikāra</em>) и некоторые направления вайшешики. <strong><em>Ланкаватара</em></strong> отвергает все девять видов <em>pariṇāmavāda</em>, поскольку они предполагают реальное бытие (<em>sadbhāva</em>) как основу превращения — что противоречит учению о всего лишь воспринимаемом собственным умом (<em>vijñaptimātratā</em>).<a href="#ref-375" class="citation-back">↩</a></p>
<p class="my-2" id="citation-376"><sup>376</sup> Этот пример часто используется в индийской философии (особенно в веданте) для иллюстрации <em>vivartavāda</em>: золото (вещество) неизменно, меняются лишь его формы. <strong><em>Ланкаватара</em></strong> использует тот же образ, но с обратным выводом: ни золото, ни его формы не существуют самостоятельно — оба суть лишь воспринимаемое собственным умом (<em>svacittadṛśyamātra</em>).<a href="#ref-376" class="citation-back">↩</a></p>
<p class="my-2" id="citation-377"><sup>377</sup> <em>vandhyāputra</em> («сын бесплодной женщины») и <em>mṛtajanma</em> («рождение мёртвого») — классические буддийские и найяйские примеры абсолютно невозможных явлений. В логике они иллюстрируют, что слова могут существовать без соответствующих объектов. В контексте сновидения, о котором говорит текст, оба образа подчёркивают одно: кажимость возникновения не требует чего-то реального — даже во сне может «родиться» то, что невозможно в принципе.<a href="#ref-377" class="citation-back">↩</a></p>
<hr class="my-8 border-t-4 border-gray-500">
<p class="my-2" id="citation-378"><sup>378</sup> <em>saṃdhi</em> означает одновременно «узел, сочленение» и «скрытый смысл» (<em>saṃdhyābhāṣā</em> — «язык сумерек» в тантре). Здесь используется первое значение: узел привязанности, стягивающий поток сознания.<a href="#ref-378" class="citation-back">↩</a></p>
<p class="my-2" id="citation-379"><sup>379</sup> Стандартная буддийская метафора самоопутывания построениями понятий. Червь сам прядёт кокон, из которого не может выбраться.<a href="#ref-379" class="citation-back">↩</a></p>
<p class="my-2" id="citation-380"><sup>380</sup> Три вида освобождения (<em>vimokṣatraya</em>): <em>шуньята</em> (<em>śūnyatā</em>), без-признаковость (<em>animitta</em>) и не обусловленность желанием (<em>apraṇihita</em>).<a href="#ref-380" class="citation-back">↩</a></p>
<p class="my-2" id="citation-381"><sup>381</sup> «Три корня самозапутывания:<br>
— <em>bhāva-grāha</em>: цепляние за/схватывание бытия — вера в то, что явления реально существуют («это реально»);
— <em>jñāna-grāha</em>: цепляние за/схватывание познания — вера в то, что ум может постичь истину как объект («я это понял»);
— <em>ruta-grāha</em>: цепляние за/схватывание речи — вера в то, что слова отражают реальность («это слово — истина»).
Эти три захвата — нити, которыми невежда опутывает себя, подобно шелковичному червю».<a href="#ref-381" class="citation-back">↩</a></p>
<hr class="my-8 border-t-4 border-gray-500">
<p class="my-2" id="citation-382"><sup>382</sup> Этот фрагмент снимает возможное нигилистическое прочтение доктрины <em>parikalpita</em>: если всё воображаемо, то, казалось бы, нет ни загрязнения, ни очищения, ни пути. На что Будда отвечает: воображаемость — характеристика способа познания невежд, она не есть абсолютная характеристика реальности. Благородные постигают ту же самую реальность через благородное знание (<em>āryajñāna</em>) — и это постижение не является «воображаемым» в том же смысле, как у невежд.<a href="#ref-382" class="citation-back">↩</a></p>
<p class="my-2" id="citation-383"><sup>383</sup> В этом отрывке аргумент Махамати трёхступенчатый:<br>
Первая ступень: если реальность постигается только Благородными, обычные люди не могут совершить поворот различения — им недоступна та точка зрения, с которой нужно увидеть.<br>
Вторая ступень: но и Благородные воображают объекты — значит и их постижение является <em>parikalpita</em>. Возникает бесконечный регресс: каждый уровень постижения оказывается воображаемым с точки зрения более высокого.<br>
Третья ступень: выход — либо признать, что утверждение «всё не таково, каким воображается» — лишь педагогический приём (<em>upāya</em>), а не основополагающее утверждение.<br>
Последний вопрос Махамати — «или же это говорится лишь ради поворота вспять различения?» — это фактически подсказка ответа, который Будда подтвердит.<br>
Прослеживается сходство с рассуждениями Канта: он различает явление (Erscheinung) и вещь-в-себе (Ding an sich), которая принципиально недоступна познанию. Махамати формулирует аналогичную проблему: если реальность такова, какой её видят Благородные, но недоступна обычному познанию — возникает та же пропасть познания. Будда, в отличие от Канта, не оставляет вещь-в-себе за скобками, он указывает на путь преодоления «кажущейся дистанции» через преображение самого познающего.<a href="#ref-383" class="citation-back">↩</a></p>
<p class="my-2" id="citation-384"><sup>384</sup> <em>utrāsapada</em> («почва для страха») — это страх перед нигилизмом: слушатели, привязанные к реальности вещей, боятся, что учение о <em>parikalpita</em> уничтожает всякую основу для пути и освобождения. Поэтому Будда использует язык «природы объекта благородного знания» как <em>упайю</em>, как педагогический мост между привязанным умом и свободой.<a href="#ref-384" class="citation-back">↩</a></p>
<hr class="my-8 border-t-4 border-gray-500">
<p class="my-2" id="citation-385"><sup>385</sup> В индийской логике <em>pratijñā</em> — первая часть силлогизма, тезис. Будда указывает на парадокс: как только произносится «все дхармы не рождены», ум слушателя овеществляет это утверждение. Оно становится объектом веры, то есть рождённой дхармой — и тем самым опровергает само себя. Далее возникает парадокс самоотсылки: если «всё не рождено», то и само это утверждение не рождено. Но тогда оно не существует как высказывание. Если же оно существует — оно возникло, и утверждение ложно. Любой выход из этой ловушки разрушает тезис. Чтобы не вязнуть в разрастании цепочки понятий (<em>prapañca</em>), бодхисаттва выходит за рамки ограничений логики тезисов.<a href="#ref-385" class="citation-back">↩</a></p>
<p class="my-2" id="citation-386"><sup>386</sup> Вместо определений реальности Будда предлагает метафору магии и сна: они признают видимость (мир есть), но отрицают его вещественность (он пуст). Это защищает ум от двух крайностей: нигилизма («ничего нет») и реализма («всё реально»).<a href="#ref-386" class="citation-back">↩</a></p>
<p class="my-2" id="citation-387"><sup>387</sup> <em>Śavabhūta</em> («подобные мертвецам») — резкий, шокирующий образ. Ум лже-логика забит мёртвыми идеями-понятиями: <em>svabhāva</em>, <em>vijñapti</em>, <em>vastu</em>, <em>ālaya</em> — все они превращены в застывшие объекты. Даже <em>Алайя</em>, если понимать её как «реальное хранилище», становится мёртвым понятием, закрывающим живую Таковость.<a href="#ref-387" class="citation-back">↩</a></p>
<p class="my-2" id="citation-388"><sup>388</sup> Это утверждение служит педагогическим инструментом для опровержения взглядов тиртхиков, утверждающих реальное рождение вещей. Как только цель достигнута, инструмент следует отложить.<a href="#ref-388" class="citation-back">↩</a></p>
<p class="my-2" id="citation-389"><sup>389</sup> Это тончайшая вибрация зарождения понятийных образов — движение ума, предшествующее оформленной мысли. Даже после отбрасывания грубых различений в уме остаётся это микродвижение. Бодхисаттвы преодолевают и его, входя в состояние <em>avikalpa</em> — недвойственной тишины, свободной от признаков (<em>nirābhāsa</em>).<a href="#ref-389" class="citation-back">↩</a></p>
<p class="my-2" id="citation-390"><sup>390</sup> Nirābhāsa — не «все объекты исчезли». Йогин не достигает без-образности через простое отрицание вещей — это было бы лишь новой формой привязанности, теперь к небытию. Плод Благородных рождается из <em>samatā</em> — равенства в отношении бытия и небытия. Бытие и небытие зрятся как равные, лишённые признаков — и именно это равенство, а не отрицание, есть основа без-образности.<a href="#ref-390" class="citation-back">↩</a></p>
<p class="my-2" id="citation-391"><sup>391</sup> Когда ум перестаёт разделять внешнее и внутреннее в их движении (<em>cala</em>), наступает <em>samatācittadarśana</em> — видение ума в состоянии равенства. Это прекращение двойственного движения ума, когда он перестаёт порождать различение «здесь — там», «моё — чужое», «бытие — небытие».<a href="#ref-391" class="citation-back">↩</a></p>
<hr class="my-8 border-t-4 border-gray-500">
<p class="my-2" id="citation-392"><sup>392</sup> <em>Cittamātra</em> («только-ум») указывает на сущность (<em>svabhāva</em>): всё есть ум. <em>Vijñaptimātra</em> («только-проявление») указывает на явление (<em>lakṣaṇa</em>): всё есть проявление ума. Оба термина описывают одну реальность с двух сторон — как то, что есть, и как то, что видится. <em>Cittamātra</em> отрицает внешнюю материю; <em>vijñaptimātra</em> отрицает реальность объекта восприятия как независимого от ума. Первое направлено против реализма, второе — против двойственности субъекта и объекта.<a href="#ref-392" class="citation-back">↩</a></p>
<p class="my-2" id="citation-393"><sup>393</sup> Махамати перечисляет четыре стандартных буддийских случая, когда познание не обнаруживает объект: неспособность различить, подавление природой объекта, физические преграды и дефекты чувств. Все четыре в абхидхарме квалифицируются как <em>ajñāna</em> — невежество. Будда предлагает пятый случай, принципиально иной: познание не находит объекта, потому что постигло, что внешнего объекта как такового нет. Это не является формой невежества, это грань высшего знания.<a href="#ref-393" class="citation-back">↩</a></p>
<hr class="my-8 border-t-4 border-gray-500">
<p class="my-2" id="citation-394"><sup>394</sup> Для Будды «красивая речь» без прозрения — это <em>bāla-pralāpa</em> (детский лепет). Локаятики (материалисты) — мастера логических ловушек и софизмов. Они могут победить в споре даже богов, но их победа пуста, так как она не меняет <em>āśraya</em> (основу сознания). Они лишь «переставляют мебель в тёмной комнате».<a href="#ref-394" class="citation-back">↩</a></p>
<p class="my-2" id="citation-395"><sup>395</sup> Общение с такими учителями даёт <em>āmiṣa</em>: признание, славу, интеллектуальное превосходство. Но это лишь усиливает <em>saṃdhi</em> (узлы) привязанности. Истинная Дхарма — это <em>vikalpasya vyāvṛtti</em> (поворот различения), который локаятикам недоступен.<a href="#ref-395" class="citation-back">↩</a></p>
<p class="my-2" id="citation-396"><sup>396</sup> Индра считался величайшим знатоком грамматики и автором «учения о звуках» (<em>śabda-śāstra</em>). Один из его учеников, приняв облик нага, явился в небесное собрание и бросил вызов учителю. Наг предложил состязаться, используя исключительно методы локаятиков — древнеиндийских материалистов, отрицавших всё нематериальное. Хотя Индра был богом и создателем правил языка, наг обратил саму структуру логики против неё самой. Небесная колесница Индры — символ божественного порядка — рассыпалась, когда были разрушены его последние доводы.<br>Эта притча показывает: любая система, построенная на словах, может быть разрушена другой системой слов. Даже «царь богов» бессилен перед скептицизмом, если опирается лишь на интеллект, а не на прямое постижение реальности.<a href="#ref-396" class="citation-back">↩</a></p>
<p class="my-2" id="citation-397"><sup>397</sup> Будда даёт точное определение материализма: это фиксация на теле, рассудке и объектах. Это — буддийское определение <em>lokāyata</em> как системы, ограниченной тремя уровнями — телесным, интеллектуальным и объектным, — и не признающей ни кармы, ни перерождения, ни освобождения.<a href="#ref-397" class="citation-back">↩</a></p>
<p class="my-2" id="citation-398"><sup>398</sup> <em>Āya-vyaya</em> («прибыль и убыток») — базовая пара локаятиков: реальность есть накопление (<em>āya</em>) и рассеивание (<em>vyaya</em>) материальных элементов. Будда заменяет эту пару на <em>anāyavyaya</em> — «свободное от прихода и ухода» — что является синонимом <em>anutpāda</em> («не-возникновение»). Тем самым он переворачивает саму основу материализма: там, где локаятик видит движение материи, Будда указывает на отсутствие самого основания этого движения.<a href="#ref-398" class="citation-back">↩</a></p>
<hr class="my-8 border-t-4 border-gray-500">
<p class="my-2" id="citation-399"><sup>399</sup> Существование промежуточного состояния между смертью и новым рождением было предметом споров в абхидхарме: сарвастивада признавала <em>antarābhava</em>, тхеравада отрицала. Будда здесь не даёт прямого ответа — вопрос о нём относится к категории локаяты, то есть построений понятий, не ведущих к освобождению.<a href="#ref-399" class="citation-back">↩</a></p>
<p class="my-2" id="citation-400"><sup>400</sup> Классическое определение взаимозависимого возникновения подразумевает внешнюю причинно-следственную цепь. Здесь же Будда описывает <em>pratītyasamutpāda</em> как само различение (<em>vikalpa</em>), проявляющегося в форме субъект-объектной двойственности, как структуру самого ума.<a href="#ref-400" class="citation-back">↩</a></p>
<p class="my-2" id="citation-401"><sup>401</sup> Итоговое высказывание Будды — самое радикальное во всём диалоге. Он отвергает не только позиции брахмана, но и собственные доктрины — собственные и общие признаки (<em>svalakṣaṇa-sāmānyalakṣaṇa</em>), карму, неведение, жажду — как только они становятся объектом привязанности к идеям.<br>Эти доктрины сами по себе верны. Однако любая мысль, пытающаяся что-то утвердить или опровергнуть о природе мира, есть <em>mano-vispandita</em> — трепетание ума в различении субъекта и объекта. Пока это трепетание длится, мы находимся в локаяте — независимо от того, какими терминами оперируем: "карма", "шуньята" или "только-сознание". Выход — в прекращении самого вопрошания через постижение того, что всё воспринимаемое есть лишь проявление собственного ума.<a href="#ref-401" class="citation-back">↩</a></p>
<p class="my-2" id="citation-402"><sup>402</sup> «Не-локаята» — единственное, видимо, место в <strong><em>Ланкаватаре</em></strong>, где Будда даёт позитивное определение своего учения через противопоставление локаяте. Примечательно, что «не-локаята» тоже выражается в словах и знаках — Будда прямо признаёт это. Её сущность — прекращение самого различения (<em>vikalpasya apravṛtti</em>): когда различение «пребывает в своём месте» (<em>svasthāne avatiṣṭhate</em>), оно перестаёт устремляться к объектам и порождать субъект-объектную двойственность. Именно поэтому разум тиртхиков, привязанных к внешнему бытию, в неё не проникает.<br>По существу, «не-локаята» соответствует <em>siddhāntanaya</em> из подглавы 3.17 — методу высшей истины, свободному от утверждений о природе внешней реальности.<a href="#ref-402" class="citation-back">↩</a></p>
<hr class="my-8 border-t-4 border-gray-500">
<p class="my-2" id="citation-403"><sup>403</sup> Для локаятика существует только то, что воспринимается здесь и сейчас. Отрицая «иной мир», он пытается свести всякую реальность к непосредственно данному. Будда опровергает его одним вопросом: сам факт твоего прихода из другого места означает, что это место — «иной мир». <em>Loka</em> — это не географическая точка, а горизонт восприятия. Переместившись, ты уже признал существование того, что было за пределами твоего прежнего горизонта.<a href="#ref-403" class="citation-back">↩</a></p>
<p class="my-2" id="citation-404"><sup>404</sup> Наг исчезает уличённым, но его внутренний монолог примечателен: он верно понял суть учения Будды. Пренебрежительное «жалкий» (<em>varāka</em>) выдаёт не непонимание, а раздражение: учение о <em>svacitta-dṛśya</em> обесценивает всю его диалектику. Зачем строить сложные аргументы о мирах, если любой «мир» — лишь проявление собственного различения? Понять это умом и постичь через преобразование основы сознания (<em>āśrayaparāvṛtti</em>) — совершенно разные вещи. Наг сделал только первое, и именно поэтому он исчез, не задав главного вопроса.<a href="#ref-404" class="citation-back">↩</a></p>
<hr class="my-8 border-t-4 border-gray-500">
<p class="my-2" id="citation-405"><sup>405</sup> <em>Āmiṣa</em> — «кусок мяса», «наживка» — то, что привлекает, но таит крючок. Будда описывает её через нарастающую цепочку:<br>прикосновение (<em>āmṛśa</em>) → притяжение (<em>ākarṣaṇa</em>) → приятное ощущение (<em>nirmṛṣa</em>) → захват (<em>parāmṛṣṭi</em>) → вкус (<em>svāda</em>) → привязанность к внешним объектам → впадение в крайности.<br>Это точное описание того, как работает ловушка: ум сначала касается объекта, затем тянется к нему, затем прилипает. Каждый шаг кажется невинным — но в итоге ум оказывается накрепко привязан к колесу рождений.<a href="#ref-405" class="citation-back">↩</a></p>
<p class="my-2" id="citation-406"><sup>406</sup> Изысканные речи локаятика — тоже наживка. Они дают уму ложное чувство понимания и остроту спора. Это <em>svāda</em> на уровне интеллекта: приятный вкус превосходства в манипулировании идеями и построением понятий. Но за этим вкусом скрывается то же самое — привязанность к внешним объектам, теперь уже в форме идей. В итоге вместо <em>apravṛtti</em> (прекращения различения) — новый виток <em>jāti-jarā-maraṇa</em> (рождение-старость-смерть).<a href="#ref-406" class="citation-back">↩</a></p>
<p class="my-2" id="citation-407"><sup>407</sup> Будда описывает Дхарму как последовательное разрушение рассудочных построений.<br>Первые два пункта — постижение двойного отсутствия «я» и прекращение различения — относятся к уровню воззрения.<br>Третий пункт — <em>citta-mano-vijñāna-vyāvṛtti</em> — это уже не улучшение работы ума, а радикальный поворот самой его основы: ум перестаёт делить мир на субъект и объект.<br>Четвёртый и пятый — вхождение в поток мудрости Будд и отказ от всякой опоры в виде умозрительных положений (<em>anadhiṣṭhā-pada</em>).<br>Шестой — <em>anābhoga-vaśavartitā</em> — спонтанное владычество: бодхисаттва действует без усилия, подобно солнцу, что светит без намерения светить.<a href="#ref-407" class="citation-back">↩</a></p>
<p class="my-2" id="citation-408"><sup>408</sup> Будда вскрывает логику, порождающую две крайности:<br>Отрицание причин заставляет считать вещи обладающими собственной природой — отсюда воззрение о вечности (<em>śāśvata</em>).<br>Признание причин без признания их следствий разрушает всякую связность — отсюда воззрение об уничтожении (<em>uccheda</em>).<br>Срединный путь — видение возникновения, пребывания и распада (<em>utpāda-sthiti-bhaṅga</em>) как они есть, без приписывания им крайностей.<a href="#ref-408" class="citation-back">↩</a></p>
<p class="my-2" id="citation-409"><sup>409</sup> «Причина и следствие» — язык наставления (<em>deśanānaya</em>) для незрелых умов. В высшей истине (<em>siddhānta</em>) нет реального порождения одного другим: есть лишь недвойственное проявление ума. Принять причинность как факт — значит принять реальность внешних объектов и времени. Это и есть основа Локаяты.<a href="#ref-409" class="citation-back">↩</a></p>
<p class="my-2" id="citation-410"><sup>410</sup> Это самое ёмкое определение во всём разделе. Локаята — это не «плохая философия», это сам процесс движения различающего ума к объекту. Пока ум движется (<em>pravartate</em>) в сторону объекта, он по определению находится в мирском различении. <em>Apravṛtti</em> — не-развёртывание — это когда ум «пребывает в своём месте» (<em>svasthāne avatiṣṭhate</em>, подглава 3.19) и видит мир не как внешнюю среду, а как проявление собственного сознания (<em>svacitta</em>).<a href="#ref-410" class="citation-back">↩</a></p>
