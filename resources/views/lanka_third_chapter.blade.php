    <p class="my-2" id="citation-447"><sup>447</sup> Гатхи 107–108 образуют синтаксически незавершённую конструкцию — по всей видимости, лакуна в рукописной традиции. Смысл восстанавливается из контекста: тот, кто полагает явления отдельными от связи условий, впадает в заблуждение о независимом существовании.<a href="#ref-447" class="text-blue-500 hover:underline ml-2">↩</a></p>

    <p class="my-2" id="citation-448"><sup>448</sup> <em>Anutpādakṣānti</em> — «терпение к не-возникновению» — высшее постижение бодхисаттвы: способность пребывать в осознании нерождённости всех явлений без страха и смятения.<a href="#ref-448" class="text-blue-500 hover:underline ml-2">↩</a></p>

    <p class="my-2" id="citation-449"><sup>449</sup> <em>Yuktyāgama</em> — «логика и предание» — два источника достоверного знания: рациональное рассуждение (<em>yukti</em>) и авторитетное наставление (<em>āgama</em>). Тот, кто признаёт рождение явлений из внешних причин, противоречит обоим.<a href="#ref-449" class="text-blue-500 hover:underline ml-2">↩</a></p>

    <p class="my-2" id="citation-450"><sup>450</sup> Гатхи 115–117 образуют единый аргумент: многообразие учений Будды — не противоречие, оно является следствием различия способностей существ. Как врач применяет разные средства при разных болезнях, так и Будда проповедует по-разному — но его учение едино. Единая колесница (<em>ekayāna</em>) — благой восьмеричный путь (<em>āryāṣṭāṅgikamārga</em>). Гатхи 86-117 практически дословно совпадают с гатхами 581-613 десятой главы. В примечаниях к ним дан более подробный комментарий.<a href="#ref-450" class="text-blue-500 hover:underline ml-2">↩</a></p>

