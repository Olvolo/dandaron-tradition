<h4 class="text-center text-blue-800 font-bold text-xl sm:text-xl md:text-xl mt-4 mb-4">Подглава 3.28 (28. О непостоянстве)</h4>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>Затем Бодхисаттва-махасаттва Махамати вновь спросил Благословенного:</p>
    <p>— О Благословенный, «непостоянство, непостоянство» — так воображают все тиртхики. И Ты в своих наставлениях учишь: «О, непостоянны обусловленные вещи (<em>saṃskārā</em>), их природа — возникновение и распад». Так истинно это или ложно, Благословенный? И скольких видов бывает непостоянство?</p>

    <p>Благословенный ответил:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>— Махамати, тиртхики воображают восемь видов непостоянства, но Я учу иначе. Каковы эти восемь видов?</li>
        <li>• Некоторые, Махамати, говорят: непостоянство — это прекращение начатого (<em>prārambha-vinivṛtti</em>). «Начало» для них — это возникновение; его отсутствие — непостоянство.</li>
        <li>• Другие описывают непостоянство как исчезновение формы (<em>saṃsthāna-vinivṛtti</em>).</li>
        <li>• Иные считают, что сама форма (<em>rūpa</em>) непостоянна.</li>
        <li>• Другие — что непостоянно видоизменение формы.</li>
        <li>• Иные полагают, что все дхармы распадаются в непрерывном потоке мгновений собственной силой — подобно превращению молока в простоквашу; они зрят исчезновение в каждом объекте и говорят: «Нет вечности».</li>
        <li>• Другие воображают непостоянством само бытие (<em>bhāva</em>).</li>
        <li>• Иные — бытие и небытие (<em>bhāvābhāva</em>).</li>
        <li>• Другие — не-возникновение (<em>anutpāda</em>) всех дхарм, полагая, что непостоянство включено в него.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Под «непостоянством бытия и небытия», Махамати, они понимают следующее: исчезновение собственных признаков первоэлементов и производных от них не обнаруживается, и природа первоэлементов не развёртывается далее.</li>
        <li>Под «непостоянством не-возникновения» они понимают следующее: все дхармы не видятся ни как существующие, ни как несуществующие — даже при анализе вплоть до атомов. Это лишь иное имя для не-возникновения, но не для [реального] возникновения.</li>
        <li>Таков, Махамати, признак непостоянства не-возникновения. Из-за его непонимания все тиртхики впадают в [ложное] учение о непостоянстве возникновения.<a href="#citation-451" id="ref-451" class="citation-mark"><sup>451</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Кроме того, Махамати, для того, кто считает само бытие вечным, непостоянство [в его понимании] — это лишь плод воображения, а не реальность. Почему? Потому что само непостоянство не уничтожается.</li>
        <li>Если здесь, Махамати, небытие всех явлений является следствием работы «непостоянства», то небытие явлений невозможно без участия этого «непостоянства» — подобно паре разбиваемого и разбивающего — палки, камня или молота. Мы видим здесь неразрывную связь. Стало быть, непостоянство — это причина, а небытие явлений — следствие.</li>
        <li>Но между причиной и следствием нет различия: «вот это непостоянство, а вот это — его результат». Раз нет различия между причиной и следствием, то все явления [парадоксальным образом] оказываются вечными, так как у их бытия нет [отдельной от них] причины. Ведь небытие всех явлений, Махамати, само оказывается беспричинным.</li>
        <li>Этого не понимают невежды и обычные люди. Причина не может породить следствие, которое ей совершенно не подобно. А если бы порождала, то непостоянство явлений было бы следствием, не имеющим отношения к причине, и различие между причиной и следствием исчезло бы. Но [тиртхики] видят это различие.</li>
        <li>Если бы непостоянство было самим «небытием», оно подпадало бы под признаки действия и причины, или было бы завершённым как единое во всех явлениях. Но если оно обладает признаком действия и причины, то само непостоянство оказывается вечным; а раз оно вечно, то и все [подвластные ему] явления должны быть вечными.<a href="#citation-452" id="ref-452" class="citation-mark"><sup>452</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Если же непостоянство [как некая сила] заключено внутри всех явлений, то оно должно быть подвластно трём временам (<em>tryadhva-patita</em>).</li>
        <li>Но то, что было формой (<em>rūpa</em>) в прошлом, погибло вместе с тем [прошлым]. Будущее же ещё не возникло. А поскольку форма не возникает [из ничего], то и в настоящем она не имеет отличного от себя признака [непостоянства].</li>
        <li>Форма — это лишь особый способ сочетания первоэлементов (<em>bhūta</em>). Но природа первоэлементов и производных от них не гибнет, поскольку они свободны от [отношений] тождества и различия.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>У всех тиртхиков [по их предположению] первоэлементы не уничтожаются; из них состоит весь тройственный мир, в котором лишь воображаются (<em>prajñapyate</em>) возникновение, пребывание и видоизменение. Что же ещё может быть «непостоянным» помимо первоэлементов и производных от них, для чего тиртхики воображают непостоянство? Ведь сами элементы, [по их убеждению], не приходят в движение и не прекращаются — в силу укоренённости [тиртхиков] в признаках собственной природы [первоэлементов].<a href="#citation-453" id="ref-453" class="citation-mark"><sup>453</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>В этом [учении] непостоянство как не-начало (<em>prārambhavinivṛtti</em>) означает следующее: первоэлементы не порождают друг друга, поскольку их взаимно несхожие собственные признаки не дают никакого основания для «начала». Поскольку такого основания нет и никакого начала не возникает — по этим двум соображениям у тиртхиков рождается представление о непостоянстве.<a href="#citation-454" id="ref-454" class="citation-mark"><sup>454</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>В этом [учении] непостоянство как исчезновение формы (<em>saṃsthāna-vinivṛtti</em>) означает следующее: первоэлементы и производное от них (<em>bhūta-bhautika</em>) не гибнут вплоть до момента [окончательного] распада (<em>pralaya</em>).</li>
        <li>Под «распадом», Махамати, [они понимают] исследование и анализ вплоть до атома (<em>paramāṇu</em>); это — разрушение формы первоэлементов и производного от них. Из-за видения изменения формы [они перестают] обнаруживать «длинное» или «короткое».</li>
        <li>Однако [они полагают, что] в самих атомах-первоэлементах разрушения не происходит. Из-за видения [лишь] исчезновения формы первоэлементов они впадают в учение Санкхьи (<em>sāṃkhyavāda</em>).<a href="#citation-455" id="ref-455" class="citation-mark"><sup>455</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>В этом [учении] непостоянство формы (<em>saṃsthāna-anityatā</em>) означает следующее: для того, кто считает непостоянной лишь саму форму, непостоянство относится к ней, но не к первоэлементам (<em>bhūta</em>).</li>
        <li>Ведь если бы и первоэлементы были непостоянны, то мирское взаимодействие (<em>loka-saṃvyavahāra</em>) стало бы невозможным. А при невозможности мирского взаимодействия [учитель] впал бы в воззрение локаятиков (нигилистов), полагая все вещи лишь пустым звуком (<em>vāgmātra</em>), не признавая их реально возникающими в своих собственных признаках.<a href="#citation-456" id="ref-456" class="citation-mark"><sup>456</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>В этом [учении] непостоянство как видоизменение (<em>vikāra-anityatā</em>) означает следующее: [утверждается], что видится иное состояние формы (<em>rūpa</em>), но не самих первоэлементов (<em>bhūta</em>), — подобно тому как зрят видоизменения формы золотых украшений. Само золото не гибнет как сущность (<em>bhāva</em>), гибнет лишь форма украшения.<a href="#citation-457" id="ref-457" class="citation-mark"><sup>457</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>И другие [учения], подпадающие под категорию видоизменения (<em>vikāra</em>), — подобные этим виды воззрений о непостоянстве воображаются тиртхиками.</li>
        <li>[Они полагают, что] первоэлементы (<em>bhūta</em>), будучи сжигаемы огнём, не сжигаются, поскольку обладают [неизменными] собственными признаками (<em>svalakṣaṇa</em>). Но если бы собственные признаки [элементов] исчезали друг в друге, то наступило бы [полное] уничтожение (<em>uccheda</em>) сущности первоэлементов и производного от них.<a href="#citation-458" id="ref-458" class="citation-mark"><sup>458</sup></a></li>
    </ul>

    <ul class="list-none mb-12 pl-2 space-y-1 ml-2">
        <li>Моё же [учение], Махамати, — ни вечно, ни невечно. Почему? Потому что Я не допускаю существования внешних объектов и учу, что тройственный мир — это только-сознание (<em>citta-mātra</em>). Поскольку Я не учу о [реальности] многообразных признаков, то и особое сочетание первоэлементов не приходит в движение и не прекращается.</li>
        <li>Различение (<em>vikalpa</em>) не является порождением первоэлементов, поэтому признаки субъекта и объекта (<em>grāhya-grāhaka</em>) не развёртываются двояко. Благодаря полному постижению этой двойственности различения, оставлению воззрений о внешнем бытии и небытии и осознанию того, что всё — лишь собственный ум, — различение продолжает двигаться лишь у того, кто питает его актами воображения (<em>vikalpābhisaṃskāra</em>); у того же, кто перестал воображать, оно не движется.</li>
        <li>Ввиду отсутствия бытия и небытия в ментальных различениях — ни мирские, ни высшие надмирские дхармы не являются ни вечными, ни невечными. Лишь из-за непонимания того, что мир — это проявления собственного ума, тиртхики, павшие в крайности, воображают непостоянство, подобно сказочным персонажам, которых никогда не существовало.</li>
        <li>Трояким, Махамати, является признак всех дхарм (мирских и высших) у тиртхиков — он порождён лишь речевым различением (<em>vāg-vikalpa</em>). Но невежды и обычные люди не понимают этого.<a href="#citation-459" id="ref-459" class="citation-mark"><sup>459</sup></a></li>
    </ul>

     <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>118. Ослеплённые [неведением],</li>
        <li>тиртхики воображают непостоянство</li>
        <li>как прекращение начатого, как изменение формы,</li>
        <li>как [распад] бытия или материи.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>119. При этом они полагают, что явления не разрушаются,</li>
        <li>и первоэлементы (<em>bhūta</em>) вечно пребывают в своей природе.</li>
        <li>Погружённые в многообразие воззрений,</li>
        <li>эти тиртхики [на самом деле] воображают вечность (<em>nityatā</em>).</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>120. Ни у одного из тиртхиков нет [понимания]</li>
        <li>ни истинного разрушения, ни возникновения.</li>
        <li>Если первоэлементы вечны в своей сути,</li>
        <li>то для чего они воображают непостоянство?<a href="#citation-460" id="ref-460" class="citation-mark"><sup>460</sup></a></li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>121. Всё это — лишь Только-сознание (<em>citta-mātra</em>).</li>
        <li>Сознание развёртывается двояко —</li>
        <li>как «схватываемое» и «схватывающий».</li>
        <li>Ни «я», ни «моё» [в реальности] не обнаруживаются.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>122. От обители Брахмы и до самого края [вселенной] —</li>
        <li>всё это, Я утверждаю, есть Только-сознание.</li>
        <li>Вне Только-сознания ни Брахма,</li>
        <li>ни кто-либо иной не обретаются.<a href="#citation-461" id="ref-461" class="citation-mark"><sup>461</sup></a></li>
    </ul>
    </blockquote>
    <p class="text-center font-bold">***</p>
