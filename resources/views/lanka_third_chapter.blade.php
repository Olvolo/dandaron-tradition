<p class="my-2" id="citation-417"><sup>417</sup> Двадцать пять <em>таттв</em> (<em>pañcaviṃśatitattva</em>) — система санкхьи: 1 <em>puruṣa</em>, 1 <em>prakṛti</em>, 7 <em>vikāra</em> (изменения), 16 <em>vikāra</em> низшего порядка. Постижение этих принципов считалось в санкхье путём к освобождению.<a href="#ref-417" class="citation-back">↩</a></p>
<p class="my-2" id="citation-418"><sup>418</sup> <em>Prajāpāla</em> — «царь-хранитель», «защитник подданных». <em>Ṣāḍguṇya</em> — «шесть качеств» или «шесть наставлений» — традиционный список царских добродетелей в политической философии. Речь, по всей видимости, об одной из систем <em>дхармашастры</em>, где Нирвана понималась как плод праведного следования закону.<a href="#ref-418" class="citation-back">↩</a></p>
<p class="my-2" id="citation-419"><sup>419</sup> Четыре позиции относительно бытия и Нирваны соответствуют четырём крайностям <em>catuṣkoṭi</em>: есть, нет, и то и другое, ни то ни другое. Будда последовательно отвергает все четыре как локаяту.<a href="#ref-419" class="citation-back">↩</a></p>
<p class="my-2" id="citation-420"><sup>420</sup> Это единственная позиция в перечне, которую Будда не отвергает — она описывает его собственное учение. «Львиный рык» (<em>siṃhanāda</em>) — устойчивый образ в буддийской литературе: непреклонное провозглашение истины, которое заставляет умолкнуть всех оппонентов.<a href="#ref-420" class="citation-back">↩</a></p>
<p class="my-2" id="citation-421"><sup>421</sup> <em>Jalpa-prapañca</em> — болтовня и размножествление — это не просто интеллектуальный порок. Будда называет их «источником страдания в тройственном мире» (<em>traidhātuka-duḥkha-yoni</em>). Пока ум производит речь и понятия о Нирване, он остаётся в том самом мире, от которого пытается освободиться. Истина (<em>tattva</em>) — это не «правильное описание», это прекращение самого производства описаний.<a href="#ref-421" class="citation-back">↩</a></p>
<p class="my-2" id="citation-422"><sup>422</sup> <em>Vāsanā-darpaṇa</em> — «зеркало отпечатков» — одна из красивейших метафор <strong><em>Ланкаватары</em></strong>. Ум подобен зеркалу: в нём отражаются образы, но за стеклом ничего нет. Ошибка невежды — принимать отражение за самостоятельный объект. Двойственность субъекта и объекта — это игра отражений в одном зеркале, а не два разных мира.<a href="#ref-422" class="citation-back">↩</a></p>
<p class="my-2" id="citation-423"><sup>423</sup> Гатхи 75–77 образуют нарастающую триаду:<br>— непостижение проекций ума порождает двойственность — постижение её прекращает.<br>— сам ум есть многообразие, свободное от разделения на «признак» и «носитель признака».<br>— тройственный мир — лишь различение, внешнего объекта нет вовсе.<a href="#ref-423" class="citation-back">↩</a></p>
<p class="my-2" id="citation-424"><sup>424</sup> Будда указывает на лингвистический тупик: искать означаемое (<em>abhidheya</em>) за пределами обозначения (<em>abhidhāna</em>) как некий внешний объект — значит снова впасть в воображение. В мире только-сознания нет «вещи», на которую указывает слово, отдельно от самого указывания. Именно поэтому в каждой сутре различение проповедовалось под разными именами — не потому что у него много форм, а потому что любое имя есть лишь палец, указывающий на луну.<a href="#ref-424" class="citation-back">↩</a></p>
<hr class="my-8 border-t-4 border-gray-500">
<p class="my-2" id="citation-425"><sup>425</sup> Махамати использует весь арсенал индийской логики, чтобы прояснить статус Татхагаты.<br>
«Сотворённое / несотворённое» (<em>kṛtaka/akṛtaka</em>): Если Будда «сотворён» (результат практики), то Он непостоянен и разрушим. Если «несотворён», то как Он может быть связан с путём и практикой существ?<br>
«Следствие / причина» (<em>kārya/kāraṇa</em>): Махамати проверяет, встроен ли Будда в цепь причинности (<em>pratītyasamutpāda</em>). Является ли Он «продуктом» пробуждения или «источником» спасения?<br>
«Носитель признака / признак» (<em>lakṣya/lakṣaṇa</em>): Обладает ли Будда качествами как их носитель, или Он и есть само Просветление без остатка?<br>
«Обозначение / обозначаемое» (<em>abhidhāna/abhidheya</em>): Является ли «Татхагата» лишь именем, или за ним стоит реальная, постигаемая умом сущность?<br>
Махамати хочет знать: Будда — это объект (пусть и высший), который можно классифицировать, или Он — нечто принципиально иное? Этот вопрос подготавливает почву для знаменитого ответа Будды о том, что Татхагата — это не-явление, лежащее за пределами всех разделений.<a href="#ref-425" class="citation-back">↩</a></p>
<p class="my-2" id="citation-426"><sup>426</sup> Разрушение логики крайностей (<em>cātuṣkoṭika</em>). Будда говорит: если вы называете Меня «несотворённым» (вечным), вы превращаете Меня в пустой звук, в чистую абстракцию, не имеющую связи с реальностью. Если же «сотворённым» — Я становлюсь обычным временным предметом. Татхагата — это Срединный Путь, который невозможно постичь средствами логики.<a href="#ref-426" class="citation-back">↩</a></p>
<p class="my-2" id="citation-427"><sup>427</sup> Парадокс отсутствия «я» (<em>svātmanā</em> или <em>parātmanā</em>). Когда Будда говорит, что «я» нет, он не имеет в виду, что дхармы — это полное ничто. Он говорит: корова — это корова, она не является лошадью. Дхарма лишена «я» другого, то есть не определяется через внешнее приписывание, она проявляется в своих собственных признаках (<em>svalakṣaṇa</em>). Ошибка невежд в том, что они пытаются «понять» отсутствие «я» как философскую идею, тогда как её нужно увидеть за пределами слов.<a href="#ref-427" class="citation-back">↩</a></p>
<p class="my-2" id="citation-428"><sup>428</sup> Чтобы описать связь со <em>скандхами</em> (тождество и отличие) Будда использует метафору двух рогов одного быка. Рога растут вместе, но они — разные. Так и Будда: Он проявляется через форму (<em>скандхи</em>), но Он не ограничен ими. Это исключает и материализм (Будда — это просто тело), и крайность полного отличия (Будда как нечто совершенно внешнее по отношению к <em>скандхам</em>).<a href="#ref-428" class="citation-back">↩</a></p>
<p class="my-2" id="citation-429"><sup>429</sup> <em>Pramāṇa</em> («мерило, средство познания») — восприятие, логика, авторитет. Всё, что постигается через эти средства, подлежит рождению и прекращению. Татхагата свободен от всех мерил — значит, любое высказывание о нём есть лишь <em>vāgmātra</em> («указание»), а не описание объекта. Указание же само по себе не рождено и не прекращается — оно подобно пространству (<em>ākāśa</em>): не причина и не следствие, безопорно (<em>nirālambya</em>). Безопорное выходит за пределы любого разрастания понятий (<em>prapañca</em>). Это и есть Татхагата. Цепочка построена так, что каждый шаг освобождает от предыдущего ограничения — это классический буддийский метод последовательного отрицания (<em>prasajyapratiṣedha</em> — отрицания, не предполагающего никакого скрытого утверждения взамен, в отличие от <em>paryudāsa</em> — отрицания с подразумеваемым утверждением).<a href="#ref-429" class="citation-back">↩</a></p>
<p class="my-2" id="citation-430"><sup>430</sup> <em>Dharmatā</em> — «истинная природа явлений» — это не объект, который можно обнаружить или опровергнуть средствами логики. Если Татхагата не обнаруживается через мерила и суждения, это не означает его отсутствия: отсутствие в поле логики не есть отсутствие как таковое. Именно это Будда называет <em>dharmatā</em> — природой, которая не зависит от того, воображается она или нет.<a href="#ref-430" class="citation-back">↩</a></p>
<hr class="my-8 border-t-4 border-gray-500">
<p class="my-2" id="citation-431"><sup>431</sup> Перечень имён Татхагаты охватывает три уровня. Первый — имена из брахманической и народной традиции: Брахма, Вишну, Ишвара, Индра, Варуна, Рама, Вьяса. Будда не отвергает эти имена — он включает их в синонимический ряд Татхагаты, тем самым указывая, что любое подлинное постижение высшего, в какой бы традиции оно ни возникало, указывает на одно. Второй уровень — имена из буддийской доктрины: <em>Шуньята</em>, Таковость, Нирвана, <em>Дхармадхату</em>. Третий — указания на природу самого постижения: Не-возникновение, Равенство, Недвойственность, Беспризнаковость.<a href="#ref-431" class="citation-back">↩</a></p>
<p class="my-2" id="citation-432"><sup>432</sup> Это одно из ключевых различений <strong><em>Ланкаватары</em></strong>: <em>ruta</em> («звук, буква») и <em>artha</em> («смысл»). Звук рождается и гибнет — он принадлежит миру обусловленного. Смысл же не рождается и не прекращается — он принадлежит тому, что за пределами знаков. Цепляться за букву в поисках смысла — всё равно что принимать палец, указывающий на луну, за саму луну.<a href="#ref-432" class="citation-back">↩</a></p>
<p class="my-2" id="citation-433"><sup>433</sup> Это парадоксальное утверждение — «Татхагата не произнёс ни единого звука» — не означает молчания. Это указание на то, что подлинная Дхарма передаётся не через знаки, а через <em>pratyātmāryajñāna</em> — личное благородное постижение. Слова — лишь условный мост, который следует пройти, а не на котором следует остановиться.<a href="#ref-433" class="citation-back">↩</a></p>
<p class="my-2" id="citation-434"><sup>434</sup> Будда не отрицает высшие состояния — личное благородное постижение, без-образность, прекращение различения — а указывает, что они не служат основанием для учения. Учитель проповедует не затем, чтобы утвердить ученика в состоянии, — это вновь создало бы точку опоры, а значит, новую привязанность. Цель — сам поворот сознания (<em>citta-mano-vijñāna-vyāvṛtti</em>), после которого все эти состояния возникают естественно, не становясь объектами гордости или идентичности.<a href="#ref-434" class="citation-back">↩</a></p>
<p class="my-2" id="citation-435"><sup>435</sup> Четыре опоры (<em>catvāri pratiśaraṇāni</em>) — классическое буддийское учение: опираться на смысл, а не на букву; на мудрость, а не на сознание; на окончательное значение, а не на условное; на Дхарму, а не на личность учителя.<a href="#ref-435" class="citation-back">↩</a></p>
<p class="my-2" id="citation-436"><sup>436</sup> <em>Sarvadharmabhūmi</em> означает все сферы, в которых проявляются дхармы — от низших состояний сансары до высших ступеней бодхисаттвы. <em>Svalakṣaṇa</em> — это собственный признак каждой дхармы в её собственной сфере. Бодхисаттва становится искусным, когда видит каждую дхарму в её правильном месте и в её истинной природе, не смешивая уровни и не приписывая признаки одного уровня другому.<a href="#ref-436" class="citation-back">↩</a></p>
<p class="my-2" id="citation-437"><sup>437</sup> <em>Āyatana</em> — «обитель», «сфера» — здесь указывает на высшие состояния пребывания бодхисаттвы, соответствующие его реализации. <em>Viśeṣa</em> — «особый», «превосходный». Вместе — «особые обители», то есть сферы деятельности, недоступные обычным существам.<a href="#ref-437" class="citation-back">↩</a></p>
<p class="my-2" id="citation-438"><sup>438</sup> Десять видов власти (<em>daśa vaśitā</em>) бодхисаттвы:<br>
власть над жизнью (<em>āyur-vaśitā</em>),<br>
власть над умом (<em>citta-vaśitā</em>),<br>
власть над необходимыми вещами (<em>pariṣkāra-vaśitā</em>),<br>
власть над кармой (<em>karma-vaśitā</em>),<br>
власть над рождением (<em>upapatti-vaśitā</em>),<br>
власть над волей (<em>adhimukti-vaśitā</em>),<br>
власть над устремлением (<em>praṇidhāna-vaśitā</em>),<br>
власть над чудесными силами (<em>ṛddhi-vaśitā</em>),<br>
власть над знанием (<em>jñāna-vaśitā</em>),<br>
власть над Дхармой (<em>dharma-vaśitā</em>).<br>
Эти власти позволяют бодхисаттве свободно проявляться в мирах для блага существ.<a href="#ref-438" class="citation-back">↩</a></p>
<p class="my-2" id="citation-439"><sup>439</sup> <em>Anuśaya</em> — «скрытая склонность» — технический термин абхидхармы, обозначающий скрытые/дремлющие тенденции, которые не проявлены в сознании, но готовы возникнуть при подходящих условиях. Бодхисаттва, обладая прямым знанием, видит эти склонности и устраняет их корень.<a href="#ref-439" class="citation-back">↩</a></p>
<p class="my-2" id="citation-440"><sup>440</sup> <em>Tathātva</em> — «таковость» — состояние вещей такими, каковы они есть, без наложения понятий. Проповедь Дхармы «в соответствии с таковостью» означает адаптацию учения к подлинной природе слушателя, а не к его представлениям.<a href="#ref-440" class="citation-back">↩</a></p>
<p class="my-2" id="citation-441"><sup>441</sup> Будда говорит, что истина о «не-возникновении» несъедобна в «сыром» (чисто интеллектуальном) виде. Чтобы она «засияла» и принесла пользу, её нужно «приготовить» через личную практику. Просто повторять «всё шуньята» без реализации — это всё равно что есть сырой рис.<br>
Метафора «приготовления» (<em>abhisaṃskāra</em>) намеренно перекликается с буддийским термином <em>abhisaṃskāra</em> — «постепенное накопление заслуг и мудрости» на пути бодхисаттвы. Таким образом, «приготовление истины» — это сама практика пути.<a href="#ref-441" class="citation-back">↩</a></p>
