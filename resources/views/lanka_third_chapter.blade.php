<p class="my-2" id="citation-442"><sup>442</sup> Девять основ (<em>nava dravya</em>) системы вайшешики: земля (<em>pṛthivī</em>), вода (<em>ap</em>), огонь (<em>tejas</em>), ветер (<em>vāyu</em>), пространство (<em>ākāśa</em>), время (<em>kāla</em>), направление (<em>diś</em>), душа (<em>ātman</em>) и ум (<em>manas</em>). Вайшешика считала их вечными и несотворёнными первоначалами. Махамати указывает: если Будда тоже признаёт что-либо несотворённым и неуничтожимым, то его учение неотличимо от вайшешики.<a href="#ref-442" class="citation-back">↩</a></p>
<p class="my-2" id="citation-443"><sup>443</sup> <em>Satkāryavāda</em> («следствие реально существует в причине») — позиция санкхьи: масло уже скрыто в семени. <em>Asatkāryavāda</em> («следствие не существует в причине до возникновения») — позиция ньяя-вайшешики: горшок возникает из глины как нечто новое. Махамати указывает: если Будда признаёт какую-либо причинность, он неизбежно примыкает к одной из этих позиций — и тем самым теряет уникальность своего учения.<a href="#ref-443" class="citation-back">↩</a></p>
