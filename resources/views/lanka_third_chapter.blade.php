<p class="my-2" id="citation-451"><sup>451</sup> Будда перечисляет восемь идей непостоянства, чтобы показать: все они предполагают, что вещь сначала реально возникла, а затем реально исчезла. Это укрепляет веру в объективность мира — и потому является ловушкой.<br>
Особого внимания заслуживает восьмой вид — <em>anutpādānityatā</em> («непостоянство не-возникновения»). Некоторые тиртхики, анализируя вещи вплоть до атомов и не обнаруживая ничего устойчивого, приходят к выводу: всё непостоянно, ибо ничто не рождается. Это звучит как буддийское учение — но Будда указывает на принципиальное различие: они по-прежнему мыслят в категориях «возникновения» и «распада», лишь перенося их на атомарный уровень. Подлинное не-возникновение (<em>anutpāda</em>) не есть вид непостоянства — оно указывает на то, что вещи никогда и не рождались. Называть «непостоянством» то, чего никогда не было — значит сохранять саму рамку, которую следует отбросить. Именно из-за непонимания этого различия тиртхики, даже достигая тонких уровней анализа, остаются в пределах учения о непостоянстве возникновения.<a href="#ref-451" class="citation-back">↩</a></p>
<p class="my-2" id="citation-452"><sup>452</sup> Будда вскрывает логическую ловушку, в которую попадает любая попытка овеществить непостоянство — превратить его из описания в самостоятельную сущность.<br>
Если непостоянство — это причина, разрушающая явления, то оно должно само оставаться неизменным, чтобы продолжать это разрушение: «разбивающее» (<em>bhedaka</em>) предшествует «разбиваемому» (<em>bhedya</em>) и не разрушается вместе с ним. Но тогда непостоянство вечно — что противоречит исходному тезису.<br>
Если же непостоянство тождественно самому небытию явлений, то оно несёт в себе признаки и причины, и действия одновременно. Это делает его замкнутой сущностью — и вновь вечной.<br>
Выход, который Будда указывает, не назван здесь прямо, но подразумевается из всего предшествующего: явления непостоянны не потому, что некая внешняя сила их разрушает, а потому что они изначально лишены независимого бытия — <em>anutpanna</em>, нерождённые. Непостоянство тиртхиков описывает распад того, что якобы существовало. Будда указывает: то, что никогда не рождалось, не может и распасться.<a href="#ref-452" class="citation-back">↩</a></p>
<p class="my-2" id="citation-453"><sup>453</sup> Будда разрушает идею «непостоянства» через анализ времени и природы первоэлементов.<br>
Если непостоянство — реальное свойство явления, оно должно действовать в каком-то из трёх времён. Но прошлая форма уже исчезла вместе с прошлым. Будущая ещё не возникла. В настоящем же форма не имеет отдельного от себя признака непостоянства — ибо форма есть лишь особый способ сочетания первоэлементов (<em>bhūta</em>), а не самостоятельная сущность.<br>
Далее Будда обращается к самим первоэлементам. Тиртхики полагают, что «материя» остаётся, тогда как «формы» меняются. Но природа первоэлементов и производных от них не гибнет — они свободны от отношений тождества и различия, а значит, нет того, что могло бы их разрушить. Весь тройственный мир состоит из этих элементов, и возникновение, пребывание, видоизменение лишь воображаются (<em>prajñapyate</em>) в нём. Что же тогда является носителем «непостоянства»?<br>
С точки зрения только-сознания первоэлементы — не физические кирпичики реальности, а единицы восприятия. Они не приходят в движение и не прекращаются — не потому что вечны, а потому что укоренённость тиртхиков в признаках их собственной природы удерживает ум в иллюзии их независимого существования.<a href="#ref-453" class="citation-back">↩</a></p>
<p class="my-2" id="citation-454"><sup>454</sup> Будда разбирает первый из восьми видов непостоянства — <em>prārambhavinivṛtti</em> — и показывает его внутреннее противоречие.<br>
Тиртхики полагают, что мир устроен как цепочка «начал»: один элемент запускает другой. Непостоянство для них — это когда эта цепочка прерывается, когда что-то «не начинается» снова. Но Будда указывает на скрытое противоречие: чтобы один элемент мог «начать» другой, они должны быть реально различны. Однако собственные признаки (<em>svalakṣaṇa</em>) первоэлементов абсолютно индивидуальны — земля есть земля, вода есть вода, между ними нет общей основы, которая позволила бы одному «перейти» в другое или «породить» другое.<br>
Таким образом тиртхики оказываются в ловушке собственной теории: если элементы абсолютно различны, никакого «начала» никогда и не было. А то, чего никогда не было, не может и «прекратиться». Называть это «непостоянством» — значит давать имя тому, чего нет. При этом, спасая первоэлементы от порождения и разрушения, тиртхики незаметно превращают их в вечные сущности — их "непостоянство" оказывается скрытой формой этернализма (<em>nityavāda</em>).<a href="#ref-454" class="citation-back">↩</a></p>
<p class="my-2" id="citation-455"><sup>455</sup> Будда разбирает второй вид непостоянства — <em>saṃsthānavinivṛtti</em> — и показывает, что за ним скрывается та же вера в нечто вечное.<br>
Тиртхики этого толка признают: форма (<em>saṃsthāna</em>) — кувшин, тело, гора — непостоянна и разрушается. Но при анализе вплоть до атома сами атомы остаются нетронутыми. «Длинное» и «короткое» исчезают как относительные признаки, но первоэлементы (<em>bhūta</em>) продолжают существовать. Непостоянство здесь — лишь смена формы неизменной основы.<br>
Будда прямо связывает этот взгляд с санкхьей и её доктриной <em>satkāryavāda</em>: следствие уже содержится в причине, изменение есть лишь проявление того, что уже было скрыто. Разрушение формы кувшина не уничтожает глину — оно лишь возвращает её в исходное состояние. Такое «непостоянство» оставляет нетронутой саму идею чего-то вечного, лишь меняя масштаб: вместо кувшина теперь «вечны» атомы. <em>Шуньяту</em> это не затрагивает.<a href="#ref-455" class="citation-back">↩</a></p>
<p class="my-2" id="citation-456"><sup>456</sup> Будда разбирает третий вид непостоянства — <em>saṃsthānānityatā</em> — и показывает, что попытка ограничить непостоянство лишь формой, сохранив вечность первоэлементов, внутренне противоречива.<br>
Тиртхики этого толка боятся довести свою логику до конца. Признать непостоянство первоэлементов для них означало бы уничтожить саму возможность мирского взаимодействия (<em>lokasaṃvyavahāra</em>): торговли, речи, познания — всего, что предполагает устойчивую основу. Поэтому они останавливаются на полпути: форма (<em>saṃsthāna</em>) меняется, но элементы остаются.<br>
Будда указывает на парадокс: спасая «реальность» мира через вечные элементы, тиртхики на самом деле приближаются к той самой позиции, которой боятся — к локаяте. Ведь если непостоянство формы не затрагивает основу, то форма оказывается лишь условным обозначением, пустым звуком (<em>vāgmātra</em>) поверх вечной материи. Разница между «кувшин непостоянен» и «кувшин — пустой звук» стирается. Настоящее же возникновение в собственных признаках (<em>svalakṣaṇotpatti</em>) не признаётся ни теми, ни другими.<a href="#ref-456" class="citation-back">↩</a></p>
<p class="my-2" id="citation-457"><sup>457</sup> Будда разбирает четвёртый вид непостоянства — <em>vikārānityatā</em> — и показывает, что метафора золота и украшений, при всей её кажущейся убедительности, лишь маскирует веру в вечную материю.<br>
Тиртхики этого толка проводят чёткое разграничение: <em>bhāva</em> («бытие», вещество, материя) и <em>saṃsthāna</em> («форма», взаиморасположенность). Золото переплавляется из кольца в браслет — форма меняется, золото остаётся. Это позволяет признать видимые изменения мира, не отказываясь от идеи устойчивой основы. Непостоянство здесь — лишь смена «масок» на неизменном «лице».<br>
Этот аргумент широко используется в веданте и санкхье, где он служит утешением: сколько бы форм ни возникало и ни гибло, <em>brahman</em> или <em>prakṛti</em> остаются нетронутыми. Но именно это Будда квалифицирует как скрытый этернализм (<em>nityavāda</em>): если основа (<em>bhūta</em>) не гибнет, то речь идёт не о подлинном непостоянстве, а лишь о перераспределении вечной материи.<br>
С точки зрения только-сознания нет «золота» отдельно от его текущей формы в сознании воспринимающего. Разделение на нечто неизменное и изменчивую форму — это наложение понятий, а не описание реальности. Всё, что воспринимается, — единое проявление ума, в котором нет ни вечного «золота», ни отдельного от него «украшения».<a href="#ref-457" class="citation-back">↩</a></p>
<p class="my-2" id="citation-458"><sup>458</sup> Этот абзац завершает разбор четвёртого вида непостоянства и одновременно подводит итог общей логике тиртхиков в отношении первоэлементов.<br>
Тиртхики, особенно вайшешики, наделяют каждый первоэлемент неуничтожимым собственным признаком (<em>svalakṣaṇa</em>): земля — твёрдость, вода — текучесть, огонь — жар. Когда дерево сгорает, атомы земли в нём не меняют своей природы — они лишь перегруппировываются. Огонь не уничтожает «земляность» земли, он лишь разрушает форму (<em>saṃsthāna</em>). Это означает, что на уровне элементов в мире ничего по-настоящему не происходит — перед нами скрытый этернализм.<br>
Будда указывает на внутреннее противоречие этой позиции: если собственные признаки элементов абсолютно неизменны, то элементы не могут взаимодействовать вообще. Огонь не может «сжигать» землю, потому что «земляность» земли непроницаема для «огненности» огня. Признаки замкнуты в себе и не переходят друг в друга (<em>anyonyataḥ svalakṣaṇavigama</em> — «исчезновение собственных признаков друг в друге»). Но если допустить такое взаимопроникновение, то элементы утратят свою природу — и наступит полное уничтожение (<em>uccheda</em>).<br>
Тиртхики оказываются между двух ловушек: либо элементы абсолютно замкнуты — и тогда никакого взаимодействия нет, либо они взаимопроникают — и тогда наступает уничтожение. Оба пути ведут к абсурду. Истинное непостоянство, которое Будда указывает, не предполагает ни вечных кирпичиков, ни их полного уничтожения — оно указывает на нерождённость (<em>anutpāda</em>) самих первоэлементов как независимых сущностей.<br>
Пятый (<em>kṣīradadhi</em>) и шестой (<em>bhāva</em>) виды Будда не разбирает отдельно, поскольку их логическое противоречие следует из общего разбора.<a href="#ref-458" class="citation-back">↩</a></p>
<p class="my-2" id="citation-459"><sup>459</sup> Этот отрывок подводит итог всему разбору восьми видов непостоянства и формулирует позицию Будды.<br>
Все тиртхики, при всём различии своих систем, разделяют одну предпосылку: существуют внешние объекты, обладающие теми или иными признаками — вечными или непостоянными. Будда отказывается от этой предпосылки целиком. Поскольку внешних объектов нет и тройственный мир есть только-сознание (<em>cittamātra</em>), сами вопросы «вечно или нет?» и «постоянно или изменчиво?» теряют основание.<br>
Различение (<em>vikalpa</em>) движется не потому, что мир объективно меняется, а потому что ум продолжает воображать (<em>abhisaṃskāra</em>). Для того, кто постиг, что всё — лишь проекция собственного ума (<em>svacittadṛśyamātra</em>), различение не прекращается насильственно — оно просто перестаёт питаться верой во внешние объекты и замирает само собой.<br>
<em>Kathāpuruṣa</em> — «сказочный персонаж» — одна из самых резких метафор текста. Споры о вечности атомов или непостоянстве форм подобны спорам о свойствах героя из сказки: у него нет ни волос, ни роста, ни возраста — потому что его нет. Признаки внешних объектов, о которых спорят тиртхики, столь же нереальны — они порождены лишь речевым различением (<em>vāgvikalpa</em>), а не описывают что-либо существующее.<br>
Трояким Будда называет признак всех дхарм у тиртхиков, по всей видимости, имея в виду три уровня их рассмотрения: мирской, надмирской и высший надмирской — все три остаются в пределах речевого различения и не достигают прямого постижения.<a href="#ref-459" class="citation-back">↩</a></p>
<p class="my-2" id="citation-460"><sup>460</sup> Главное противоречие тиртхиков: их учения о непостоянстве на поверку оказываются скрытым утверждением существования вечного. Какую бы форму непостоянства они ни описывали — прекращение начатого, исчезновение формы, распад бытия — за всеми этими идеями стоит вера в первоэлементы (<em>bhūta</em>), которые «вечно пребывают в своей природе». Признавая изменчивость форм, они сохраняют неизменную основу. Это имитация понимания непостоянства. Подлинного разрушения и подлинного возникновения в их системах нет — есть лишь перегруппировка вечной материи.<a href="#ref-460" class="citation-back">↩</a></p>
<p class="my-2" id="citation-461"><sup>461</sup> Сознание развёртывается двояко — как «схватываемое» (<em>grāhya</em>) и «схватывающий» (<em>grāhaka</em>) — и именно эта двойственность порождает иллюзию внешнего мира с его вечностью или непостоянством. Когда постигается, что ни «я», ни «моё» не существуют как независимые сущности, двойственность прекращается.<br>
Весь мир — от обители Брахмы до самого края вселенной — есть только-сознание. Брахма и боги — не внешние силы, а уровни проявления ума. Когда это постигнуто, сами вопросы о вечности или непостоянстве теряют основание: нет внешнего мира, к которому они могли бы быть применены.<a href="#ref-461" class="citation-back">↩</a></p>
