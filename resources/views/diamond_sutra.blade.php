    <h1 class="text-center text-blue-900 font-bold text-2xl sm:text-2xl md:text-2xl mt-6 mb-6">
        Алмазная сутра</h1>
    <div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">1</h4>
        <p><em>Так я слышал.<a href="#citation-1" id="ref-1" class="citation-mark"><sup>1</sup></a></em>
        </p>
        <p>Однажды Бхагаван пребывал в Шравасти, в роще Джеты, в саду Анатхапиндады, вместе с
            великой сангхой нищенствующих монахов — тысяча двести пятьюдесятью бхикшу<a
                href="#citation-2" id="ref-2" class="citation-mark"><sup>2</sup></a> — и множеством
            великосущих бодхисаттв.<a href="#citation-3" id="ref-3"
                                      class="citation-mark"><sup>3</sup></a></p>
        <p>В первой половине дня Бхагаван облачился в монашеское одеяние, взял чашу для подаяний и
            отправился в великий город Шравасти собирать подаяние. Обойдя город и собрав подаяние,
            он вкусил пищу, затем отложил чашу и одеяние, омыл ноги, уселся на подготовленное
            сидение, скрестив ноги, выпрямив тело и направив внимание перед собой.</p>
        <p>Тогда многие монахи подошли к Бхагавану, склонили головы к его стопам, трижды обошли его
            посолонь с левой стороны направо<a href="#citation-4" id="ref-4"
                                               class="citation-mark"><sup>4</sup></a> и расселись
            поодаль, образуя благоговейный круг.</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">2</h4>
        <p>Тем временем в собрании поднялся старейшина Субхути. Закинув край верхнего одеяния на
            одно плечо, преклонив правое колено на землю, он, сложив ладони, обратился к
            Бхагавану:</p>
        <p>— Удивительно, Бхагаван! В высшей степени удивительно, Благоушедший! Ведь именно
            Татхагата, Архат, Совершенно Просветлённый наивысшей мудростью наполняет великосущих
            бодхисаттв. Удивительно, Бхагаван, что именно Татхагата, Архат, Совершенно Просветлённый
            дарует им высший дар!</p>
        <p>Как же должен поступать, Бхагаван, сын или дочь из благородной семьи, вступивший на стезю
            бодхисаттвы: как вести себя, как направлять свой ум?</p>
        <p>Бхагаван ответил Субхути:</p>
        <p>— Верно, верно, Субхути! Именно так, как ты говоришь: Татхагата наивысшей мудростью
            наполняет великосущих бодхисаттв и дарует им высший дар. Посему слушай внимательно,
            Субхути, и хорошо запомни. Я поведаю тебе, как должен поступать сын или дочь из
            благородной семьи, вступивший на стезю бодхисаттвы: как вести себя, как направлять свой
            ум.</p>
        <p>— Слушаю, Бхагаван, — ответил достопочтенный Субхути.</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">3</h4>
        <p>Бхагаван сказал:</p>
        <p>— В этом мире, Субхути, вступивший на стезю бодхисаттвы должен породить в себе такую
            мысль: «Сколько бы существ ни было во всех сферах существования — рождённых из яйца,
            рождённых из утробы, рождённых из влаги, рождённых самопроизвольно;<a href="#citation-5"
                                                                                  id="ref-5" class="citation-mark"><sup>5</sup></a>
            имеющих форму или не имеющих формы; обладающих восприятием, не обладающих восприятием
            или ни обладающих, ни не обладающих восприятием — всех их я должен привести к нирване,
            не оставляющей остатка.<a href="#citation-6" id="ref-6"
                                      class="citation-mark"><sup>6</sup></a> И даже если таким
            образом приведено к нирване бесчисленное множество существ, ни одно существо не было
            приведено».</p>
        <p>Почему так? Если, Субхути, бодхисаттва держится понятия «существо», его нельзя называть
            бодхисаттвой. Воистину, Субхути, нельзя называть бодхисаттвой того, кто держится понятия
            атман, саттва, джива или пудгала.<a href="#citation-7" id="ref-7"
                                                class="citation-mark"><sup>7</sup></a></p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">4</h4>
        <p>— Однако, Субхути, бодхисаттва не должен совершать даяние, опираясь на что-либо. Не
            следует давать даяние, опираясь на форму, звук, запах, вкус, осязаемое или дхармы.</p>
        <p>Почему так? Потому что заслуга того бодхисаттвы, который даёт даяние, не опираясь ни на
            какие признаки,<a href="#citation-8" id="ref-8" class="citation-mark"><sup>8</sup></a>
            не поддаётся измерению.</p>
        <p>Как ты думаешь, Субхути, можно ли измерить пространство на востоке?</p>
        <p>— Нет, Бхагаван.</p>
        <p>— Точно так же, Субхути, не поддаётся измерению заслуга бодхисаттвы, который совершает
            даяние, не опираясь ни на какие признаки. Посему, Субхути, вступивший на стезю
            бодхисаттвы должен давать даяние, не имея опоры.</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">5</h4>
        <p>— Как ты думаешь, Субхути, можно ли узреть Татхагату по полноте его признаков?</p>
        <p>— Нет, Бхагаван. Татхагату нельзя узреть по полноте признаков. Почему так?</p>
        <p>Если бы Татхагата узревался по полноте признаков, то чакравартин был бы Татхагатой.</p>
        <p>Поэтому, Субхути, где Татхагата показывает признаки, не показывая признаков, там следует
            видеть Татхагату.</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">6</h4>
        <p>Достопочтенный Субхути спросил Бхагавана:</p>
        <p>— Будут ли, Бхагаван, существа в будущем — в последние пять столетий,<a
                href="#citation-9" id="ref-9" class="citation-mark"><sup>9</sup></a>
            когда начнётся упадок истинной Дхармы, — которые, услышав такие слова сутры, обретут
            чистую веру?</p>
        <p>Бхагаван ответил:</p>
        <p>— Не говори так, Субхути! Конечно, в те времена будут великосущие бодхисаттвы —
            наделённые добродетелью, высокой нравственностью и глубокой мудростью, — которые,
            услышав эти слова, в едином мгновении мысли обретут чистую веру.</p>
        <p>Ибо этим бодхисаттвам окажут покровительство не один и не два Будды, но многие миллионы
            Будд, и от многих миллионов Будд взрастят они свои благие корни.</p>
        <p>Татхагата знает их знанием Будды, видит их оком Будды, постигает их мудростью Будды. Все
            они произведут и обретут неизмеримые скопления заслуг.</p>
        <p>Почему так? Потому что у этих великосущих бодхисаттв нет понятий атман. У них нет ни
            понятия «дхарма», ни понятия «не-дхарма». Более того, Субхути, у них вообще нет понятий
            и нет отсутствия понятий. Почему так? Если бы, Субхути, у этих великосущих бодхисаттв
            было понятие «дхарма» — они бы тем самым держались за атман, за саттву, за дживу, за
            пудгалу. Если бы у них было понятие «не-дхарма» — они также держались бы за эти
            представления.</p>
        <p>Поэтому, Субхути, великосущий бодхисаттва не должен держаться ни дхармы, ни
            не-дхармы.</p>
        <p>Вот почему Татхагата изрёк это сокровенное наставление:</p>
        <ul class="list-none mb-4 pl-2 space-y-2 ml-2">
            <li>«Имея в виду дхармы — следует оставить дхармы;</li>
            <li>имея в виду не-дхармы — следует оставить не-дхармы».</li>
        </ul>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">7</h4>
        <p>Бхагаван спросил достопочтенного Субхути:</p>
        <p>— Как ты думаешь, Субхути, есть ли какая-либо дхарма, которую Татхагата постиг как
            наивысшее совершенное Просветление? Есть ли какая-либо дхарма, которой наставляет
            Татхагата?</p>
        <p>Достопочтенный Субхути ответил Бхагавану:</p>
        <p>— Насколько я понимаю смысл изречённого тобою, Бхагаван, нет никакой дхармы, которую
            Татхагата постиг как наивысшее совершенное Просветление, и нет никакой дхармы, которой
            наставляет Татхагата.</p>
        <p>Почему так? Та Дхарма, которую Татхагата постиг и которой наставляет, непостижима и
            невыразима. Она ни дхарма, ни не-дхарма.</p>
        <p>Почему так? Потому что благородные личности неопределимы.<a href="#citation-10"
                                                                       id="ref-10" class="citation-mark"><sup>10</sup></a>
        </p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">8</h4>
        <p>Бхагаван сказал:</p>
        <p>— Как ты думаешь, Субхути, если какой-либо сын или дочь из благородной
            семьи наполнит три тысячи мириад миров<a href="#citation-11" id="ref-11"
                                                     class="citation-mark"><sup>11</sup></a> семью
            драгоценностями и преподнесёт их в дар Татхагатам, Архатам, Совершенным Буддам, —
            создаст ли этот сын или дочь из благородной семьи великое скопление заслуг?</p>
        <p>Субхути ответил:</p>
        <p>— Великое, Бхагаван! Великое, Благоушедший! Великое скопление заслуг
            создаст этот сын или дочь из благородной семьи.</p>
        <p>Почему так? То, что Татхагата называет скоплением заслуг, Татхагата же называет
            не-скоплением заслуг. Поэтому он и говорит: «скопление заслуг».</p>
        <p>Бхагаван сказал:</p>
        <p>— Но если, Субхути, какой-либо сын или дочь из благородной семьи
            наполнит три тысячи мириад миров семью драгоценностями и преподнесёт их в дар
            Татхагатам, Архатам, Совершенным Буддам, а другой человек, взяв из этого изложения
            Дхармы хотя бы одну четырёхстрочную гатху, научит ей других и разъяснит её, — то этот
            последний создаст несравненно большее, неизмеримое скопление заслуг.</p>
        <p>Почему так? Потому что, Субхути, именно отсюда возникло наивысшее совершенное
            Просветление Татхагат, Архатов, Совершенных Будд, и именно отсюда произошли
            Будды-Бхагаваты.</p>
        <p>Почему так? То, что называют «дхармами Будды», Субхути, — Татхагата говорил о них как о
            не-дхармах Будды. Поэтому они и зовутся «дхармами Будды».</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">9</h4>
        <p>Бхагаван спросил Субхути:</p>
        <p>— Как ты думаешь, Субхути, приходит ли вступившему в поток на
            ум: «Мною обретён плод вступления в поток»?</p>
        <p>— Нет, Бхагаван. У вступившего в поток не возникает такой мысли. Почему так? Потому что
            он не вступил в обладание ни формой, ни звуком, ни запахом, ни вкусом, ни осязаемым,
            ни дхармами. Поэтому его и называют «вступившим в
            поток».<a href="#citation-12" id="ref-12" class="citation-mark"><sup>12</sup></a>
            Если бы у него возникла мысль: «Я обрёл плод вступления в поток», — он бы держался за
            понятия атман, саттва, джива, пудгала.</p>
        <p>Бхагаван сказал:</p>
        <p>— А у возвращающегося один раз<a href="#citation-13" id="ref-13"
                                            class="citation-mark"><sup>13</sup></a> приходит ли на ум: «Мною обретён плод
            возвращения один раз»?</p>
        <p>— Нет, Бхагаван. Почему так? Потому что нет дхармы, которая была бы «возвращением
            один раз». Поэтому его и называют «возвращающимся один раз».</p>
        <p>— А у невозвращающегося<a href="#citation-14" id="ref-14"
                                     class="citation-mark"><sup>14</sup></a> приходит ли на ум:
            «Мною обретён плод невозвращения»?</p>
        <p>— Нет, Бхагаван. Почему так? Потому что нет дхармы,
            которая была бы «невозвращением». Поэтому его и называют «невозвращающимся».</p>
        <p>— А у архата<a href="#citation-15" id="ref-15" class="citation-mark"><sup>15</sup></a>
            приходит ли на ум: «Мною достигнуто архатство»?</p>
        <p>— Нет, Бхагаван. Почему так? Потому что нет дхармы, именуемой «архат». Поэтому его и
            называют «архатом». Если бы у архата возникла мысль: «Я достиг архатства», — он бы
            держался за понятия атман, саттва, джива, пудгала.</p>
        <p>Ведь обо мне, Бхагаван, Татхагата, Архат, Совершенный Будда сказал: «Субхути — первый
            среди пребывающих в безмятежности». Я — архат, свободный от страстей, Бхагаван. Но у
            меня не возникает мысли: «Я — архат, свободный от страстей».</p>
        <p>Если бы такая мысль возникла, Татхагата не назвал бы меня «пребывающим в
            безмятежности». Поэтому Татхагата назвал меня «пребывающим в безмятежности».</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">10</h4>
        <p>Бхагаван спросил Субхути:</p>
        <p>— Как ты думаешь, Субхути, есть ли какая-либо дхарма, которую я получил от Татхагаты
            Дипанкары, Архата, Совершенного Будды?</p>
        <p>— Нет, Бхагаван. Нет никакой дхармы, которую ты получил от Татхагаты Дипанкары.</p>
        <p>Бхагаван сказал:</p>
        <p>— Если бодхисаттва скажет: «Я создам чистые земли Будды»,<a href="#citation-16"
                                                                       id="ref-16" class="citation-mark"><sup>16</sup></a> — он скажет неправильно.</p>
        <p>Почему так? «Чистые земли, чистые земли», Субхути, — Татхагата говорил о них как о
            не-чистых. Поэтому их и называют «чистыми землями Будды».</p>
        <p>Поэтому, Субхути, великосущий бодхисаттва должен породить ум, не опирающийся ни на что.
            Он не должен порождать ум, опирающийся на форму. Он не должен порождать ум, опирающийся
            на звук, запах, вкус, осязаемое или дхармы. Он должен породить ум, нигде не
            пребывающий.</p>
        <p>Субхути, это подобно тому, как если бы был человек, наделённый телом, великим телом, чьё
            телесное воплощение было бы подобно царю гор Сумеру.<a
                href="#citation-17" id="ref-17" class="citation-mark"><sup>17</sup></a> Как ты
            думаешь, Субхути, было бы велико то телесное воплощение?</p>
        <p>Субхути ответил:</p>
        <p>— Велико, Бхагаван! Велико, Благоушедший, было бы то телесное воплощение!</p>
        <p>Почему так? «Телесное воплощение, телесное воплощение», Бхагаван, — Татхагата говорил о
            нём как о не-воплощении. Поэтому его и называют «телесным воплощением». Ибо, Бхагаван,
            оно ни существование, ни не-существование. Поэтому его и называют «телесным
            воплощением».</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">11</h4>
        <p>Бхагаван сказал:</p>
        <p>— Как ты думаешь, Субхути, если бы было столько рек Ганг, сколько песчинок в одной реке
            Ганг, — было бы велико число песчинок во всех этих реках Ганг?</p>
        <p>Субхути ответил:</p>
        <p>— Уже само число этих рек Ганг было бы огромным, Бхагаван, — что уж говорить о песчинках
            в них!</p>
        <p>Бхагаван сказал:</p>
        <p>— Поведаю тебе, Субхути, открою тебе истину. Если бы некий сын или дочь из благородной
            семьи наполнил семью драгоценностями столько миров, сколько песчинок во всех этих реках
            Ганг, и преподнёс их в дар Татхагатам, Архатам, Совершенным Буддам, — он создал бы
            великое скопление заслуг.</p>
        <p>Но если, Субхути, сын или дочь из благородной семьи возьмёт из этого изложения Дхармы
            хотя бы одну четырёхстрочную гатху, усвоит её, научит ей других и разъяснит её подробно,
            — то он создаст ещё большее, неизмеримое, неисчислимое скопление заслуг.</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">12</h4>
        <p>Более того, Субхути, то место на земле, где кто-либо, взяв из этого изложения Дхармы хотя
            бы одну четырёхстрочную гатху, научит ей и разъяснит её другим, — станет местом
            поклонения для всего мира: для богов, людей и асур.</p>
        <p>Что же говорить о тех, кто усвоит это изложение Дхармы целиком, сохранит его, будет
            читать, постигать и подробно разъяснять другим!</p>
        <p>Те, Субхути, совершат высшее и наиудивительнейшее деяние.</p>
        <p>В том месте будет либо сам Татхагата, либо тот, кто почитает Татхагату.</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">13</h4>
        <p>Тогда достопочтенный Субхути спросил Бхагавана:</p>
        <p>— Как же называется это изложение Дхармы, Бхагаван, и как мне его воспринять?</p>
        <p>Бхагаван ответил достопочтенному Субхути:</p>
        <p>— Это изложение Дхармы, Субхути, называется «Ваджрная Праджня-парамита». Так и
            воспринимай его.</p>
        <p>Почему так? То, что Татхагата называет Праджня-парамитой, Субхути, Татхагата же
            называет не-парамитой. Поэтому оно и зовётся «Праджня-парамитой».</p>
        <p>Как ты думаешь, Субхути, есть ли какая-либо дхарма, которую проповедовал Татхагата?</p>
        <p>— Нет, Бхагаван. Нет никакой дхармы, которую проповедовал Татхагата.</p>
        <p>Бхагаван сказал:</p>
        <p>— Как ты думаешь, Субхути, много ли пылинок в трёх тысячах мириад миров?</p>
        <p>— Много, Бхагаван! Много, Благоушедший!</p>
        <p>Почему так? То, что Татхагата называет пылинками, Субхути, Татхагата же называет
            не-пылинками. Поэтому они и зовутся «пылинками».</p>
        <p>То, что Татхагата называет миром, Татхагата же называет не-миром. Поэтому он и зовётся
            «миром».</p>
        <p>Бхагаван сказал:</p>
        <p>— Как ты думаешь, Субхути, можно ли узнать Татхагату, Архата, Совершенного Будду по
            тридцати двум признакам великого человека?<a href="#citation-18" id="ref-18"
                                                         class="citation-mark"><sup>18</sup></a></p>
        <p>— Нет, Бхагаван. Нельзя узнать Татхагату по тридцати двум признакам великого
            человека.</p>
        <p>Почему так? То, что Татхагата называет тридцатью двумя признаками великого человека,
            Татхагата же называет не-признаками. Поэтому они и зовутся «тридцатью двумя признаками
            великого человека».</p>
        <p>Бхагаван сказал:</p>
        <p>— Более того, Субхути, если какой-либо сын или дочь из благородной семьи будет жертвовать
            своей жизнью столько раз, сколько песчинок в реке Ганг, и так — в течение стольких же
            кальп, — но если другой, взяв из этого изложения Дхармы хотя бы одну четырёхстрочную
            гатху, научит ей других и разъяснит её подробно, — то этот последний создаст неизмеримо,
            несравненно большее скопление заслуг.</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">14</h4>
        <p>И тут достопочтенный Субхути, преисполненный силой Дхармы, пролил слёзы. Вытерев их, он
            обратился к Бхагавану:</p>
        <p>— Удивительно, Бхагаван! В высшей степени удивительно, Благоушедший!</p>
        <p>Татхагата изложил эту Дхарму ради тех, кто вступил на путь высшей колесницы.</p>
        <p>Благодаря этому, Бхагаван, у меня родилось знание.</p>
        <p>Я никогда прежде не слышал изложения Дхармы в такой форме.</p>
        <p>Те бодхисаттвы, что услышат эту сутру и обретут истинное постижение
            (<em>bhūtasaṃjñā</em>), будут охвачены
            великим изумлением. Почему так? То, что называют «истинным постижением», в
            действительности не есть постижение. Поэтому его и зовут «истинным постижением».</p>
        <p>Мне, Бхагаван, нетрудно уверовать в это изложение Дхармы и принять его. Но те
            существа, кто в будущем — в последние пять столетий, когда начнётся упадок истинной
            Дхармы — возьмут эту сутру, усвоят, прочтут, изучат и разъяснят другим, — вот они-то
            будут поистине достойны изумления! Ибо у них не будет понятий атман, саттва, джива,
            пудгала. Не будет у них ни понятий, ни отсутствия понятий. Почему так? То, что есть
            понятие атман, — не есть понятие. Понятия саттва, джива, пудгала — также не-понятия.
            Почему? Потому что Будды и бодхисаттвы свободны от всех понятий.</p>
        <p>Бхагаван ответил достопочтенному Субхути:</p>
        <p>— Это так, Субхути! Именно так! Те, кто, услышав эту сутру, не устрашится, не
            содрогнётся и не убоится, — будут в высшей степени достойны изумления. Почему так? То,
            что Татхагата называет «высшей Парамитой», в действительности не есть высшая
            Парамита. Поэтому её и зовут «высшей Парамитой». Это же самое проповедуют и
            бесчисленные Будды-Бхагаваны.</p>
        <p>Более того, Субхути, то, что Татхагата называет «Парамитой терпения», не есть Парамита
            терпения. Почему так? В прошлом, Субхути, когда царь Калинга отсекал плоть от каждого
            моего члена, у меня не было понятий атман, саттва, джива, пудгала. Не было у меня ни
            понятий, ни отсутствия понятий. Почему так? Если бы у меня тогда было понятие атман,
            возникла бы и злоба. Так же — если бы у меня были понятия саттва, джива, пудгала. Более
            того, Субхути, я помню: пятьсот рождений назад я был риши Кшантивадином — проповедником
            терпения. И тогда у меня не было понятий атман, саттва, джива, пудгала. Поэтому,
            Субхути, великосущий бодхисаттва, отринув все понятия, должен породить ум, направленный
            на наивысшее совершенное Просветление. Он не должен порождать ум, опирающийся на форму,
            не должен порождать ум, опирающийся на звук, запах, вкус, осязаемое или дхармы. Он
            должен породить ум, который ни на что не опирается. Почему так? То, что считается
            опорой, есть не-опора. Поэтому Татхагата сказал: «Бодхисаттва должен совершать даяние,
            не опираясь ни
            на что. Он не должен совершать даяние, опирающееся на форму, звук, запах, вкус,
            осязаемое
            или дхармы». Более того, Субхути, ради блага всех существ бодхисаттва должен так
            совершать даяние. Почему так? То, что называют «понятием существа», не есть понятие. Те,
            о ком Татхагата говорит как о «всех существах», в действительности не суть существа.
            Почему так? Татхагата, Субхути, говорит истину, говорит правду, говорит так, как есть.
            Татхагата не говорит иначе, не говорит лжи. Но, Субхути, та Дхарма, которую Татхагата
            постиг и которой учит, — ни истина, ни ложь. Субхути, бодхисаттва, чей ум пребывает в
            дхармах, совершая даяние, подобен человеку, вошедшему во тьму: он ничего не видит. А
            бодхисаттва, чей ум не пребывает в дхармах, совершая даяние, подобен зрячему при восходе
            солнца: он видит все формы. Более того, Субхути, если сын или дочь из благородной семьи
            возьмут это изложение Дхармы, усвоят, прочтут, изучат и подробно разъяснят другим, —
            Татхагата знает их знанием Будды, Татхагата видит их оком Будды, Татхагата постигает их
            мудростью Будды. Все они, Субхути, породят и обретут неизмеримые, неисчислимые скопления
            заслуг.</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">15</h4>
        <p>Более того, Субхути: если сын или дочь из благородной семьи утром будет жертвовать своей
            жизнью столько раз, сколько песчинок в Ганге, в полдень — столько же, вечером — столько
            же, и так — в течение сотен тысяч мириад кальп, — но другой человек, услышав это
            изложение Дхармы, не отвергнет его, — то этот последний создаст гораздо большие,
            неизмеримые скопления заслуг. Что же говорить о том, кто запишет эту сутру, усвоит,
            прочтёт, изучит и подробно разъяснит другим!</p>
        <p>Более того, Субхути, это изложение Дхармы непостижимо, несравненно. И плод его
            непостижим, несравнен. Татхагата изложил его, Субхути, ради тех, кто вступил на
            высшую колесницу. Те, кто возьмёт это изложение Дхармы, усвоит, прочтёт, изучит и
            подробно разъяснит другим, — Татхагата знает их знанием Будды, Татхагата видит их оком
            Будды, Татхагата постигает их мудростью Будды. Все они, Субхути, будут наделены
            непостижимыми, несравненными, безмерными, беспредельными скоплениями заслуг. Все они,
            Субхути, обретут наивысшее совершенное Просветление. Почему так? Невозможно, Субхути,
            чтобы это изложение Дхармы услышали существа низших
            устремлений, держащиеся воззрений об атмане, о саттве, о дживе, о пудгале. Невозможно,
            чтобы это изложение Дхармы услышали, восприняли, прочли, изучили или передали существа,
            не давшие обета бодхисаттвы. Такого не может быть.</p>
        <p>Более того, Субхути, то место на земле, где будет проповедана эта сутра, станет местом
            поклонения для всего мира: для богов, людей и асуров. Ему следует воздавать почести и
            обходить его посолонь, ибо оно становится подобным ступе.</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">16</h4>
        <p>Однако, Субхути, те сыновья или дочери из благородной семьи, кто возьмёт эту сутру,
            усвоит, запомнит, изучит и подробно разъяснит другим, — станут презираемы,<a
                href="#citation-19" id="ref-19" class="citation-mark"><sup>19</sup></a> глубоко
            презираемы. Почему так? Те неблагие деяния, совершённые ими в прошлых рождениях, которые
            привели бы их в дурные уделы, — будут уничтожены благодаря этому презрению в нынешней
            жизни. И они обретут наивысшее совершенное Просветление.</p>
        <p>Я помню, Субхути: в прошлом, за неисчислимые, более чем неисчислимые кальпы до Татхагаты,
            Архата, Совершенного Будды Дипанкары, я почитал восемьдесят четыре миллиарда миллионов
            Будд, почитал их должным образом, и ни один не был отвергнут мною. Но если сравнить
            то скопление заслуг с заслугой того, кто в последние времена, в
            последние пять столетий, в эпоху упадка истинной Дхармы, возьмёт эту сутру, усвоит,
            прочтёт, изучит и подробно разъяснит другим, — то прежнее скопление заслуг не составит
            даже одной сотой части, даже тысячной, даже стотысячной, даже миллионной, даже
            стомиллионной, даже миллиардной части. Оно вообще не поддаётся исчислению, сравнению,
            уподоблению.</p>
        <p>Более того, Субхути, если бы я полностью поведал о скоплении заслуг тех сыновей или
            дочерей из благородной семьи, которые в то время будут порождать и обретать скопления
            заслуг, — существа обезумели бы, впали бы в смятение. Поэтому знай, Субхути: это
            изложение Дхармы, произнесённое Татхагатой, непостижимо, и плод его непостижим.</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">17</h4>
        <p>И тут достопочтенный Субхути спросил Бхагавана:</p>
        <p>— Как, Бхагаван, должен поступать вступивший на стезю бодхисаттвы? Как должен вести себя?
            Как направлять свой ум?</p>
        <p>Бхагаван ответил:</p>
        <p>— В этом мире, Субхути, вступивший на стезю бодхисаттвы должен породить такую мысль:
            «Всех существ я должен привести к нирване, не оставляющей остатка». И даже если так
            приведено к нирване бесчисленное множество существ, ни одно существо не
            было приведено. Почему так? Если у бодхисаттвы есть понятие саттва, его нельзя
            называть бодхисаттвой. Так же — если есть понятия атман, джива, пудгала. Ибо,
            Субхути, нет никакой дхармы, именуемой «бодхисаттва».</p>
        <p>Как ты думаешь, Субхути, есть ли какая-либо дхарма, которую Татхагата постиг как
            наивысшее совершенное Просветление от Татхагаты, Архата, Совершенного Будды
            Дипанкары?</p>
        <p>Достопочтенный Субхути ответил Бхагавану:</p>
        <p>— Насколько я понимаю смысл изречённого тобою, Бхагаван, нет никакой дхармы, которую
            Татхагата постиг как наивысшее совершенное Просветление от Татхагаты Дипанкары.</p>
        <p>Бхагаван сказал достопочтенному Субхути:</p>
        <p>— Это так, Субхути! Именно так! Нет никакой дхармы, которую Татхагата постиг как
            наивысшее совершенное Просветление от Татхагаты, Архата, Совершенного Будды
            Дипанкары.</p>
        <p>Более того, Субхути, если бы Татхагата постиг какую-либо дхарму, то Татхагата Дипанкара
            не предсказал бы обо мне: «Ты будешь в будущем, юноша, Татхагатой, Архатом, Совершенным
            Буддой по имени Шакьямуни».</p>
        <p>Но именно потому, Субхути, что Татхагата, Архат, Совершенный Будда постиг, что нет
            никакой дхармы, которая была бы наивысшим совершенным Просветлением, — именно поэтому
            Татхагата Дипанкара предсказал обо мне: «Ты будешь в будущем, юноша, Татхагатой,
            Архатом, Совершенным Буддой по имени Шакьямуни». Почему так? «Татхагата», Субхути, —
            это имя истинной таковости.<a href="#citation-20" id="ref-20"
                                          class="citation-mark"><sup>20</sup></a> Тот, кто скажет, Субхути: «Татхагата, Архат,
            Совершенный Будда постиг наивысшее
            совершенное Просветление», — тот скажет неправильно. Он ложно представит меня, Субхути,
            приняв за истину то, чего нет. Почему так? Нет, Субхути, никакой дхармы, которую
            Татхагата постиг как наивысшее совершенное Просветление.</p>
        <p>Более того, Субхути, та Дхарма, которую Татхагата постиг и которой учит, — в ней нет ни
            истины, ни лжи. Поэтому Татхагата говорит: «Все дхармы суть дхармы Будды». Почему
            так? «Все дхармы», Субхути, — Татхагата говорил о них как о не-дхармах. Поэтому
            говорится: «Все дхармы суть дхармы Будды».</p>
        <p>Субхути, это подобно тому, как если бы был человек, наделённый телом, великим телом.</p>
        <p>Достопочтенный Субхути сказал:</p>
        <p>— То, что Татхагата называет «человеком, наделённым телом, великим телом», Бхагаван,
            Татхагата же называет не-телом. Поэтому говорится: «человек, наделённым телом, великим
            телом».</p>
        <p>Бхагаван сказал:</p>
        <p>— Это так, Субхути. Если бодхисаттва скажет: «Я приведу существ к нирване», — его нельзя
            называть бодхисаттвой. Почему так? Есть ли, Субхути, какая-либо дхарма, которая была
            бы «бодхисаттвой»?</p>
        <p>Субхути ответил:</p>
        <p>— Нет, Бхагаван. Нет никакой дхармы, которая была бы «бодхисаттвой».</p>
        <p>Бхагаван сказал:</p>
        <p>— «Существа, существа», Субхути, — Татхагата говорил о них как о не-существах. Поэтому
            говорится: «существа». Поэтому Татхагата говорит: «Все дхармы лишены атмана, саттвы,
            дживы, пудгалы».</p>
        <p>Субхути, если бодхисаттва скажет: «Я создам чистые земли Будды», — о нём следует говорить
            так же. Почему так? «Чистые земли Будды, чистые земли Будды», Субхути, — Татхагата
            говорил о них как о не-чистых землях. Поэтому говорится: «чистые земли Будды».</p>
        <p>Субхути, если бодхисаттва понимает, что все дхармы лишены атмана, — его Татхагата, Архат,
            Совершенный Будда называет великосущим бодхисаттвой.</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">18</h4>
        <p>Бхагаван сказал:</p>
        <p>— Как ты думаешь, Субхути, имеет ли Татхагата телесное око?</p>
        <p>— Да, Бхагаван. Татхагата имеет телесное око.</p>
        <p>— Как ты думаешь, Субхути, имеет ли Татхагата божественное око?</p>
        <p>— Да, Бхагаван. Татхагата имеет божественное око.</p>
        <p>— Как ты думаешь, Субхути, имеет ли Татхагата око мудрости?</p>
        <p>— Да, Бхагаван. Татхагата имеет око мудрости.</p>
        <p>— Как ты думаешь, Субхути, имеет ли Татхагата око Дхармы?</p>
        <p>— Да, Бхагаван. Татхагата имеет око Дхармы.</p>
        <p>— Как ты думаешь, Субхути, имеет ли Татхагата око Будды?</p>
        <p>— Да, Бхагаван. Татхагата имеет око Будды<a href="#citation-21" id="ref-21"
                                                       class="citation-mark"><sup>21</sup></a>.</p>
        <p>— Как ты думаешь, Субхути, о песчинках, что есть в реке Ганг, — говорил ли о них
            Татхагата как о песчинках?</p>
        <p>— Да, Бхагаван. Татхагата говорил о них как о песчинках.</p>
        <p>— Как ты думаешь, Субхути, если бы было столько рек Ганг, сколько песчинок в одной реке
            Ганг, и было бы столько миров Будды, сколько песчинок во всех этих реках Ганг, — было бы
            много этих миров?</p>
        <p>— Очень много, Бхагаван!</p>
        <p>Бхагаван сказал Субхути:</p>
        <p>— Сколько бы ни было существ в этих мирах, все их потоки
            состояний ума знает Татхагата. Почему так? «Потоки состояний ума, потоки состояний
            ума», Субхути, — Татхагата говорил о них как о не-потоках. Поэтому говорится:
            «потоки состояний ума». Почему так? Прошлый ум невозможно схватить, настоящий ум
            невозможно схватить, будущий ум невозможно схватить.</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">19</h4>
        <p>Бхагаван спросил Субхути:</p>
        <p>— Как ты думаешь, Субхути, если сын или дочь из благородной
            семьи наполнит три тысячи мириад миров семью драгоценностями и преподнесёт их в дар
            Татхагатам, Архатам, Совершенно Просветлённым, — создаст ли он тем самым великое
            скопление заслуг?</p>
        <p>Субхути ответил:</p>
        <p>— Великое, Бхагаван! Великое, Благоушедший!</p>
        <p>Бхагаван сказал:</p>
        <p>— Именно так, Субхути. Он создаст великое, неизмеримое, неисчислимое скопление заслуг.
            Почему так? «Скопление заслуг, скопление заслуг», — Татхагата говорил о нём, Субхути,
            как о не-скоплении. Поэтому говорится: «скопление заслуг». Более того, Субхути, если
            бы скопление заслуг существовало как таковое, Татхагата не
            сказал бы: «скопление заслуг, скопление заслуг».</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">20</h4>
        <p>Бхагаван спросил Субхути:</p>
        <p>— Как ты думаешь, Субхути, можно ли узреть Татхагату по полноте Тела
            Формы?<a href="#citation-22" id="ref-22" class="citation-mark"><sup>22</sup></a></p>
        <p>Субхути ответил:</p>
        <p>— Нет, Бхагаван. Нельзя узреть Татхагату по полноте Тела Формы. Почему так? «Полнота
            Тела Формы, полнота Тела Формы», — Татхагата говорил о ней как о не-полноте. Поэтому
            говорится: «полнота Тела Формы».</p>
        <p>Бхагаван сказал:</p>
        <p>— Как ты думаешь, Субхути, можно ли узреть Татхагату по полноте признаков?</p>
        <p>Субхути ответил:</p>
        <p>— Нет, Бхагаван. Нельзя узреть Татхагату по полноте признаков. Почему
            так? «Полнота признаков, полнота признаков», — Татхагата говорил о ней как о
            не-полноте. Поэтому говорится: «полнота признаков».</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">21</h4>
        <p>Бхагаван спросил Субхути:</p>
        <p>— Как ты думаешь, Субхути, возникает ли у Татхагаты такая мысль: «Мною изложена Дхарма»?</p>
        <p>Субхути ответил:</p>
        <p>— Нет, Бхагаван. У Татхагаты не возникает такой мысли.</p>
        <p>Бхагаван сказал:</p>
        <p>— Тот, Субхути, кто скажет: «Татхагата изложил Дхарму», — тот скажет неправду и ложно
            представит меня, приняв за истину то, чего нет. Почему так? «Изложение Дхармы,
            изложение Дхармы», Субхути, — нет никакой дхармы, которая была бы изложением Дхармы.</p>
        <p>Тогда достопочтенный Субхути спросил Бхагавана:</p>
        <p>— Будут ли, Бхагаван, в будущем — в последние пять столетий, в эпоху упадка истинной
            Дхармы, — существа, которые, услышав такие изречения Дхармы, обретут веру?</p>
        <p>Бхагаван ответил:</p>
        <p>— Они, Субхути, ни существа, ни не-существа. Почему так? «Существа, существа», Субхути,
            — Татхагата говорил о них как о не-существах. Поэтому говорится: «существа».</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">22</h4>
        <p>Бхагаван спросил Субхути:</p>
        <p>— Как ты думаешь, Субхути, есть ли какая-либо дхарма, которую
            Татхагата постиг как наивысшее совершенное Просветление?</p>
        <p>Достопочтенный Субхути ответил:</p>
        <p>— Нет, Бхагаван. Нет никакой дхармы, которую Татхагата
            постиг как наивысшее совершенное Просветление.</p>
        <p>Бхагаван сказал:</p>
        <p>— Именно так, Субхути! Именно так! В наивысшем совершенном Просветлении
            нет даже малейшей дхармы, которую можно было бы постичь. Поэтому его и называют
            «наивысшим совершенным Просветлением».</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">23</h4>
        <p>Более того, Субхути, наивысшее совершенное Просветление едино и равно. В нём нет ничего
            неравного. Поэтому его и называют «наивысшим совершенным Просветление».</p>
        <p>В нём нет представлений об атмане, саттве, дживе, пудгале. Оно познаётся через все благие
            дхармы. Почему так? «Благие дхармы, благие дхармы», Субхути, — Татхагата говорил о
            них как о не-дхармах. Поэтому говорится: «благие дхармы».</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">24</h4>
        <p>И ещё, Субхути, если сын или дочь из благородной семьи соберёт столько гор Сумеру из семи
            драгоценностей, сколько их в трёх тысячах мириад миров, и преподнесёт их в дар
            Татхагатам, Архатам, Совершенно Просветлённым, — а другой человек, взяв хотя бы одну
            четырёхстрочную гатху из этого изложения Дхармы — Праджня-парамиты, передаст её другим и
            разъяснит её смысл, — то заслуга первого не составит даже сотой части заслуги второго,
            даже тысячной, даже стотысячной. Её невозможно исчислить, сравнить или уподобить.</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">25</h4>
        <p>Бхагаван спросил Субхути:</p>
        <p>— Как ты думаешь, Субхути, возникает ли у Татхагаты такая мысль: «Мною введены в нирвану
            существа»?</p>
        <p>— Нет, Бхагаван.</p>
        <p>— Именно так, Субхути! Именно так! Нет никакого существа, введённого Татхагатой в
            нирвану. Ибо, Субхути, если бы существовало хоть одно существо, введённое в нирвану
            Татхагатой, у Татхагаты возникло бы представление об атмане, саттве, дживе, пудгале.</p>
        <p>«Представление о я, представление о я», Субхути, — Татхагата говорил о нём как о
            не-представлении. Поэтому говорится: «представление о я».</p>
        <p>Но простые люди<a href="#citation-23" id="ref-23" class="citation-mark"><sup>23</sup></a>
            держатся этого представления. «Простые люди, простые люди», Субхути, — Татхагата
            говорил о них как о не-людях. Поэтому говорится: «простые люди».</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">26</h4>
        <p>Бхагаван спросил Субхути:</p>
        <p>— Как ты думаешь, Субхути, можно ли узреть Татхагату по полноте признаков?</p>
        <p>Субхути ответил:</p>
        <p>— Нет, Бхагаван. Насколько я понимаю смысл изречённого тобою, Татхагату нельзя узреть по
            полноте признаков.</p>
        <p>Бхагаван сказал:</p>
        <p>— Верно, Субхути! Именно так. Татхагату нельзя узреть по полноте признаков. Почему
            так? Если бы, Субхути, Татхагату можно было узреть по полноте признаков, то и
            чакравартин, вселенский царь, был бы Татхагатой. Поэтому Татхагату нельзя узреть по
            полноте признаков.</p>
        <p>Тогда Бхагаван произнёс эти гатхи:</p>
        <ul class="list-none mb-4 pl-2 space-y-2 ml-2">
            <li>«Те, кто видит Меня в форме,</li>
            <li>Те, кто следует за Моим голосом,</li>
            <li>Движимые ложным стремлением,</li>
            <li>Они не узрят Татхагату.</li>
        </ul>
        <ul class="list-none mb-4 pl-2 space-y-2 ml-2">
            <li>На Будду следует смотреть как на Дхарму,</li>
            <li>Ибо Тело Дхармы (<em>Дхармакая</em>) — это Татхагата.</li>
            <li>Природу Дхармы (<em>Дхармату</em>) нельзя постичь,</li>
            <li>Её невозможно узреть».</li>
        </ul>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">27</h4>
        <p>Бхагаван спросил Субхути:</p>
        <p>— Как ты думаешь, Субхути, постигал ли Татхагата наивысшее
            совершенное Просветление через полноту признаков?</p>
        <p>— Нет, Бхагаван.</p>
        <p>— Именно так, Субхути! Именно так! Татхагата не постигал наивысшее совершенное
            Просветление через полноту признаков. И пусть никто не скажет тебе, Субхути:
            «Вступившие на стезю бодхисаттвы учат уничтожению дхарм». Ты, Субхути, не должен
            верить в это. Почему так? Вступившие на стезю бодхисаттвы не учат уничтожению дхарм.</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">28</h4>
        <p>Более того, Субхути, если сын или дочь из благородной семьи наполнит семью
            драгоценностями столько миров, сколько песчинок в реке Ганг, и преподнесёт их в дар
            Татхагатам, Архатам, Совершенным Буддам, а бодхисаттва обретёт Парамиту терпения,
            основанную на том, что все дхармы лишены атмана и не возникают, — то именно этот
            последний породит гораздо большее скопление заслуг, неизмеримое, неисчислимое.</p>
        <p>Но великосущий бодхисаттва, Субхути, не должен привязываться к скоплению заслуг.</p>
        <p>Достопочтенный Субхути спросил Бхагавана:</p>
        <p>— Разве бодхисаттва не должен, Бхагаван, создавать скопление заслуг?</p>
        <p>Бхагаван ответил:</p>
        <p>— Должен создавать, Субхути, но не должен за это цепляться. Поэтому
            говорится: «должен создавать».</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">29</h4>
        <p>И ещё, Субхути, если кто-нибудь скажет: «Татхагата приходит или уходит, стоит или лежит»,
            — тот не понимает смысла сказанного Мною. Почему так? «Татхагата, Татхагата»,
            Субхути, — Он никуда не приходит и никуда не уходит.
            Поэтому Его и называют «Татхагата, Архат, Совершенный Будда».</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">30</h4>
        <p>И ещё, Субхути, если сын или дочь из благородной семьи превратит в пыль все миры трёх
            тысяч мириад мировых систем, — как ты думаешь, много ли было бы тех пылинок?</p>
        <p>Субхути ответил:</p>
        <p>— Много, Бхагаван! Много, Благоушедший!</p>
        <p>Бхагаван сказал:</p>
        <p>— Но, Субхути, нет такой дхармы, именуемой «пылинки». Почему так? «Пылинки, пылинки»,
            Субхути, — Татхагата называл их не-пылинками. Поэтому их и зовут «пылинками».</p>
        <p>Так же и с мирами: «Миры, миры», Субхути, — Татхагата называл их не-мирами. Поэтому их и
            зовут «мирами».</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">31</h4>
        <p>Бхагаван спросил Субхути:</p>
        <p>— Если кто-нибудь скажет: «Татхагата проповедует взгляд об
            атмане, саттве, дживе, пудгале», — понял ли он, Субхути, смысл Моих слов?</p>
        <p>Субхути ответил:</p>
        <p>— Нет, Бхагаван. Такой человек не понял смысла Ваших слов.</p>
        <p>Бхагаван сказал:</p>
        <p>Почему так? Когда Татхагата
            говорит об «атмане», он не утверждает атман; когда говорит о «саттве», он не утверждает
            саттву; когда говорит о «дживе», он не утверждает дживу; когда говорит о «пудгале»,
            он не утверждает пудгалу. Поэтому их и называют «атманом, саттвой, дживой, пудгалой».</p>
        <p>— И ещё, Субхути, тот, кто стремится к наивысшему совершенному Просветлению, должен
            познавать все дхармы так, что не возникает признака дхармы. Почему так? «Признак
            дхармы, признак дхармы», Субхути, — Татхагата называл его
            не-признаком. Поэтому его и зовут «признаком дхармы».</p>

        <h4 class="inline-flex items-center justify-center w-8 h-8 bg-amber-100 rounded-full
        shadow-lg mt-2 mb-2 ml-8">32</h4>
        <p>И ещё, Субхути, если сын или дочь из благородной семьи наполнит миры семью
            драгоценностями и преподнесёт их в дар Татхагатам, Архатам, Совершенно Просветлённым, —
            а другой человек возьмёт из этого изложения Дхармы хотя бы одну четырёхстрочную гатху,
            усвоит её, прочтёт, изучит и разъяснит другим, — то заслуга второго превзойдёт заслугу
            первого.</p>
        <p>И как следует разъяснять? На все составные дхармы следует смотреть так: как на сон, как
            на иллюзию, как на марево, как на пузырь на воде, как на росу, как на молнию.<a
                href="#citation-24" id="ref-24" class="citation-mark"><sup>24</sup></a></p>
        <p>Когда Бхагаван завершил эту сутру, достопочтенный Субхути, монахи и монахини, миряне и
            мирянки, а также боги и асуры этого мира восприняли сказанное с великой радостью, обрели
            веру и последовали Дхарме.</p>
        <p>Так завершилась сутра о Совершенной мудрости — Ваджрной Праджня-парамите.</p>
