                ограниченное материальными формами;<br>
                2. Божественное око (divya-cakṣus) — способность видеть
                перерождения существ, их кармические связи, далёкие миры и
                тонкие явления;<br>
                3. Око мудрости (prajñā-cakṣus) — прямое прозрение в пустотность
                (śūnyatā) всех дхарм, видение их бессамостности;<br>
                4. Око Дхармы (dharma-cakṣus) — непосредственное постижение
                истинной природы реальности: Четырёх Благородных Истин,
                взаимозависимого возникновения, природы ума;<br>
                5. Око Будды (buddha-cakṣus) — всеведение (sarvajñatā),
                одновременное проникновение во все миры, все умы всех существ,
                прошлое-настоящее-будущее без препятствий.<br>
                Контекст сутры (§17-18): Будда обладает всеми пятью видами зрения,
                но не цепляется ни за один как за сущность или достижение. Более
                того, все «потоки сознания» существ известны Будде, но сами эти
                потоки — не-потоки, а мысли — неуловимы в трёх временах.<a href="#ref-21"
                                                                           class="text-blue-500 hover:underline">↩</a>
            </p>
            <p class="my-2" id="citation-22"><sup>22</sup> Тело Формы (rūpa-kāya) — в доктрине
                трёх Тел Будды (tri-kāya) это собирательное название для двух проявленных Тел:<br>
                • Нирманакая (nirmāṇa-kāya) — «Тело Преображения»: физическое
                проявление Будды в мире людей (например, исторический Будда
                Шакьямуни) для проповеди Дхармы обычным существам;<br>
                • Самбхогакая (saṃbhoga-kāya) — «Тело Наслаждения»: величественное,
                украшенное всеми признаками проявление в чистых землях для
                высоких бодхисаттв;<br>
                • Дхармакая (dharma-kāya) — «Тело Дхармы»: абсолютная природа
                Будды, недвойственная таковость (tathatā), запредельная всякой
                форме и концепции, тождественная пустотности (śūnyatā).<br>
                Контекст сутры (§5, 20, 26): нельзя «узреть Татхагату» через
                rūpa-kāya или через полноту его признаков (lakṣaṇa-saṃpad). Хотя
                Будда проявляется в форме из сострадания, его истинная природа —
                бесформенная Дхармакая. «На Будду следует смотреть как на Дхарму,
                Ибо Тело Дхармы (Дхармакая) — это Татхагата.» (§26, гатха).<a href="#ref-22"
                                                                              class="text-blue-500 hover:underline">↩</a>
            </p>
            <p class="my-2" id="citation-23"><sup>23</sup> Простые, невежественные люди
                (bāla-pṛthag-jana) — санскр. bāla («неразумный, незрелый, детский») + pṛthag-jana
                («обособленные существа, отдельный народ»). Технический термин для обозначения
                обыкновенных, непросветлённых существ, которые:<br>
                • не постигли пустотность (śūnyatā) и бессамостность (anātman);<br>
                • цепляются за «я» и явления как за реально существующие сущности;<br>
                • держатся представлений (saṃjñā) о самости, существах, душе, личности;<br>
                • не вступили на путь освобождения.<br>
                Противопоставляются благородным (ārya-pudgala) — тем, кто вступил в поток Дхармы
                (минимум сротапанна) и непосредственно постиг истинную природу реальности.<br>
                Контекст сутры (§25, 30, 31): простые люди «держатся» (abhiniveśa)
                представлений о «я», «сущностной реальности» и других концепций,
                тогда как благородные свободны от всех признаков (sarva-nimitta-
                vigatāḥ).<a href="#ref-23" class="text-blue-500 hover:underline">↩</a></p>
            <p class="my-2" id="citation-24"><sup>24</sup> Шесть метафор непостоянства (§32,
                заключительная гатха) — каждая символизирует грань иллюзорности всех составных
                явлений (saṃskṛta- dharma):<br>
                • Сон (svapna) — кажущаяся реальность того, что на самом деле нереально;
                переживается как истинное, но исчезает при пробуждении;<br>
                • Иллюзия, мираж (māyā) — магическое наваждение, обман восприятия;
                кажется существующим, но лишено субстанции;<br>
                • Марево (marīci) — оптическая иллюзия в пустыне; неуловимость,
                тщетность преследования призрачного;<br>
                • Пузырь [на воде] (budbuda) — хрупкость, мгновенное возникновение
                и исчезновение без следа;<br>
                • Роса (cchāyā — букв. «тень») — мимолётность, исчезновение при
                первом луче солнца/понимания;<br>
                • Молния (vidyut) — ослепительная вспышка; мгновенность даже
                самого яркого явления.<br>
                Вместе они показывают: всё обусловленное (saṃskṛta) лишено
                постоянства (nitya), самости (ātman) и независимого существования
                (svabhāva). «Так следует созерцать их» (evaṃ draṣṭavyam) — не как
                интеллектуальное понимание, а как прямое видение природы всех
                явлений.<a href="#ref-24" class="text-blue-500 hover:underline">↩</a></p>
