<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4 text-black">
    <p class="text-right italic text-lg text-gray-800">В.&nbsp;М.&nbsp;Монтлевич</p>

    <p>Публикуемый русский перевод ритуала имеет длинную предысторию. Началась она в 1968 г., когда Б.&nbsp;Д.&nbsp;Дандарон дал своим ученикам подстрочный перевод текста. Потребовалось двадцать семь лет переводческих и созерцательных усилий, чтобы окончательно в рамках традиции Дандарона сложилась русская версия этого древнего текста. Подстрочный перевод Учителя побудил В.&nbsp;Н.&nbsp;Пупышева и А.&nbsp;М.&nbsp;Донца, независимо друг от друга, снова перевести этот текст. Их перевод был просмотрен санскритологом О.&nbsp;Ф.&nbsp;Волковой, были внесены незначительные уточнения. В дальнейшем перевод уточнялся и адаптировался к семантике русского языка, и, наконец, была создана версия, передающая поэтическим ритмом магическую энергию ритуала. В публикуемом виде перевод завершен в 1994 г., с этого же года согшод проводится по-русски; впервые опубликован на сайте «Правидья» в 1999 г. Оригинальные обороты нашего перевода повлияли на некоторые последующие публикации этого текста<a href="#citation-1" id="ref-1" class="citation-mark"><sup>1</sup></a>.</p>
    <p>Согшод, или на санскрите <em>ганачакра</em>, является главным ритуалом буддийских тантристов. Это ритуал соборного жертвоприношения Учителю. Он исполнялся издревле в Индии, был унаследован в Тибете и затем через Монголию и Бурятию пришел в Россию. Согшод воспроизводит в ритуальной символической форме полноту вселенского жизненного цикла. Этот цикл включает глубину микромира, распахнутость космоса и тайну живого. Первые строчки содержат предельно сжатое определение Бытия: «Сущность — Мудрость, Форма — Жертва». Мир, согласно этой формуле, совершенен и самопроявлен. Самопроявленность именуется «жертвой». Ритуальный, осознанный резонанс с постоянно совершающимся жертвенным мировым действом — мистерией Бытия — смысл переживания проводящего согшод. Такое определение согшода позволяет утверждать, что его необходимо творить постоянно, и более того — наша жизнь есть непрерывно длящийся согшод, вселенское жертвоприношение. Вне согшода просто невозможно быть. Остается только осознать это, и, осознав, никогда не упускать это осознание, и иногда в яркой пиршественной форме совершать его, собирая в минуты ритуала концентрацию силы и ясность понимания смысла.</p>

