    <!-- 1. Сущность Согшода уровня карнатантры -->
    <h3 class="mt-8 mb-4">1. <em>Сущность Согшода уровня карнатантры</em></h3>

    <p>Жертва — отделение части от целого, размножествление, рождение единичного. Единичное возникает как форма существования Целого; через запрограммированное время, будь то физическое или биологическое, достигает полноты Целого, созревает и само совершает акт деления или жертвы.</p>

    <p>Жертвование может совершаться по вере. Но в развитии личности наступает момент, когда постоянно присутствовавшая в нем полнота осознается, и тогда совершается сознательное жертвование. Жертвователь осознает, что все воспринимаемое им шестью органами чувств есть жертва Целого. Поняв так, он ни на мгновение не задерживает воспринятое и отдает его той же полноте в лице окружающего его мира — природе и живым существам. При этом жертвователь испытывает блаженство и обретает мудрость недвойственности блаженства и шуньяты. Когда он приучается к такому деянию и пронизывает им все свои действия, он становится <em>жрецом</em> — тем, кто пропускает через себя жертву, не задерживая её. Жрец реализует форму ваджра и обладает ваджрным здоровьем.</p>

    <p>Обратимся к строкам текста.</p>

    <p><span class="font-bold text-red-700">ОМ А ХУМ, ОМ А ХУМ, ОМ А ХУМ</span></p>

    <p>Этим очищается место проведения ритуала и призываются Три Ваджра — Тело, Речь и Мысль Будды.</p>

    <ul class="space-y-2 text-left list-none ml-6 text-xl my-6">
        <li>Сущность — Мудрость, Форма — Жертва.</li>
        <li>Данная внутри и внешне,</li>
        <li><strong>Шествуя</strong> шестью путями</li>
        <li>В сфере чувственных явлений,</li>
        <li>Все пространство, землю, небо</li>
        <li><strong>Заполняя</strong> подношеньем</li>
        <li>Внешним, внутренним и тайным —</li>
        <li>Из предметов ритуальных,</li>
        <li>Образов и неохватных</li>
        <li>Даже мыслью жертв бескрайних,</li>
        <li>Чудным образом <strong>рождает</strong></li>
        <li>Мудрость Пустоты-Блаженства!</li>
    </ul>

    <p><strong>Сущность — Мудрость.</strong> В русском языке мудростью называется знание, соединенное с состраданием. Знание — постоянное статичное зерно Бытия, сострадание — динамика знания, его развертывание, иногда его называют не совсем точно словом «энергия».</p>

    <p><strong>Форма — Жертва.</strong> Развертывание всегда обретает образ, форму. По отношению к целому это будет жертвой: одно стало многим.</p>

    <p><strong>Шествуя</strong> — способность восприятия и сам процесс восприятия, полнота жизнепроявленности.</p>

    <p><strong>Заполняя</strong> — воспринятое мгновенно передается, в данном случае тремя способами жертвования: внешним — отдача предметов, еды, внутренним — угощение нектаром (амритой), тайным — одарение блаженством страсти.</p>

    <p><strong>Рождает</strong> — обретение и переживание в сердце мудрости единства пустоты и блаженства.</p>

    <p>Сказанное есть комментарий к начальным и самым важным строфам Согшода, представляющих собой мировоззрение Согшода — <em>тава</em> (<em>lta-ba</em>): восприняв данное во всех аспектах ощущение как жертву Дхармакаи, мгновенно любым способом одариваешь воспринятым всех живых. Тогда в тебе рождается мудрость недвойственности, и ты поистине становишься сознательным соучастником Бытия — жрецом. В нашем случае — ачарьей.</p>

