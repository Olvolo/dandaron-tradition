    <p><strong><em>Те, кто знают это так</em></strong> (<span class="font-bold text-red-700">ХУМ</span>) — спица (ступица становится спицей) — Нирманакая — Зерцалоподобная Мудрость.</p>
    <p><strong><em>Рассуждения отбросив</em></strong> (<span class="font-bold text-red-700">ОМ</span>) — ступица — Дхармакая — Мудрость Дхармового Пространства,</p>
    <p><strong><em>Веселятся в дивной Чакре</em></strong> (<span class="font-bold text-red-700">А</span>) — обод — Самбхогакая.</p>
    <p>Собравшиеся на Согшод образуют собой Чакру — средство вхождения в состояние Будды. Чтобы Чакра пришла в движение, необходимо отбросить концептуальный тип мышления — <em><strong>рассуждения отбросив</strong></em> — и достичь внеконцептуальности (<em>авикальпа</em>). Вращение Чакры обнаруживает, что внутренняя структура спиц — тоже чакра; такое понимание оборачивается переживанием <em>веселия</em>: Мудрость Дхармового Пространства искрится Зерцалоподобной Мудростью, Акшобхья и Вайрочана танцуют контрданс — это известная «Тельняшка Железнова» — чередование символических цветов названных дхьянибудд — синего и белого. Каждый участник ритуала, благодаря вращению Чакры, может увидеть центр, то есть Учителя, глазами своего собрата, что возможно только в состоянии динамического очищения от индивидуального <em>Я</em>. Поэтому на согшод приходят, только сняв все проблемы взаимоотношений друг с другом.</p>

    <!-- 8. Песня Ачарьи-Учителя -->
    <h3 class="mt-8 mb-4">8. <em>Песня Ачарьи-Учителя</em> (<em>rang-gi-don</em> — «для себя»)</h3>

    <ul class="space-y-2 text-left list-none ml-6 text-xl my-6">
        <li><span class="font-bold text-red-700">ОМ</span> — тождественный Трем Ваджрам,</li>
        <li>Вот я сам — Идам — Учитель.</li>
        <li><span class="font-bold text-red-700">А</span> — чистейшим соком Джняны,</li>
        <li><span class="font-bold text-red-700">ХУМ</span> — держась за Бодхичитту,</li>
        <li>Веселюсь с богами тела — <span class="font-bold text-red-700">А ХО МАХА СУХА</span>!</li>
    </ul>

    <p><span class="font-bold text-red-700">ОМ</span> — возжигает достоинство Будды во всех живых, делает их тождественными друг другу. Ачарья гордо заявляет, что неотличим от Идама и Учителя — <strong><em>тождественный Трем Ваджрам</em></strong>, Трикая реализована в Учителе-Ачарье: «Вот я сам (Нирманакая) — Идам (Самбхогакая) — Учитель (Дхармакая)».</p>
    <p><span class="font-bold text-red-700">А</span> (динамическая последовательность пяти махабхут, это можно показать только графически) — <strong><em>чистейшим</em></strong> (<span class="font-bold text-red-700">ОМ</span>) <strong><em>соком</em></strong> (<span class="font-bold text-red-700">А</span>) <strong><em>джняны</em></strong> (<span class="font-bold text-red-700">ХУМ</span> — интуиция, познающая шуньяту). Учитель пьет нектар.</p>
    <p><span class="font-bold text-red-700">ХУМ</span> — <strong><em>держась за бодхичитту</em></strong> — Пребывая в «самадхи тела (<span class="font-bold text-red-700">ОМ</span>) чистой (<span class="font-bold text-red-700">А</span>) мысли (<span class="font-bold text-red-700">ХУМ</span>)» = бодхичитта, не отхожу от нее,</p>
    <p><strong><em>Веселюсь</em></strong> (<span class="font-bold text-red-700">А</span>) <strong><em>с богами</em></strong> (<span class="font-bold text-red-700">ХУМ</span>) <strong><em>тела</em></strong> (<span class="font-bold text-red-700">ОМ</span>).</p>
    <p>Все собранное в качестве жертвы подносится на алтарь Учителю и сонму божеств. Участникам ритуала раздается угощение, а остатки собираются перед угощением всех живых для благословения.</p>

    <!-- 9. Ритуал Ачарьи -->
    <h3 class="mt-8 mb-4">9. <em>Ритуал Ачарьи</em> (<em>gzhan-gi-don</em> — для других)</h3>

    <ul class="space-y-2 text-left list-none ml-6 text-xl my-6">
        <li><span class="font-bold text-red-700">ХУМ</span> — нечистое исчезло,</li>
        <li><span class="font-bold text-red-700">А</span> — сок Джняны прибывает,</li>
        <li><span class="font-bold text-red-700">ОМ</span> — желанное повсюду!</li>
    </ul>

    <p><span class="font-bold text-red-700">ХУМ</span> — <strong><em>нечистое исчезло</em></strong>: очищение мыслью,</p>
    <p><span class="font-bold text-red-700">А</span> — <strong><em>сок Джняны прибывает</em></strong>: очищение речью, нектар проповеди; здесь амриту пьет Ачарья.</p>
    <p><span class="font-bold text-red-700">ОМ</span> — <strong><em>желанное повсюду</em></strong>: познание телом. Удовлетворяется океан желаний, насыщается спектр всех чувств, исчезает сенсорный голод, все живые радуются — шестой дхьянибудда — Адибудда, единство всех живых, тождество сансары и нирваны.</p>

    <h3 class="mt-8 mb-4">10. <em>Далее: угощение остатками жертвоприношения духов местности и прочих духов.</em></h3>
    <h3 class="mt-8 mb-4">11. <em>Затем: заклинательный речитатив и броска.</em></h3>
