    <h3 class="mt-8 mb-4">3. <em>Приготовление нектара</em></h3>

    <p>Далее начинается алхимия Согшода — приготовление нектара, или амриты. Слог <span class="font-bold text-red-700">ХУМ</span> — сущность Дхармакаи — возбуждает пространство Дхармадхату («акаша, впавшая в метрику»), основу всего проявленного. В пространстве начинается движение, символ его — ветер. Ветер воздействует на огонь, огонь — на стенки капалы, внутри которой десять составляющих из пяти мужских и пяти женских махабхут начинают плавиться и вскипать.</p>

    <ul class="space-y-2 text-left list-none ml-6 text-xl my-6">
        <li><span class="font-bold text-red-700">ХУМ</span> — Пространство Дхармакаи,</li>
        <li>Проявлений всех Основа.</li>
        <li>Ветер воздымает пламя</li>
        <li>В очаге троеголовом,</li>
        <li><span class="font-bold text-red-700">А</span> — громадная капала,</li>
        <li><span class="font-bold text-red-700">ОМ</span> — все жертвенные яства</li>
        <li>По отдельности пылают.</li>
    </ul>

    <p>Над капалой расположились Три Слога, и состав кипит.</p>

    <ul class="space-y-2 text-left list-none ml-6 text-xl my-6">
        <li>Над капалою — <span class="font-bold text-red-700">ОМ А ХУМ</span></li>
        <li>Самоцветно воссияли.</li>
        <li>Ветры буйные, раздуйте</li>
        <li>В очаге сильнее пламя!</li>
        <li>Все, что собрано отдельно,</li>
        <li>В общем изобилье тает</li>
        <li>И, расплавившись, вскипает.</li>
    </ul>

    <p>От Трех Слогов исходят лучи и приглашают Три Ваджра — Тело, Речь и Мысль Всех Будд, которые, как нектар, пропитывают эти Слоги. Слоги плавятся до нектара и падают в капалу, где десятисоставное варево уже сплавилось в нечто единое, но еще не обрело свойств амриты.</p>

    <ul class="space-y-2 text-left list-none ml-6 text-xl my-6">
        <li>Три Слога, освещая</li>
        <li>Все стороны лучами,</li>
        <li>Три Ваджра приглашают,</li>
        <li>Подобные Нектару.</li>
        <li>Те, в каждый Слог проникнув,</li>
        <li>Расплавив до Нектара,</li>
        <li>В капале в сок вступают.</li>
    </ul>

    <p>Наступает кульминация приготовления нектара. Три Слога с достоинствами Трех Ваджров воздействуют на содержимое капалы тройным способом: Мыслью (<span class="font-bold text-red-700">ХУМ</span>) очищают; Речью (<span class="font-bold text-red-700">А</span>) — все становится понятным и постижимым; Телом (<span class="font-bold text-red-700">ОМ</span>) возжигается во всех живых достоинство Будд, обращая их в даков и дакинь.
    </p>

    <ul class="space-y-2 text-left list-none ml-6 text-xl my-6">
        <li><strong>Очистив, познав и зажгя</strong> — <span class="font-bold text-red-700">Э МА ХО</span>,</li>
        <li>Полнота желанного</li>
        <li>Стала морем пламенным!</li>
