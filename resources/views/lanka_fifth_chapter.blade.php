<p class="my-2" id="citation-469"><sup>469</sup> Аргумент <em>ubhayadoṣa</em> («двойной ошибки»), уже встречавшийся в третьей главе, здесь применяется к категориям вечности и непостоянства. Обе позиции предполагают, что Татхагата — некая сущность, которая либо сохраняется, либо гибнет. Вечность отождествляет Его с несотворёнными первопричинами тиртхиков — Ишварой, Прадханой, Пурушей. Непостоянство — с горшком, тканью, любым сотворённым объектом, чей распад ведёт к уничтожению. Ни одна из этих моделей не применима, поскольку Татхагата не есть сущность такого рода.<a href="#ref-469" class="citation-back">↩</a></p>
<p class="my-2" id="citation-470"><sup>470</sup> Аргумент построен на классическом буддийском примере «рогов зайца» (<em>śaśaviṣāṇa</em>) — стандартном образе абсолютно несуществующего. Рога зайца «вечны» лишь в том смысле, что они никогда не возникали — но это пустая вечность, вечность отсутствия. Будда указывает: если понимать вечность Татхагаты как «вечность не-возникновения», она сводится к той же пустоте — к простому отсутствию, лишённому какого-либо содержания. Это подмена: вместо описания природы Татхагаты получается её растворение в ничто. Подлинное не-возникновение (<em>anutpāda</em>) Татхагаты указывает на реальность, выходящую за пределы категорий бытия и небытия.<a href="#ref-470" class="citation-back">↩</a></p>
<p class="my-2" id="citation-471"><sup>471</sup> Категории «вечное» и «непостоянное» — порождения речевого различения (<em>vāgvikalpa</em>): пока ум производит слова и понятия, он неизбежно делит реальность на противоположности. Путь к освобождению от этих категорий — угасание различающего разума (<em>vikalpabuddhi</em>). Будда при этом особо оговаривает: речь идёт об угасании именно различающего разума. Разум, обладающий очищенным видением (<em>vivikta-dṛṣṭi-buddhi</em>), продолжает действовать — вне двойственных категорий.<a href="#ref-471" class="citation-back">↩</a></p>
