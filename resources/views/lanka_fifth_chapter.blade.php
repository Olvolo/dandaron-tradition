<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <p>Затем Бодхисаттва-махасаттва Махамати вновь обратился к Благословенному:</p>
    <p>О Благословенный, является ли Татхагата, Архат, Совершенно Пробуждённый вечным (<em>nitya</em>) или непостоянным (<em>anitya</em>)?</p>

    <p>Благословенный ответил:</p>
    <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Махамати, Татхагата ни вечен, ни непостоянен. Почему? Потому что это привело бы к двойной ошибке (<em>ubhaya-doṣa</em>).<a href="#citation-469" id="ref-469" class="citation-mark"><sup>469</sup></a></li>
        <li>Если бы Татхагата был вечен, следовало бы, что Он является [перво]причиной (<em>kāraṇa</em>). Ведь у всех тиртхиков первопричины считаются вечными и несотворёнными. Поэтому Татхагата не является вечным, ибо такое «вечное» означало бы несотворённость (<em>akṛtaka</em>).</li>
        <li>Если бы он был непостоянным, следовало бы, что он является сотворённым (<em>kṛtaka</em>). Поскольку отсутствуют <em>скандхи</em> как основание обозначения и их признаки, то при разрушении  <em>скандх</em> следовало бы полное уничтожение (<em>uccheda</em>). Но Татхагата не является уничтожимым.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Махамати, всё сотворённое непостоянно — как горшок, ткань, трава, дерево или кирпич. Если бы Татхагата был сотворён [и непостоянен], то накопление всеведения и мудрости было бы напрасным. Тогда всё сотворённое могло бы быть Татхагатой, ибо не было бы особой причины [для отличия].</li>
        <li>По этой причине, Махамати, Татхагата — ни вечен, ни непостоянен.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Кроме того, Махамати, Татхагата не является вечным (<em>nitya</em>). Почему? Потому что это привело бы к бессмысленности [всякого] накопления [заслуг и мудрости] — ведь пространство вечно без какого-либо накопления.</li>
        <li>Подобно тому, Махамати, как пространство — ни вечно, ни непостоянно, ибо оно свободно от двойственности вечности и непостоянства, — так и [Татхагата] невыразим через пороки [логических крайностей]: единства или отличия, того и другого или ни того, ни другого, вечности или непостоянства.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Более того, Махамати, [если бы Татхагата был вечным лишь в смысле не-возникновения], Он был бы подобен рогам зайца, лошади, осла, верблюда, лягушки, змеи, мухи или рыбы, [которые считаются] «вечными» [лишь] по причине своего не-возникновения (<em>anutpāda-nityatva</em>). Таким образом, из-за [абсурдности] этого вывода о «вечности как не-возникновении» — Татхагата не является вечным.<a href="#citation-470" id="ref-470" class="citation-mark"><sup>470</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Более того, Махамати, существует подход, в котором Татхагата вечен. Почему? Потому что Татхагата вечен благодаря вечности знания прямого постижения (<em>abhisamayādhigamajñāna</em>). Поистине, Махамати, знание прямого постижения вечно у Татхагат, Архатов, Совершенно Пробуждённых.</li>
        <li>Независимо от того, возникают ли Татхагаты или нет, эта таковость (Истинная Природа) (<em>dharmatā</em>), эта закономерность дхарм (<em>dharma-niyāmatā</em>), эта устойчивость дхарм (<em>dharma-sthititā</em>) остаётся неизменной в постижениях шраваков, пратьекабудд и тиртхиков. Однако эта устойчивость дхарм не пребывает в пространстве, и невежды не понимают её.</li>
        <li>Знание о постижении у Татхагат, Махамати, озарено <strong>высшей мудростью</strong> (<em>prajñā-jñāna</em>). Татхагаты, Махамати, не обусловлены умом, <em>манасом</em>, сознанием, <em>скандхами</em>, <em>дхату</em>, <em>аятанами</em> или отпечатками неведения. Ибо весь тройственный мир, Махамати, возникает из <strong>ложного различения</strong> (<em>abhūta-vikalpa</em>), но Татхагаты не порождены ложным различением.</li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>Там, где есть двойственность, Махамати, там возникает «вечность» и «непостоянство», но не в недвойственности. Двойственность, Махамати, лишена основания, поскольку все дхармы имеют признак недвойственного не-возникновения.</li>
        <li>По этой причине Татхагаты — ни вечны, ни непостоянны. До тех пор, Махамати, пока развёртывается <strong>речевое различение</strong> (<em>vāg-vikalpa</em>), — до тех пор будет преследовать порок [крайностей] вечности и непостоянства. Лишь через <strong>угасание различающего разума</strong> (<em>vikalpa-buddhi</em>) устраняется цепляние за вечность и непостоянство у невежд, но не через угасание разума с очищенным видением, свободным от различения (<em>vivikta-dṛṣṭi-buddhi</em>).<a href="#citation-471" id="ref-471" class="citation-mark"><sup>471</sup></a></li>
    </ul>

    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>1. Те, кто всегда видят Будд</li>
        <li>свободными от вечности и непостоянства —</li>
        <li>пусть даже их представляют «вечными» и «непостоянными» —</li>
        <li>те во власти воззрений не пребывают.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>2. Если принимать вечность или непостоянство [буквально],</li>
        <li>возникает бессмысленность достижения.</li>
        <li>Через устранение изъянов различающего разума</li>
        <li>отвергаются крайности вечности и непостоянства.</li>
    </ul>
    <ul class="list-none mb-8 pl-2 space-y-1 ml-2">
        <li>3. До тех пор, пока выдвигается какой-либо [логический] тезис,</li>
        <li>всё [познание] остаётся смешанным [с заблуждением].</li>
        <li>Видя всё как «только-ум» (<em>svacitta-mātra</em>),</li>
        <li>не следует вступать в споры.</li>
    </ul>
    </blockquote>

    <p class="text-center font-bold">***</p>
