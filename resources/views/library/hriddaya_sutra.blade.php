            <p class="my-2" id="citation-3"><sup>3</sup> <strong>Пять скандх (pañca
                    skandhāḥ)</strong>. Skandha — букв. «куча», «груда», «агрегат». Пять скандх —
                это пять совокупностей или групп элементов, которые в сочетании создают иллюзию
                целостной личности или «Я»:<br><strong>Rūpa</strong> — форма (тело человека и весь
                физический мир, воспринимаемый органами чувств.)<br><strong>Vedanā</strong> —
                ощущение (Первичная эмоциональная реакция на контакт органов чувств с объектами.
                Бывает трех видов: приятное, неприятное или нейтральное.)<br><strong>Saṃjñā</strong>
                — распознавание/восприятие (Способность ума определять и классифицировать объекты
                (например, «это синий цвет», «это человек», «это звук»). Это наложение имен и
                ярлыков)<br><strong>Saṃskāra</strong> — <strong>Формирующие факторы</strong>
                (Волевые импульсы). Самая сложная скандха. Это наши привычки, волевые решения,
                кармические отпечатки и психологические установки, которые заставляют нас
                действовать тем или иным образом.<br><strong>Vijñāna</strong> — сознание. Чистое
                осознавание присутствия объекта. Оно разделяется по шести каналам: сознание глаза,
                уха, носа, языка, тела и ума.<a href="#ref-3" class="text-blue-500 hover:underline">↩</a>
