    <h1 class="text-center text-blue-900 font-bold text-2xl sm:text-2xl md:text-2xl mt-6 mb-6">Сутра
        Сердца Праджняпарамиты</h1>
    <div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
        <h4 class="text-center"><strong>На санскрите: Prajñāpāramitā Hṛdaya Sūtra</strong><a
                href="#citation-1" id="ref-1" class="citation-mark"><sup>1</sup></a></h4>
        <p><em>Ом! Поклонение Благословенной Арья-Праджняпарамите!</em></p>
        <p>Так я слышал. Однажды Благословенный пребывал в Шравасти, в саду Джеты, в монастыре
            Анатхапиндики, вместе с великим собранием монахов — тысячей тремястами пятьюдесятью
            бхикшу — и вместе с пятьюдесятью бодхисаттвами-махасаттвами.<a href="#citation-2"
                                                                           id="ref-2"
                                                                           class="citation-mark"><sup>2</sup></a>
        </p>
        <p>И тогда Благословенный, обращаясь к достопочтенному Субхути, изложил Сердце
            Праджняпарамиты. А именно:</p>
        <p>Бодхисаттва-махасаттва Арья-Авалокитешвара, пребывая в практике глубокой Праджняпарамиты,
            внимательно созерцал и увидел: пять скандх<a href="#citation-3" id="ref-3"
                                                         class="citation-mark"><sup>3</sup></a> по
            своей природе —
            шунья.<a href="#citation-4" id="ref-4" class="citation-mark"><sup>4</sup></a></p>
        <p>Здесь, о Субхути: форма — шуньята; шуньята — форма.</p>
        <p>Форма неотделима от шуньяты; шуньята неотделима от формы.</p>
        <p>Что есть форма — то есть шуньята; что есть шуньята — то есть форма.<a href="#citation-5"
                                                                                 id="ref-5"
                                                                                 class="citation-mark"><sup>5</sup></a>
        </p>
        <p>Так же и с ощущением, распознаванием, формирующими факторами и сознанием.<a
                href="#citation-6" id="ref-6" class="citation-mark"><sup>6</sup></a></p>
        <p>Здесь, о Субхути, все дхармы носят печать шуньяты:</p>
        <ul class="list-disc pl-5 space-y-1 ml-8">
            <li class="my-2">не возникающие и не прекращающиеся,</li>
            <li class="my-2">не загрязнённые и не чистые,</li>
            <li class="my-2">ни едины, ни множественны,</li>
            <li>без различий,</li>
            <li>ни высшие, ни низшие.<a
                    href="#citation-*" id="ref-*" class="citation-mark"><sup>*</sup></a></li>
        </ul>
        <p>Потому в шуньяте:</p>
        <ul class="list-disc pl-5 space-y-1 ml-8">
            <li class="my-2">ни формы, ни ощущения, ни восприятия, ни формирующих факторов, ни
                сознания;<a href="#citation-7" id="ref-7" class="citation-mark"><sup>7</sup></a>
            </li>
            <li class="my-2">ни глаза, ни уха, ни носа, ни языка, ни тела, ни ума;</li>
            <li class="my-2">ни формы, ни звука, ни запаха, ни вкуса, ни осязаемого, ни объектов
                ума;<a href="#citation-8" id="ref-8" class="citation-mark"><sup>8</sup></a></li>
            <li class="my-2">ни сферы зрения... вплоть до ни сферы умственного сознания;<a
                    href="#citation-9" id="ref-9" class="citation-mark"><sup>9</sup></a></li>
            <li class="my-2">ни неведения, ни знания,</li>
            <li>ни формирующих факторов, ни мудрости,</li>
            <li>ни достижения, ни недостижения.</li>
        </ul>
        <p>Потому, в силу недостижения,<a href="#citation-10" id="ref-10"
                                          class="citation-mark"><sup>10</sup></a> бодхисаттва,
            опираясь на Праджняпарамиту, пребывает без покровов в уме.<a href="#citation-11"
                                                                         id="ref-11"
                                                                         class="citation-mark"><sup>11</sup></a>
            Его ум не привязывается — и потому нет привязанности. Он свободен от страха, преодолел
            все искажения и достиг окончательной нирваны.</p>
        <p>Все Будды трёх времён, опираясь на Праджняпарамиту, достигли высшего полного пробуждения.<a
                href="#citation-12" id="ref-12" class="citation-mark"><sup>12</sup></a></p>
        <p>Поэтому следует знать:</p>
        <p>Праджняпарамита — это великая мантра,<a href="#citation-13" id="ref-13"
                                                   class="citation-mark"><sup>13</sup></a> великое
            знание,<a href="#citation-14" id="ref-14" class="citation-mark"><sup>14</sup></a>
            непревзойдённая мантра,<a href="#citation-15" id="ref-15"
                                      class="citation-mark"><sup>15</sup></a> несравненная мантра,<a
                href="#citation-16" id="ref-16" class="citation-mark"><sup>16</sup></a> укрощающая
            всё страдание.<a href="#citation-17" id="ref-17" class="citation-mark"><sup>17</sup></a>
        </p>
        <p>Это — истина, ибо лишена обмана.</p>
        <p>В Праджняпарамите провозглашена великая мантра. А именно:</p>
        <p class="text-center"><strong>Гате гате парагате парасамгате бодхи сваха!</strong></p>
        <p class="text-center"><strong>(gate gate pāragate pārasaṃgate bodhi svāhā)</strong><a
                href="#citation-18"
                id="ref-18" class="citation-mark"><sup>18</sup></a></p>
        <p>Так завершается Сердце Праджняпарамиты.</p>
        <p>Так изрёк Благословенный. Достопочтенный Субхути с радостью и внимательным умом принял
            [это слово Благословенного].</p>
        <p class="text-right italic">Перевёл с санскрита и составил примечания О.&nbsp;Л.&nbsp;Волошановский,
            Киев, январь 2026&nbsp;г.</p>
