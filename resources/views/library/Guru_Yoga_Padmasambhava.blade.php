        <p>Надо созерцать к тому же, что в центре межбровья Падмасамбхавы сияет белый
            <strong>ОМ</strong>, в Его гортани — красный <strong class="text-red-700">АХ</strong>,
            и в центре его сердца — синий <strong class="text-blue-700">ХУМ</strong>. Но эти
            биджи (слоги) нельзя
            представлять как бы лежащими поверх Его тела, их надо видеть неотъемлемо присущими,
            влитыми в Его радугоподобную фигуру. После того, как удалось достичь устойчивого
            указанного созерцания, начни читать мантру <em>(здесь не приводится)</em>, и по ходу её
            чтения <em>(или после прочтения)</em> надо представить, увидеть, как из белого ОМ в
            центре межбровья Падмасамбхавы излучается чистейший белый луч света, и падает в центр
            твоего межбровья. Этот свет уничтожает все твои телесные пороки и скверны, и несёт
            взамен все качества «тела» <em>(тиб. <em>sku</em>, санскр. <em>kaya</em>)</em>
            Падмасамбхавы.<a href="#citation-2" id="ref-2" class="citation-mark"><sup>2</sup></a></p>
        <p>Из центра Его речи, красный <strong class="text-red-700">АХ</strong> излучает красный
            луч света, и тот протягивается к твоему
            центру речи, и, проникнув, уничтожает все прегрешения речи, всё неверно сказанное, а
            взамен несёт качества речи Падмасамбхавы. Из Его сердечного центра хрустально-синий
            <strong class="text-blue-700">ХУМ</strong>
            излучает в центр твоего сердца синий луч света, который разрушает невежество (санскр.
            <em>moha</em>), всё содеянное по неведенью, всё придуманное по невежеству, а переносит
            взамен все качества разума Падмасамбхавы. Затем многоцветные лучи начинают истекать из
            каждой поры фигуры Падмасамбхавы и пронизывают соответствующие части твоего тела. Надо
            всецело почувствовать и узреть это потрясающее явление.</p>
        <p>Затем созерцание продолжается виденьем того, как облик Падмасамбхавы начинает
            стягиваться, пропорционально сжиматься со всех сторон, с боков, с головы и ног, пока
            полностью не преобразуется в <strong class="text-blue-700">ХУМ</strong> в сердечном
            центре. Вот, этот <strong class="text-blue-700">ХУМ</strong> начинает вибрировать,
            и — о чудо! — внезапной вспышкой «выстреливает» в твой сердечный центр, как падающая
            звезда! Воды двух сосудов слились воедино. Никакой двойственности. Полнейшее единство!
            <em>(В этом удивительном, неописуемом состоянии можно пребывать некоторое время,
                вероятно, минут двадцать, не больше.)</em></p>
        <p>Это созерцание надо выполнять, по меньшей мере, трижды на день. При любых
            обстоятельствах, даже если умираешь, надо трижды в день творить эту практику. Но если её
            вершить триста раз на день — и того лучше. Но ни в коем случае нельзя помышлять, что
            практикуешь ради собственного блага. Твори это только ради счастья всего живого,
            особенно ради родителей, бедняков, престарелых, больных и т.д. Внутренняя установка
            должна быть на раздачу этого неописуемого блаженства, а не на личное потребление, не
            ради своего удовольствия. С самого начала нужно глубоко усвоить, что занимаешься всем
            этим только ради других, и всё, что было тобой добыто, надо отдать другим, ибо то
            принадлежит им, а не тебе. Никогда нельзя «зажимать» добытое, пользоваться им
            эгоистично. Созерцая Падмасамбхаву, следует полностью себя контролировать. Никаких
            колебаний, сомнений, неуверенности! Когда эта медитация завершена, любая форма,
            попадающаяся тебе на глаза, будет телом Падмасамбхавы, любой звук, который ты услышишь,
            станет речением Падмасамбхавы, и все действия — движением ума Падмасамбхавы.<a
                href="#citation-3" id="ref-3" class="citation-mark"><sup>3</sup></a></p>
        <p class="text-sky-700 text-right italic">Из "Зелёного блокнота" О. Ф. Волковой</p>


