    <h1 class="text-center text-blue-900 font-bold text-2xl sm:text-2xl md:text-2xl mt-6 mb-6">
        Перенесение Тела, Речи и Ума Падмасамбхавы</h1>
    <div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
        <p>Сразу же после пробуждения, ранним утром, надо немедленно определить, где и на чём
                пребывает твоё осознание, а затем очиститься от застоялого воздуха.<a
                href="#citation-1" id="ref-1" class="citation-mark"><sup>1</sup></a></p>
        <p>Прежде надо принять удобную позу, но с выпрямленной спиной и без опоры на что-либо <em>(сиддхасана
                и т.п.)</em>. Затем, после медленного плавного вдоха через обе ноздри, надо закрыть
            левую ноздрю левым указательным пальцем и выдохнуть очень медленно через правую ноздрю.
            Это выполнить трижды. Затем, закрыть правую ноздрю правым указательным пальцем, и очень
            медленно выдохнуть через левую ноздрю. Итого в целом — шесть раз <em>(три раза через
                правую, три раза через левую)</em>. Затем выдохнуть ещё трижды, не закрывая ноздри,
            через ноздри, а затем ещё три выдоха, только через рот. Каждый выдох должен быть очень
            глубоким, т.е. надо постараться выдыхать из тела весь застоявшийся воздух, особенно из
            желудка.</p>
        <p>Выдыхая через правую ноздрю, надо вообразить, что из ноздри истекает тёмно-красный цвет.
            Этот цвет — символ страсти и привязанности. Выдыхая через левую ноздрю, надо вообразить,
            что из этой ноздри истекает тусклый серо-синий туман, это символ препятствий <em>(в
                основном умственных препон)</em> и гнева. Выдыхая через обе ноздри и рот, надо
            представить, что освобождаешься от пурпурно окрашенного тумана, который символизирует
            лень, заблуждение, сумбурность. Повторить по три раза через ноздри, и три раза через
            рот.</p>
        <p>Итак, ты очистился. Теперь начни созерцать Падмасамбхаву, созерцать
            физически, т.е. надо пристально, внимательно, вплоть до мельчайших деталей рассматривать
            скульптурное или рисованное изображение Падмасамбхавы. Плоскостное изображение не
            трёхмерно, но надо созерцать Учителя трёхмерным, однако, особым образом. Не следует
            думать, что Он точно таков же, как и ты, т.е. со всеми обычными анатомическими и
            физиологическими качествами и признаками. Он — как радуга, чист, блистателен, неуловимо
            тонок, ясен. Он всеведущ. Даже мельчайшая частица Его ведает всё. Будды прошлого,
            настоящего и будущего времени сияют из каждой поры Его кожи.</p>

        <p>Скульптуру и икону с образом Падмасамбхавы надо поместить перед собой на высоте в полтора
            локтя над уровнем головы. Представь, что Он взирает именно на тебя с несокрушимым
            милосердием. Он — лучезарен, Его кожа блистательна, лоснится небесным сиянием. Его можно
            созерцать восьмилетним или шестнадцатилетним юношей (лучше шестнадцатилетним). Он —
            воплощение всех Джнянендр (санскр. <em>jñānendra</em>, букв. «Владыка Знания»; тиб. <em>ye
                shes pa dbang po</em>). Он — вместилище Трикайя. Ты должен всецело отдаться Ему
            посредством всепронизывающего твоё существо благоговения. Но не надейся, что Он
            сниспошлёт тебе какие-то качества или вещи. Просто «сдайся» Ему. Если твоя вера и любовь
            к Падмасамбхаве искренни, то вскоре заметишь, что твои глаза увлажнились слезой
            благоговения. И ещё одно — это созерцание Падмасамбхавы есть, по сути, одновременно и
            созерцание твоего Гуру.</p>
