            <h4 class="text-center text-gray-800 font-bold text-xl my-4">ПРИМЕЧАНИЯ</h4>
            <p></p>
            <p class="my-2" id="citation-1"><sup>1</sup> <strong>Санскритский оригинал</strong><br>
                <strong>Деванагари:</strong><br>
                ॐ नमो भगवत्यै आर्यप्रज्ञापारमितायै ॥<br>
                एवं मया श्रुतम् ।<br>
                एकं समयं भगवान् श्रावस्त्यां विहरति स्म जेतवनेऽनाथपिण्डदस्यारामे महता भिक्षुसङ्घेन सार्धमर्धत्रयोदशभिः भिक्षुशतैः सार्धं पञ्चाशता बोधिसत्त्वैर्महासत्त्वैः ।<br>
                अथ खलु भगवान् आयुष्मता सुभूतिना सहं सर्वधर्माणामक्षरमातृकत्वं देशयति स्म ।<br>
                यदुत — सर्वधर्मा अक्षराः ।<br>
                कस्य हेतोः? अनुत्पन्नत्वात्सर्वधर्माणाम् ।<br>
                तस्मात्सुभूते अक्षरं नाम प्रज्ञापारमिता ।<br>
                सर्वधर्मा अनुत्पन्ना अनिरुद्धाः । शान्ता अद्वया अनात्मानः ।<br>
                तस्मात्सुभूते बोधिसत्त्वो महासत्त्वोऽप्रमत्तः प्रज्ञापारमितां भावयितव्यः ।<br>
                भगवतो भाषितमिदमभ्यनन्ददायुष्मान्सुभूतिः प्रीतिर्मनसिकारश्च ॥<br><br>
                <strong>Транслитерация:</strong><br>
                oṃ namo bhagavatyai ārya-prajñāpāramitāyai ||<br>
                evaṃ mayā śrutam |<br>
                ekaṃ samayaṃ bhagavān śrāvastyāṃ viharati sma jetavane 'nāthapiṇḍadasyārāme mahatā bhikṣu-saṃghena sārdham ardhatrayodaśabhiḥ bhikṣu-śataiḥ sārdhaṃ pañcāśatā bodhisattvair mahāsattvaiḥ |<br>
                atha khalu bhagavān āyuṣmatā subhūtinā sahaṃ sarva-dharmāṇām akṣara-mātṛkatvaṃ deśayati sma |<br>
                yad uta — sarva-dharmā akṣarāḥ |<br>
                kasya hetoḥ? anutpannatvāt sarva-dharmāṇām |<br>
                tasmād subhūte akṣaraṃ nāma prajñāpāramitā |<br>
                sarva-dharmā anutpannā aniruddhāḥ | śāntā advayā anātmānaḥ |<br>
                tasmād subhūte bodhisattvo mahāsattvo 'pramattaḥ prajñāpāramitāṃ bhāvayitavyaḥ |<br>
                bhagavato bhāṣitam idam abhyanandad āyuṣmān subhūtiḥ prītir manasikāraś ca ||<br>
                Эта сутра известна как <em>Akṣara Prajñāpāramitā</em> или
                <em>Akṣara-mātṛkā Prajñāpāramitā</em> — «Сутра Праджняпарамиты о [Букве] А» или
                «Сутра Праджняпарамиты о Матери Слогов». Она принадлежит к краткому корпусу текстов
                Праджняпарамиты, наряду с <em>Ekākṣarī Prajñāpāramitā</em> (Сутрой Одной Буквы)
                и <em>Prajñāpāramitā Hṛdaya</em> (Сутрой Сердца). Эта сутра и
                <em>Ekākṣarī Prajñāpāramitā</em> построены по общему «шаблону», где различие лишь в
                центральной части.<a href="#ref-1" class="text-blue-500 hover:underline">↩</a></p>
