        <p class="text-center text-xl font-semibold text-gray-800 mt-6">Ом! Поклонение Благословенной Арья-Праджняпарамите!</p>
        <p>Так я слышал. Однажды Благословенный пребывал в Шравасти, в саду Джеты, в монастыре Анатхапиндики, вместе с великим собранием монахов — тысячей тремястами пятьюдесятью бхикшу — и вместе с пятьюдесятью бодхисаттвами-махасаттвами.<a href="#citation-2" id="ref-2" class="citation-mark"><sup>2</sup></a></p>
        <p>И тогда Благословенный, обращаясь к достопочтенному Субхути, изложил учение о том, что все дхармы [рождены из] матери слогов. А именно —</p>
        <blockquote class="border-l-4 border-amber-500 pl-6 my-6 text-gray-800 text-xl">
            «Все дхармы — неразрушимы (акшара).<a href="#citation-3" id="ref-3" class="citation-mark"><sup>3</sup></a> Почему? Потому что все дхармы не созданы. Потому, о Субхути, "А" есть Праджняпарамита.<br><br>
            Все дхармы — не созданы и неразрушимы; они успокоены, недвойственны, лишены «я». Потому, о Субхути, бодхисаттве-махасаттве следует неотступно взращивать Праджняпарамиту».
        </blockquote>
        <p>Так изрёк Благословенный. Достопочтенный Субхути с радостью и внимательным умом принял [это слово Благословенного].</p>
