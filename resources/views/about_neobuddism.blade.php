    <h1 class="text-center text-blue-900 font-bold text-2xl sm:text-2xl md:text-2xl mt-6 mb-6">О
        НЕОБУДДИЗМЕ Б. Д. ДАНДАРОНА</h1>
    <div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
        <p class="text-right italic text-gray-800 my-4">М. Ф. Альбедиль</p>

        <p>15 декабря 2014 г. исполнилось 100 лет со дня рождения Бидии Дандаровича Дандарона.
            Следует отметить, что это официально признанная дата, ее называл и сам
            Б.&nbsp;Д.&nbsp;Дандарон. Но его родственники ее не принимают и считают, что он родился
            25 ноября 1913 г. Есть и другие свидетельства, ставящие под сомнение дату 15 декабря
            2014 г., но это не суть важно. Важен масштаб личности Б.&nbsp;Д.&nbsp;Дандарона: он был
            не только серьезным ученым-буддологом, философом, но и мастером буддийской тантры,
            йогином, духовным учителем и проповедником, много сделавшим для продвижения буддизма на
            Запад в советское время.</p>
        <p>В Бурятии его считают перерожденцем Джа-яг Ринпоче XIII Галсана Цултима Данбий Нима,
            хамбо-ламы монастыря Гумбум Джамбалин, основанного на месте рождения Цзонхавы (в Бурятии
            его называют Джаягсан-гэгэн). По местным легендам и преданиям, в конце XIX в. некоторые
            тибетские перерожденцы связывали дальнейшее развитие буддизма с Бурятией и Россией, и
            Джа-яг Ринпоче был в их числе. Когда он в начале XX в. приезжал в Бурятию, буддисты
            Кижинги попросили, чтобы следующая его инкарнация появилась у них, и он согласился. Так
            появился на свет Бидия Дандарон.</p>
        <p>На его долю выпала трагическая судьба, полная лишений и испытаний. О ней необходимо
            написать несколько слов, потому что она, может быть, не всем известна, но главным
            образом потому, что учение Б.&nbsp;Д.&nbsp;Дандарона и его жизнь неразрывно связаны. Он
            всегда стремился придать своей жизни достоинство этического аргумента и воплотить в
            жизнь тот буддийский идеал истинного сострадания ко всему живому, который теоретически
            обосновывал.</p>
        <p>Б.&nbsp;Д.&nbsp;Дандарон жил в советскую эпоху воинствующего атеизма, когда вера сурово
            преследовалась. В 1937 г. его, 23-летнего студента, арестовали. В то время он учился в
            Ленинграде, в институте авиационного приборостроения (ЛИАП), и был вольнослушателем
            Восточного факультета Ленинградского государственного университета им.
            А.&nbsp;А.&nbsp;Жданова (ныне СПбГУ), где изучал тибетский язык. Через полтора года
            следствия его осудили по статьям 58-10 и 58-11 УК РСФСР как панмонголиста, ведущего
            активную работу по созданию контрреволюционной националистической группы, и приговорили
            к расстрелу. Но потом смертную казнь заменили тюремным заключением сроком на 10 лет.
            Здесь он в полной мере узнал, что такое пересылки, голод, стужа и жестокие пытки, после
            которых он чудом остался жив.</p>
        <p>В 1943 г. Б.&nbsp;Д.&nbsp;Дандарона выпустили из лагеря по болезни: у него обнаружилась
            открытая форма туберкулеза. Но в 1948 г. его снова арестовали за антисоветскую агитацию
            и приговорили к десяти годам заключения в исправительно-трудовых лагерях. В августе 1956
            г. он вышел на волю. Дело прекратили за отсутствием состава преступления и его
            полностью реабилитировали.</p>
        <p>Советская каторга, при всех ее тяготах, имела некоторые положительные стороны. Среди
            заключенных оказалось много творческих, образованных людей, сложился даже неокантианский
            кружок. Лагерным наставником Б.&nbsp;Д.&nbsp;Дандарона стал Василий Эмильевич Сеземан
            (1884—1963), неокантианец марбургского направления, профессор Каунасского и Вильнюсского
            университетов. Известно, что тюремные и лагерные библиотеки, составленные из книг
            репрессированной интеллигенции, были тогда лучшими в СССР. В лагерях отбывали срок
            наказания и ламы, поэтому Б.&nbsp;Д.&nbsp;Дандарон смог продолжить там и свое буддийское
            образование. Вспоминая эти годы, он называл их своими университетами. В лагерях он много
            читал и усердно практиковал тантрийское созерцание, умудряясь заниматься этим по ночам,
            после тяжелой работы на лесоповале [Пупышев, 1995: 9—10]. Позже
            Б.&nbsp;Д.&nbsp;Дандарон не раз вспоминал, что созерцание лучше совершать в лагерях,
            чем на свободе: процесс идет интенсивнее.</p>
        <p>После второго освобождения в 1956 г. Б.&nbsp;Д.&nbsp;Дандарону было отпущено всего 16
            лет жизни вне тюрем, ссылок и лагерей. Он сравнительно недолго находился на свободе.
            В 1972 г. его снова арестовали, обвинили по статьям 147 и 227 УК РСФСР в мошенничестве
            и в создании тайной буддийской секты, деятельность которой под видом проповедования
            вероучения была сопряжена с посягательством на личность граждан, и приговорили к 5 годам
            исправительно-трудовых лагерей. Суд был похож на заранее срежиссированный спектакль,
            которому Бурятская прокуратура вознамерилась придать всесоюзный масштаб [Семека, 1974:
            6—7]. В 1974 г. Б.&nbsp;Д.&nbsp;Дандарон умер.</p>
        <p>Поразительно, как много он успел сделать за время на свободе и как ученый, и как духовный
            наставник, несмотря на то что его судьба и в этот период складывалась совсем не просто.
            Естественно, после сталинских лагерей ему было трудно найти работу в Москве или
            Ленинграде по специальности востоковеда. После безуспешных попыток устроиться в Институт
            востоковедения АН СССР, предпринимавшихся им с осени 1956 г. по май 1957 г., он вернулся
            в Бурятию. Здесь до 1966 г. он работал младшим научным сотрудником в Бурятском
            комплексном научно-исследовательском институте Сибирского отделения АН СССР, а потом в
            Бурятском институте общественных наук Сибирского отделения АН СССР (с 1997 г. Институт
            монголоведения, буддологии и тибетологии СО РАН). За это время он проделал огромную
            научную работу: исследовал фонд тибетских и монгольских рукописей и ксилографов, которые
            хранились в Рукописном отделе института, одном из богатейших не только в России, но и в
            мире. Он много переводил с тибетского и монгольского языков на русский, написал ряд
            статей и монографий [Пупышев, 1995: 10]. В общей сложности он опубликовал более 20
            работ, осталось еще много неизданного. Достаточно назвать выполненное им фундаментальное
            описание монгольского Ганджура, в 108 томах, которое составляет около 40 авторских
            листов [Дандарон, 2006: 558—560].</p>
        <p>В своей научной работе Б.&nbsp;Д.&nbsp;Дандарон обращался к широкому кругу тем, связанных
            с буддизмом: от истории буддийских дацанов до сложных вопросов буддийской эзотерики.</p>
        <p>Одной из сквозных тем его непрерывных исследований был необуддизм. Еще в сталинских
            лагерях он написал работу, где в общих чертах развивал идеи необуддизма; она так и
            называлась «Необуддизм». Эту рукопись вывез из зоны пленный поляк Кокошка, устроив себе
            ложный перелом руки и спрятав листы рукописи под гипсом. Идеи необуддизма
            Б.&nbsp;Д.&nbsp;Дандарон вынашивал и позже, выйдя на свободу. В наиболее полном и
            систематизированном виде они были впервые отражены в письмах, которые он писал в
            1956—1959 гг. Наталье Юрьевне Ковригиной, приемной дочери Сеземана. Их связывало
            сильное чувство, превышающее плотскую любовь. По признанию
            Н.&nbsp;Ю.&nbsp;Климанскене-Ковригиной, она стала первой ученицей
            Б.&nbsp;Д.&nbsp;Дандарона, когда он вышел на свободу [Дандарон, 1995: 328].</p>
        <p>К счастью, эти письма сохранились и были изданы в 1995 г. усилиями ученика
            Б.&nbsp;Д.&nbsp;Дандарона В.&nbsp;М.&nbsp;Монтлевича [Дандарон, 1995]. В них
            Б.&nbsp;Д.&nbsp;Дандарон определил свое видение буддизма в современной жизни и наметил
            пути синтеза с идеями западной философии и современной науки. В одном из писем он писал:
        </p>

        <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
            Если пойдет удачно, то можно будет излагать свои мысли более-менее систематически,
            чтобы впоследствии из этих писем вычленить схему будущей философской системы. Эту
            систему я мыслю как попытку синтеза западной и восточной мудрости [Дандарон, 1995: 64].
        </blockquote>

        <p>Стремление Б.&nbsp;Д.&nbsp;Дандарона создать подобную философскую систему находилось в
            русле философских и духовных исканий того времени. Проблема «Восток—Запад» была
            актуальной для России по меньшей мере с XVI в., когда она начала объединять в своих
            государственных границах некоторые регионы Востока. Различные варианты решения этой
            проблемы являлись, по сути, необходимым средством исторической и культурной
            идентификации [Колесников, 2004: 186]. Аналогичными поисками схождений и пересечений
            буддийской и европейской философии была озабочена и отечественная буддология конца
            XIX—начала XX в., стремившаяся рассматривать буддийскую философию в контексте мировой
            философии.</p>
        <p>Внимательно изучив западную философию, Б.&nbsp;Д.&nbsp;Дандарон обратил внимание на ее
            ограниченность в определенных вопросах. Так, рассуждая о мистических элементах в
            европейской философии, так или иначе дополнявших рациональную сторону познания,
            Б.&nbsp;Д.&nbsp;Дандарон подчеркивал, что западные философы доходили только до порога,
            т. е. до исследования рациональной интуиции. «За порог могут переступить только те,
            которые сделают синтез европейской и индийской философии», — утверждал он
            [Дандарон, 1995: 65]. Эта мысль о соединении духовных накоплений Востока и Запада,
            ставшая лейтмотивом его исканий, и отразилась в термине «необуддизм». Именно этим
            термином он назвал создаваемую им научную систему, которую в тюремных условиях
            приходилось по большей части держать в голове. При этом он отметил, что «основатели
            теории (системы) необуддизма вынуждены строить свою метафизическую систему, которая
            может объяснить происхождение мира и совершенство атмана, не впадая в противоречие с
            современной наукой» [Там же: 81].</p>
        <p>Одним из источников его учения была непоколебимая убежденность в единстве человеческого
            разума и мировой философии. Он писал в одном из писем
            Н.&nbsp;Ю.&nbsp;Ковригиной-Климантене:</p>

        <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
            Я пишу тебе о христианской мистике, чтобы сравнить ее с буддийской, ибо на разных
            концах земли в разную эпоху человеческая мысль, направленная к одной цели, приводит в
            конечном итоге к одному и тому же выводу, чем подтверждается истинность положения вещей
            [Дандарон, 1995: 54].
        </blockquote>

        <p>В письмах Дандарон представил и план, по которому намеревался строить систему
            необуддизма. Он выделил следующие смысловые блоки и структуру системы: 1) индивидуальное
            Я; 2) психология; 3) учение о зависимом происхождении; 4) этика; 5) карма и новое
            рождение; 6) еще раз о нирване; 7) отношение к Богу; 8) практическая религия; 9) теория
            познания; 10) пути совершенствования [Дандарон, 1995: 18]. Для того чтобы стать подлинно
            научной, «философия должна вступить в связь с другими науками, и иными способами (мы
            полагаем) она не может быть построена. Современные люди, воспитанные на точных науках,
            не могут допустить возможности априорного построения метафизики, но также не могут
            допустить и построения ее при помощи только экспериментальной науки» [Там же: 99].
            Б.&nbsp;Д.&nbsp;Дандарон был убежден, что разработанная им система необуддизма сможет
            выдержать испытание в том случае, если будет способна аргументированно объяснить все
            явления феноменального и духовного.</p>
        <p>Практически все темы, намеченные им как основополагающие для указанных выше смысловых
            блоков необуддизма, Б.&nbsp;Д.&nbsp;Дандарон тщательно разрабатывал в те недолгие годы,
            когда он находился на свободе; они отражены в большей части его публикаций. Он продолжал
            работать над ними и во время своего последнего заключения в 1972—1974 гг.; результатом
            этой работы стала «Черная тетрадь» [Дандарон, 2006: 139—248]. В итоге была разработана,
            как представляется, фундаментальная и претендующая на универсализм система необуддизма,
            синтезировавшая буддийские духовные искания с положениями современной науки.</p>
        <p>В центре творчества Дандарона как необуддиста всегда находились самые насущные проблемы
            духовного развития, а именно: проблема мистического постижения сущности Бытия,
            восприятия Божественного, сочетания мистически-интуитивного акта (в том числе и путем
            религиозного опыта, практики медитаций) вхождения в мир «сверхфеноменального» и
            рационального метода «развертывания» содержания действительности, обусловленной этой
            трансцендентной сущностью.</p>
        <p>Одной из важнейших частей системы необуддизма является метафизика. Обращая внимание на
            непреодолимую тягу человечества к построению метафизики, Дандарон старается методически
            выстроить новую метафизику. Ее изложение в указанных письмах он начинает с понятия о
            боге:</p>

        <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
            Все философские системы с древнейших времен до наших дней пытаются объяснить, что
            представляет собой мир как целое; есть ли он что-либо случайное, нечто бессмысленное,
            вроде вещи, существование которой не имеет никакого смысла, или он живет, развивается и
            направляется к заранее намеченной цели. Мы видели, что мир представляет собой единое
            целое, систему, и поэтому можно предположить, что он в своем развитии стремится к
            определенной цели, поставляемой Разумной Волей… Перед нами стоит вопрос: существует ли
            нечто, дающее направление миру, жизни вселенной, каковы его свойства и т. п. Существует
            ли божество и какими свойствами оно обладает? [Дандарон, 1995: 81].
        </blockquote>

        <p>Он перечисляет доказательства бытия бога в докантовской метафизике, подробно анализирует
            аргументы Канта; показывая глубокое знание его произведений и отмечая созвучность его
            идей с буддийскими, Б.&nbsp;Д.&nbsp;Дандарон приходит к выводу, что доказать бытие бога
            посредством разумного анализа или дискурсивным способом невозможно, потому что причина,
            имеющая абсолютный характер, не может нами мыслиться.</p>
        <p>Б.&nbsp;Д.&nbsp;Дандарон утверждает, что для разрешения этого вопроса «буддисты
            рассматривают происхождение идеи бога с точки зрения психологической. А именно: каким
            образом возникает идея бога в нашем сознании, так ли, как идея о вещах вообще, или иным
            способом? Они считают, что мистическое восприятие божества и способ его познания имеют
            особый характер, отличный от познания других вещей. По этой теории мы познаем бога,
            потому что он оказывает постоянное воздействие на наш дух» [Дандарон, 1995: 84—85]. Не
            постижимый рассудком, бог постигается при помощи внутреннего чувства, интуиции.</p>
        <p>Учение об интуиции, дополняющей сугубо рассудочное знание, затронутое в письмах,
            Б.&nbsp;Д.&nbsp;Дандарон развивал и позже. По его мнению, человек обладает особым
            органом непосредственного знания, интуиции, который помогает мысли выйти из чисто
            рассудочного мира, познать нечто сверхрассудочное и постичь сущность бытия
            непосредственно, глубоко и истинно. Он был убежден, что показания этого органа столь же
            достоверны, как доводы рассудка, но эта достоверность иного порядка. Позже, в своей
            работе «Мысли буддиста», законченной в 1970 г., он выделил три типа интуиции:
            рациональную, эмоционально-эстетическую и эмоционально-мистическую
            [Дандарон, 1997: 32—45]. По мнению Б.&nbsp;Д.&nbsp;Дандарона, систематизированная и
            детально разработанная философия может быть построена только на интуиции
            трансцендентной действительности.</p>
        <p>Говоря о познании бога, Б.&nbsp;Д.&nbsp;Дандарон сравнивает христианскую мистику, в
            частности Фому Кемпийского<a href="#citation-1" id="ref-1"><sup>1</sup></a> и
            Экхарта<a href="#citation-2" id="ref-2"><sup>2</sup></a>, с буддийским тантризмом. По
            его мнению, в христианстве мистика не получила в полной мере должного практического
            применения, как это произошло в буддизме. В решении задач мистического постижения мира и
            поиска методов совершенствования на пути к нирване он опирается на буддийские идеи,
            актуализируя концепцию шуньяты мадхъямаков и способы совершенствования школы
            йогачаров<a href="#citation-3" id="ref-3"><sup>3</sup></a>.</p>
        <p>Согласно необуддизму Б.&nbsp;Д.&nbsp;Дандарона, сансару с ее муками создает не сам
            абсолют, а при движении из потенции в действие он раздваивается на совершенную нирвану
            и несовершенный атман. Последний, двигаясь к нирване посредством разумной воли,
            проявляет бессознательную волю к жизни и тем самым создает сансару, где происходит
            постоянное движение, рождение, развитие и смерть, которые противостоят абсолютному
            покою нирваны. «Содержание сансары и нирваны прямо противоположно»
            [Дандарон, 1997: 102]. Подлинной реальностью является небытие, или бесконечная нирвана,
            лежащая за пределами чувственного мира, вне пределов пространства и времени. В ней нет
            тех форм, свойств и качеств, которые присущи материальному миру.</p>
        <p>Рассуждая о метафизической действительности души, Б.&nbsp;Д.&nbsp;Дандарон различает
            трансцендентное Я, сущность которого скрыта от нашего разума, и феноменальное, или
            эмпирическое Я, состоящее из составных частей-скандх. Он определяет его как
            несовершенство, или авидью, атмана; авидья же представляет собой оскверняющий характер
            неведения. Трансцендентное Я он сравнивает со светлой стороной атмана, а эмпирическое Я
            — с темной. Сансару в этом случае Б.&nbsp;Д.&nbsp;Дандарон уподобляет лаборатории, в
            которой ведется целеустремленная работа по очищению атмана от его несовершенства, полнее
            всего выраженного в неведении-авидье [Дандарон, 1997: 131—132].</p>
        <p>Корень возникновения индивидуального Я таится в неведении. Именно от него происходят все
            основные черты эго.</p>

        <blockquote class="border-l-4 border-sky-500 pl-6 my-6 text-gray-800 text-xl">
            Из неведения возникают санскары (очертания), из санскар возникает сознание, из сознания
            — имя и форма, из имени и формы возникают шесть областей (области шести органов чувств),
            из шести областей возникает соприкосновение, из соприкосновения возникает ощущение, из
            ощущения возникает жажда (или желание), из жажды возникает привязанность, из
            привязанности возникает становление, из становления возникает рождение и т. д.
            [Дандарон, 1997: 165].
        </blockquote>

        <p>Одной из особенностей метода изложения Б.&nbsp;Д.&nbsp;Дандароном тех или иных положений
            необуддизма является широкое привлечение им идей западноевропейских философов и ученых.
            Он обращается не только к И.&nbsp;Канту (1724—1804), А.&nbsp;Шопенгауэру (1788—1860),
            Н.&nbsp;Гартману (1882—1950), М.&nbsp;Хайдеггеру (1976—1889), но и к античным работам,
            к трудам христианских мистиков, а также к творчеству известного русского религиозного
            философа В.&nbsp;С.&nbsp;Соловьева (1853—1900). Определяя метафизические основания новой
            концепции, характеризуя сансару, он находит немало общих черт между их воззрениями и
            буддизмом. Но в некоторых случаях он привлекает идеи западных философов, чтобы
            продемонстрировать их недостаточность в решении фундаментальных проблем бытия и его
            познания. Б.&nbsp;Д.&nbsp;Дандарон обращается и к данным других современных наук, в
            частности физики и химии, чтобы сделать буддийские идеи более понятными для
            современного русского читателя.</p>
        <p>Именно так — сравнивая, находя общее и различное в европейской и буддийской философии,
            обращаясь к результатам современной науки, — Б.&nbsp;Д.&nbsp;Дандарон создает
            собственную философскую концепцию необуддизма. Кроме того, он стремится объединить
            религиозно-философские идеи в их разных историко-культурных формах и проявлениях с
            возможностями современной научной философии. По его мнению, только так можно создать
            принципиально новую систему, которая соединит в себе достоинства западной и восточной
            философии, не будет противоречить достижениям современной научной и в то же время будет
            иметь не только теоретическое, но и жизненно-практическое значение.</p>
        <p>Бесспорно, необуддизм Б.&nbsp;Д.&nbsp;Дандарона еще нуждается в глубоком религиоведческом
            и философском изучении, причем интересны как сама система, так и способ ее изложения.
            Первые шаги в этом направлении уже сделаны [Дандарон, 2007; Бернюкевич, 2009:
            139—150].</p>
        <p>Жизненность и практичность своей системы необуддизма Б.&nbsp;Д.&nbsp;Дандарон доказал
            своей жизнью, которая, как было сказано выше, стала главным аргументом его философии.</p>
        <p>Здесь необходимо подчеркнуть, что он чрезвычайно много сделал для продвижения буддизма на
            Запад в атеистический советский период. С 1965 г. к нему в Улан-Удэ начинают приезжать
            ученики из Москвы, Санкт-Петербурга (тогда Ленинграда), Прибалтики. К 1972 г. вокруг
            него уже сложилась группа из европейских и бурятских учеников, что и послужило поводом
            для его ареста в 1972 г. Б.&nbsp;Д.&nbsp;Дандарон отличался от популярных ныне на Западе
            «разъезжающих» учителей буддизма, которые дают посвящения толпам желающих. Он очень
            хорошо знал всех своих учеников и находился с ними в постоянном контакте, следя за их
            духовным совершенствованием. Важную роль играло и то, что он, живя в Бурятии, прекрасно
            знал язык и реалии тогдашней советской жизни, умел объяснить доступным языком сложнейшие
            положения буддийской философии и религии. Это помогало ему находить прямой путь к
            сердцам людей. Что касается его учеников из европейской части России и некоторых других
            стран бывшего Советского Союза, то, разумеется, для них чрезвычайно притягательной
            всегда оставалась сильная личность Б.&nbsp;Д.&nbsp;Дандарона и та попытка синтеза
            духовных знаний с наукой, которую он пытался осуществить в своей системе необуддизма.</p>
        <p>Таким образом, Бидия Дандарович Дандарон стоял у истоков необуддизма как современной
            версии прочтения древнейшей мировой религии и развивал духовную традицию передачи учения
            буддизма на Запад.</p>

