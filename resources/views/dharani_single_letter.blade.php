            <p class="my-2" id="citation-2"><sup>2</sup> <strong>ОМ</strong> — священный слог,
                символизирующий изначальное единство Тела, Речи и Ума всех Будд (Трикая). Он
                открывает мантру, настраивая сознание на восприятие недвойственной реальности.<br>
                <strong>А</strong> (āḥ) — в контексте Праджняпарамиты это «Единая Буква», корень
