    <h4 class="text-center text-gray-800 font-bold text-xl my-4">ПРИМЕЧАНИЯ</h4>
    <hr class="my-8 border-t-4 border-gray-500">
    <p class="my-2" id="citation-492"><sup>492</sup> Девятая глава — единственная в <strong><em>Ланкаватаре</em></strong>, целиком посвящённая дхарани. <em>Dhāraṇī</em> — буквально «то, что удерживает» — особые формулы, сочетающие в себе функции мантры, памятования и защиты. В отличие от философских глав, эта глава носит литургический характер и, по всей видимости, также является более поздним добавлением к тексту. Упоминание «проповедников Дхармы» (<em>dharmabhāṇaka</em>) указывает на конкретную ситуацию: странствующие чтецы и распространители сутр нуждались в защитных формулах для своей деятельности.<a href="#ref-492" class="text-blue-500 hover:underline ml-2">↩</a></p>
    <p class="my-2" id="citation-493"><sup>493</sup> Большинство слогов дхарани — фонетические. Но несколько элементов поддаются расшифровке:</p>
    <p class="my-2 ml-4"><em>Amale vimale</em> — «незапятнанная, чистейшая» — стандартная формула чистоты, встречающаяся во многих буддийских дхарани.</p>
    <p class="my-2 ml-4"><em>Bandhe</em> — от корня <strong>√bandh</strong>, «связывать» — призыв к сковыванию вредоносных сил.</p>
    <p class="my-2 ml-4"><em>Cale</em> — от <strong>√cal</strong>, «двигаться» — возможно, призыв к пробуждению защитной силы.</p>
    <p class="my-2 ml-4"><em>Cakre</em> — «колесо» — символ Дхармы и силы.</p>
    <p class="my-2 ml-4"><em>Svāhā</em> — стандартное завершение мантр, восходящее к ведийской жертвенной формуле.</p>
    <p class="my-2">Завершающие серии <em>ṭu ṭu ṭu ṭu, ḍu ḍu ḍu ḍu, ru ru ru ru, phu phu phu phu</em> — типичный приём звукового нагнетания в защитных формулах: нарастающий грохот и рокот, призванные устрашить и обратить в бегство вредоносные существа.</p>
    <p class="my-2">Остальные слоги — <em>tuṭṭe vuṭṭe paṭṭe kaṭṭe, aṭṭe maṭṭe vaṭṭe, dime hime vame</em> и прочие — по всей видимости, либо намеренно фонетические, либо искажённые формы слов в результате многовековой передачи через несколько языков и письменных традиций.<a href="#ref-493" class="text-blue-500 hover:underline ml-2">↩</a></p>
    <p class="my-2" id="citation-494"><sup>494</sup> Перечислены существа, населяющие космологию индийского буддизма. Часть из них принадлежит к «восьми классам» (<em>aṣṭasenā</em>) — группам сверхъестественных существ, традиционно связанных с буддийским учением: боги (<em>deva</em>), наги — змееподобные существа, хранители вод и подземных сокровищ; якши — духи природы, способные как вредить, так и защищать; асуры — могущественные существа, враждующие с богами; гаруды — мифические орлы, извечные противники нагов; киннары — полулюди-полуптицы, небесные музыканты; махораги — великие змееподобные существа; гандхарвы — небесные музыканты и ароматные духи.</p>
    <p class="my-2">Остальные принадлежат к низшим категориям вредоносных существ: бхуты — духи умерших, блуждающие в мире живых; кумбханды — демоны, высасывающие жизненные силы; пишачи — демоны болезней и безумия; апасмары — существа, вызывающие эпилепсию и потерю сознания (<em>apasmāra</em> — буквально «утрата памяти»); ракшасы — людоеды-демоны; даки и дакини — в данном контексте вредоносные существа, питающиеся плотью и кровью; оджохары — буквально «похитители жизненной силы» (<em>ojas</em>); катапутаны — разновидность нечистых духов, связанных с разложением.</p>
    <p class="my-2"><em>Ostāraka/austārakī</em> — существа неясной этимологии, возможно связанные с определённым классом местных духов, не получивших широкого распространения в канонической литературе.</p>
    <p class="my-2">Во втором списке существ санскрит заменяет завершающее <em>amanuṣyo vā amanuṣyī vā</em> («нечеловеческое существо») на <em>manuṣyo vā manuṣyī vā</em> («мужчина и женщина»), распространяя защиту дхарани также и на угрозы со стороны людей.<a href="#ref-494" class="text-blue-500 hover:underline ml-2">↩</a></p>
    <p class="my-2" id="citation-495"><sup>495</sup> Большинство слогов и в этой дхарани — скорее всего фонетические, не несущие прямого смыслового содержания. Это характерно для дхарани вообще: их сила считается звуковой, а не семантической. Тем не менее несколько элементов поддаются расшифровке:</p>
    <p class="my-2 ml-4"><em>Padme</em> — «в лотосе» — один из наиболее известных буддийских символов, указывающий на чистоту, пробуждение, Авалокитешвару.</p>
    <p class="my-2 ml-4"><em>Padmadeva</em> — «лотосовое божество» или «бог лотоса».</p>
    <p class="my-2 ml-4"><em>Dinakara</em> — буквально «творец дня», то есть солнце — один из эпитетов солнечного божества в индийской традиции. Его появление в конце перед <em>svāhā</em> характерно: завершающий призыв к светоносному началу.</p>
    <p class="my-2 ml-4"><em>Muñce</em> — от корня <strong>√muc</strong> — «освобождать, отпускать». Трёхкратное повторение усиливает призыв к освобождению.</p>
    <p class="my-2 ml-4"><em>Chinde bhinde bhañje marde pramarde</em> — глагольные формы повелительного наклонения: «разруби, разбей, сломи, сотри, уничтожь» — стандартная формула разрушения препятствий и вредоносных сил, типичная для защитных дхарани.</p>
    <p class="my-2">Остальные слоги — <em>hine hini, cule culu, ghule ghula</em> и прочие — вероятно, звуковые имитации или искажённые формы утраченных слов, либо намеренно бессмысленные звукосочетания, сила которых заключается в вибрации, а не в значении.<a href="#ref-495" class="text-blue-500 hover:underline ml-2">↩</a></p>
