        <p>В Акаништхе, где нет ни центра, ни окоема, Татхагата, Самьяксамбудда, Бхагаван, Махабхога, Владыка Ваджров Тела, Речи и Мысли всех Татхагат десяти направлений и четырех времен, тот, кто есть <em>Всё-Всегда-Здесь</em>, так раскрывает Тантру:<a href="#citation-1" id="ref-1" class="citation-mark"><sup>1</sup></a></p>
        <p>На ясной Чакре Мудростей, всемерном основании, покоится светозарное Мироздание – воплощение Мудростей. Мироздание беспредельно, но предстает квадратным в знак полнейшего развития его неизмеримых качеств. Каждая стена – воплощение определенной Мудрости, украшена драгоценной кладкой остальных Мудростей. Единосущная всему Мудрость, общая всем мандалам Будд десяти направлений и четырех времен, представлена куполом Мироздания. Невообразимые Мудрости отображаются в различных воплощениях, обретая отличия и особенности по форме, цвету и т.п., все превосходящие и нет им предела.</p>
        <p>Разнообразие воплощенности Мудростей – ажурные занавеси, связующие подвески, гирлянды ожерелий – симфония форм, звуков, запахов, вкусов и ощущений – возникает самопроизвольно, ошеломляя размахом, и все предметы ясного убранства, не затмевая друг друга, непостижимым образом содержатся в Мироздании.<a href="#citation-2" id="ref-2" class="citation-mark"><sup>2</sup></a></p>
        <p> Входы в Мироздание – Четверо Врат Свободы;<a href="#citation-3" id="ref-3" class="citation-mark"><sup>3</sup></a> порталы Мироздания – Восемь Врат Освобождения.<a href="#citation-4" id="ref-4" class="citation-mark"><sup>4</sup></a></p>
        <p>Не имея нигде ни внешнего, ни внутреннего, но все же внутри – трон льва бесстрашия, трон слона силы, трон коня риддх, трон павлина могущества, трон птицы Шан Шан беспрепятственности. На тронах – сидения из чинтамани, лотоса неоскверненности, солнца, луны и естественного ясного света.</p>
        <p>На центральном троне – Татхагата-Учитель в Теле, для которого нет «спереди» и «сзади». Лик Его ясен и сияет повсюду. Он наделен знаками и признаками Будды. Во всех неохватных мыслью мирах разнообразно проявляющий Тело, Речь и Мысль, Он восседает с равно скрещенными ногами метода и интуиции. Руки шести Мудростей держат пылающие символы Их воплощения. Три головы – непостижимые Тело, Речь и Мысль.<a href="#citation-5" id="ref-5" class="citation-mark"><sup>5</sup></a></p>
