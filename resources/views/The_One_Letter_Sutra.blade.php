<h1 class="text-center text-blue-900 font-bold text-2xl sm:text-2xl md:text-2xl mt-6 mb-6">Сутра Одной Буквы</h1>
<div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
    <h5 class="text-center text-gray-700 italic">На санскрите: Ekākṣarī Prajñāpāramitā<a
            href="#citation-1" id="ref-1" class="citation-mark"><sup>1</sup></a></h5>
    <p class="text-center text-xl font-semibold text-gray-800 mt-6"><strong>OM</strong>!<a
            href="#citation-2" id="ref-2" class="citation-mark"><sup>2</sup></a>
        Поклонение Благословенной Арья-Праджняпарамите!<a href="#citation-3" id="ref-3"
                                                          class="citation-mark"><sup>3</sup></a></p>
    <p>Так я слышал.<a href="#citation-4" id="ref-4" class="citation-mark"><sup>4</sup></a> Однажды
        Благословенный пребывал в Шравасти,<a href="#citation-5" id="ref-5"
                                              class="citation-mark"><sup>5</sup></a> в саду Джеты,<a
            href="#citation-6" id="ref-6" class="citation-mark"><sup>6</sup></a> в монастыре
        Анатхапиндики, вместе с великим собранием монахов — тысячей тремястами пятьюдесятью бхикшу —
        и вместе с пятьюдесятью бодхисаттвами-махасаттвами.</p>
    <p>И тогда Благословенный, вместе с теми бодхисаттвами-махасаттвами, изложил дхарани<a
            href="#citation-7" id="ref-7" class="citation-mark"><sup>7</sup></a> Праджняпарамиты,
        состоящую из одной буквы. А именно —</p>
    <div class="text-center my-8">
            <p>॥ <strong class="text-red-700">OM</strong> ॥</p>
            <p class="mt-2 text-lg text-gray-600">Так [она звучит].</p>
    </div>
    <p>Благословенный сказал: «Воистину, Праджняпарамита всех Будд-Благословенных собрана в одной
        букве. А именно — <strong>OM</strong>.</p>
    <p>Эта единая буква, о Субхути, — врата дхарани<a href="#citation-8" id="ref-8"
                                                      class="citation-mark"><sup>8</sup></a>
        Праджняпарамиты всех Будд-Благословенных.</p>
    <p>Итак, о Субхути, посредством этой одной буквы<a href="#citation-9" id="ref-9"
                                                       class="citation-mark"><sup>9</sup></a>
        [раскрывается, что] все дхармы<a href="#citation-10" id="ref-10" class="citation-mark"><sup>10</sup></a>
        — несозданны и неразрушимы;<a href="#citation-11" id="ref-11"
                                     class="citation-mark"><sup>11</sup></a> они успокоены,<a
            href="#citation-12" id="ref-12" class="citation-mark"><sup>12</sup></a> недвойственны,<a
            href="#citation-13" id="ref-13" class="citation-mark"><sup>13</sup></a> лишены „я".<a
            href="#citation-14" id="ref-14" class="citation-mark"><sup>14</sup></a></p>
    <p>Потому, о Субхути, бодхисаттве-махасаттве следует неотступно взращивать<a href="#citation-15"
        id="ref-15" class="citation-mark"><sup>15</sup></a> Праджняпарамиту».</p>
    <p>Так изрёк Благословенный. Достопочтенный<a href="#citation-16" id="ref-16"
                                                  class="citation-mark"><sup>16</sup></a> Субхути<a
            href="#citation-17" id="ref-17" class="citation-mark"><sup>17</sup></a> с радостью и
        внимательным умом<a href="#citation-18" id="ref-18" class="citation-mark"><sup>18</sup></a>
        принял [это слово Благословенного].</p>
    <p class="text-right italic">Перевёл с санскрита и составил примечания О.&nbsp;Л.&nbsp;
        Волошановский, Киев, январь 2026&nbsp;г.</p>
    <hr class="my-8 border-t-4 border-gray-500">
