        <h4 class="text-center text-gray-800 font-bold text-xl my-4">ПРИМЕЧАНИЯ</h4>
<p></p>
        <p class="my-2" id="citation-1"><sup>1</sup> <strong>I. Санскритский оригинал</strong><br>
            <strong>Деванагари:</strong><br>
            ॐ नमो भगवत्यै आर्यप्रज्ञापारमितायै ॥<br>
            एवं मया श्रुतम् । एकं समयं भगवान् श्रावस्त्यां विहरति स्म जेतवनेऽनाथपिण्डदस्यारामे महता भिक्षुसङ्घेन सार्धमर्धत्रयोदशभिः भिक्षुशतैः सार्धं
            पञ्चाशता बोधिसत्त्वैर्महासत्त्वैः ।<br>
            अथ खलु भगवान् सार्धं तैर्बोधिसत्त्वैर्महासत्त्वैरेकाक्षरां प्रज्ञापारमिताधारणीं देशयति स्म । यदुत —<br>
            ॥ ॐ ॥<br>
            इति ।<br>
            भगवानाह । यावत्सर्वबुद्धानां भगवतां प्रज्ञापारमिता एकाक्षरेण सङ्गृहीता । तद्यथा — ॐ ।<br>
            योऽसौ सुभूते एकाक्षरो धारणीमुखं सर्वबुद्धानां भगवतां प्रज्ञापारमितायाः ।<br>
            तेन खलु सुभूते एकाक्षरेण सर्वधर्मा अनुत्पन्ना अनिरुद्धाः । शान्ता अद्वया अनात्मानः । तस्मात्सुभूते बोधिसत्त्वो महासत्त्वोऽप्रमत्तः प्रज्ञापारमितां भावयितव्यः ।<br>
            भगवतो भाषितमिदमभ्यनन्ददायुष्मान्सुभूतिः प्रीतिर्मनसिकारश्च ॥<br>
