            <strong>II. Историко-религиозный контекст</strong><br>
            Ekākṣarī Prajñāpāramitā принадлежит к корпусу текстов
            Праджняпарамиты — одному из важнейших собраний махаянских сутр, развивавшихся с I века
            до н.э. по VIII век н.э. В этом корпусе представлены тексты от обширнейшей Сутры в 100&nbsp;000 шлок (<em>Śatasāhasrikā Prajñāpāramitā</em>) до совсем небольших текстов: Сутры
            Сердца (<em>Prajñāpāramitā Hṛdaya</em>) и данной Сутры Одной Буквы — очень краткого
            произведения, где вся Праджняпарамита сводится к одному слогу <strong>OM</strong>. Этот
            текст представляет собой предельное выражение апофатического метода махаяны: истина не
            может быть выражена словами, но может быть указана. <strong>OM</strong> в данной сутре —
            не описание реальности или изложение некой «мудрости», а прямое указание (<em>sākṣāt-kāra</em>)
            на недвойственную природу ума.<a href="#ref-1" class="text-blue-500 hover:underline">↩</a></p>
        <p class="my-2" id="citation-2"><sup>2</sup> В данной сутре слог <strong>OM</strong> встречается
            дважды в разных функциях:<br>
            1. В мангала-шлоке (вступительной формуле почитания) — как традиционное благословение и
            ритуальное открытие священного текста.<br>
            2. В теле сутры (॥ ॐ ॥) — как ekākṣarī dhāraṇī, («одна буква» или «один слог»),
            вмещающий всю Праджняпарамиту. В махаянской традиции он символизирует неделимое единство
            Трёх Тел Будды — Трикая (<em>trikāya</em>): Дхармакая (Тело Дхармы), Самбхогакая (Тело
            Блаженства) и Нирманакая (Тело Проявления), а также триаду <strong>А-У-М</strong>,
            представляющую прошлое, настоящее и будущее, или три состояния сознания (бодрствование,
            сон со сновидениями, глубокий сон), за которыми следует четвёртое — турья, чистое
            осознавание.<a href="#ref-2" class="text-blue-500 hover:underline">↩</a></p>
        <p class="my-2" id="citation-3"><sup>3</sup> <strong>Арья-Праджняпарамита
                (ārya-prajñāpāramitā)</strong> — «Благородная Совершенная Мудрость». <em>Ārya</em>
            («благородный», «возвышенный») указывает на принадлежность к над-мирскому уровню Учения,
            на вхождение в поток святости. <em>Prajñāpāramitā</em> — сложносоставное слово: <em>prajñā</em>
            («мудрость», «различающее знание») + <em>pāramitā</em> («достижение другого берега», от
            <em>pāram</em> — «на тот берег» + суффикс <em>-itā</em>). Это мудрость, достигшая
            «того/иного/противоположного берега» просветления, за пределами сансары.<a href="#ref-3"
            class="text-blue-500 hover:underline">↩</a>
        </p>
        <p class="my-2" id="citation-4"><sup>4</sup> <strong>Так я слышал (evaṃ mayā
                śrutam)</strong> — классическая формула открытия буддийских сутр, восходящая к
            устной традиции. <em>Evaṃ</em> («так») + <em>mayā</em> (творительный падеж от
            <em>aham</em> — «мною») + <em>śrutam</em> (страдательное причастие от корня √śru —
            «слышать»). Указывает на то, что текст передаётся со слов прямого свидетеля —
            традиционно Ананды, двоюродного брата и личного помощника Будды, обладавшего
            феноменальной памятью.<a href="#ref-4" class="text-blue-500 hover:underline">↩</a></p>
        <p class="my-2" id="citation-5"><sup>5</sup> <strong>Шравасти (śrāvastī)</strong> — столица
            древнего царства Кошала (современный штат Уттар-Прадеш, Индия), один из важнейших
            центров раннего буддизма. Будда провёл здесь 25 сезонов дождей (васс), больше, чем в
            любом другом месте.<a href="#ref-5" class="text-blue-500 hover:underline">↩</a></p>
        <p class="my-2" id="citation-6"><sup>6</sup> <strong>Сад Джеты, монастырь Анатхапиндики
                (jetavane anāthapiṇḍadasyārāme)</strong> — <em>Jetavana</em> («роща [принца] Джеты»)
            + <em>Anāthapiṇḍada</em> («кормящий беззащитных», прозвище богатого купца,
            пожертвовавшего землю). Согласно традиции, купец Анатхапиндика купил рощу у принца
            Джеты, выложив её площадь золотыми монетами, чтобы построить монастырь для Будды и
            сангхи.<a href="#ref-6" class="text-blue-500 hover:underline">↩</a></p>
        <p class="my-2" id="citation-7"><sup>7</sup> <strong>Дхарани (dhāraṇī)</strong> — от
            санскритского корня √dhṛ («держать», «удерживать», «поддерживать»). Дхарани — это не
            просто мантра или заклинание, но мнемоническое и духовное средство, «удерживающее» в
            сжатой форме всю суть обширного учения. В махаянской традиции дхарани обладают защитной
            и преобразующей силой, служат «вратами памяти» (<em>smṛti-dvāra</em>), позволяя
            практикующему мгновенно актуализировать всю полноту понимания.<a href="#ref-7"
                                                                             class="text-blue-500 hover:underline">↩</a>
        </p>
        <p class="my-2" id="citation-8"><sup>8</sup> <strong>Врата дхарани (dhāraṇī-mukha)</strong>
            — <em>mukha</em> означает «вход», «дверь», «лицо», «начало». Это «точка входа» в
            безбрежный океан Праджняпарамиты. Через созерцание одной буквы <strong>OM</strong>
            открывается доступ ко всей недвойственной мудрости всех Будд трёх времён.<a
                href="#ref-8" class="text-blue-500 hover:underline">↩</a></p>
        <p class="my-2" id="citation-9"><sup>9</sup> <strong>Посредством этой одной буквы (tena...
                ekākṣareṇa)</strong> — не «звук вызывает состояние», а осознание, выраженное этим
            слогом, раскрывает истинную природу явлений.<a href="#ref-9"
                                                           class="text-blue-500 hover:underline">↩</a>
        </p>
        <p class="my-2" id="citation-10"><sup>10</sup> <strong>Дхармы (dharmāḥ)</strong> — в данном
            контексте: все явления, феномены, составные и несоставные элементы опыта
            (<em>saṃskṛta</em> и <em>asaṃskṛta dharma</em>), а не Учение Будды (Дхарма с заглавной
            буквы).<a href="#ref-10" class="text-blue-500 hover:underline">↩</a></p>
        <p class="my-2" id="citation-11"><sup>11</sup> <strong>Несозданны и неразрушимы (anutpannā
                aniruddhāḥ)</strong> — <em>an-utpannā</em> (отрицание <em>ut-pad</em> — «возникать»)
            и <em>an-iruddhāḥ</em> (отрицание <em>ni-rudh</em> — «прекращаться»). Отсутствие
            рождения (<em>utpāda</em>) и прекращения (<em>nirodha</em>) указывает на природу
            таковости (<em>tathatā</em> или <em>dharmatā</em>): явления с самого начала пусты от
            собственного бытия, они никогда не возникают из некой самосущей субстанции и не исчезают
            в абсолютное ничто. Это центральный тезис учения о пустоте (<em>śūnyatā</em>).<a
                href="#ref-11" class="text-blue-500 hover:underline">↩</a></p>
        <p class="my-2" id="citation-12"><sup>12</sup> <strong>Успокоены (śāntāḥ)</strong> — от
            корня √śam («успокаиваться», «утихать»). <em>Śānta</em> описывает естественное состояние
            дхарм, свободное от волнений двойственности бытия и небытия, вечности и уничтожения. Это
            изначальный покой (<em>śānti</em>), нирвана как естественное состояние, а не достижение.<a
                href="#ref-12" class="text-blue-500 hover:underline">↩</a></p>
        <p class="my-2" id="citation-13"><sup>13</sup> <strong>Недвойственны (advayāḥ)</strong> —
            <em>a-dvaya</em>, буквально «не-два». Отсутствие разделения на субъект и объект,
            познающего и познаваемое, сансару и нирвану, чистое и нечистое, существование и
            не-существование. Недвойственность (<em>advaya-jñāna</em>) — высшая реализация махаяны,
            превосходящая любые концептуальные противопоставления.<a href="#ref-13"
                                                                     class="text-blue-500 hover:underline">↩</a>
        </p>
        <p class="my-2" id="citation-14"><sup>14</sup> <strong>Лишены «я» (anātmānaḥ)</strong> —
            <em>an-ātman</em>, отсутствие самобытия (<em>ātman</em>) во всех явлениях.
            <em>Anātman</em> — одна из трёх характеристик существования (<em>tri-lakṣaṇa</em>)
            наряду с непостоянством (<em>anitya</em>) и страданием (<em>duḥkha</em>). В махаяне это
            расширяется до учения о пустоте всех дхарм от собственной природы
            (<em>dharma-śūnyatā</em>).<a href="#ref-14" class="text-blue-500 hover:underline">↩</a>
        </p>
        <p class="my-2" id="citation-15"><sup>15</sup> <strong>Неотступно взращивать (apramattaḥ
                bhāvayitavyaḥ)</strong> — <em>apramatta</em> (от <em>a-</em> + <em>pra-mad</em> —
            «опьяняться», «быть небрежным») означает «бдительный», «внимательный», «непраздный».
            <em>Apramāda</em> («не беспечность», «бдительность») — одна из высших добродетелей
            бодхисаттвы, последнее наставление Будды перед паринирваной. <em>Bhāvayitavyaḥ</em> —
            герундив от корня √bhū («становиться», «развивать»), означающий долженствование:
            «следует развивать», «должно взращивать». Это указывает на непрерывное пребывание в
            осознании недвойственной мудрости.<a href="#ref-15"
                                                 class="text-blue-500 hover:underline">↩</a></p>
        <p class="my-2" id="citation-16"><sup>16</sup> <strong>Достопочтенный (āyuṣmat)</strong> —
            почётный эпитет старших монахов, буквально «обладающий долгой жизнью», «достойный
            долголетия». Форма вежливого обращения в монашеской общине.<a href="#ref-16"
                                                                          class="text-blue-500 hover:underline">↩</a>
        </p>
        <p class="my-2" id="citation-17"><sup>17</sup> <strong>Субхути (subhūti)</strong> — один из
            десяти главных учеников Будды, «лучший из пребывающих в покое» и наиболее глубоко
            постигший учение о пустоте. Именно Субхути является главным собеседником в большинстве
            текстов Праджняпарамиты, включая знаменитую «Алмазную сутру» (<em>Vajracchedikā
                Prajñāpāramitā Sūtra</em>). Его имя означает «благое существование»
            (<em>su-bhūti</em>).<a href="#ref-17" class="text-blue-500 hover:underline">↩</a></p>
        <p class="my-2" id="citation-18"><sup>18</sup> <strong>С радостью и внимательным умом
                (prītiḥ manasikāraḥ ca)</strong> — <em>prīti</em> здесь не обыденная эмоциональная
            радость, а восхищённая радость постижения истины (<em>dhamma-prīti</em>), один из
            факторов просветления (<em>bodhy-aṅga</em>). <em>Manasikāra</em> (от <em>manas</em> —
            «ум» + <em>kāra</em> — «делание») — «направление ума», осознанное удержание объекта
            Дхармы в уме, мудрое внимание (<em>yoniso manasikāra</em>). Эта формула завершения
