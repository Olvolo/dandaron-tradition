    <div class="prose text-justify max-w-4xl mx-auto leading-relaxed space-y-4">
        <p>Сутры Праджняпарамиты – квинтэссенция традиции Великой колесницы. Великая колесница,
            Махаяна, – учение Будды, предназначенное для бодхисаттв, подвижников, устремившихся к
            запредельному Пробуждению ради помощи живым существам. Сутры традиции
            <em>слушателей</em> (шравак, последователей так называемой Малой колесницы, Хинаяны)
            – Палийский канон, записанные в первых веках до нашей эры – через 200-300 лет после
            ухода Пробужденного в Великий Покой (Маха-паринирвану), содержали те сбереженные в
            памяти – от одного к другому выучиваемые наизусть – наставления, которые были
            предназначены Учителем прежде всего для учеников, стремящихся достичь собственного
            Освобождения от страданий. Этот этап перепрыгнуть никому невозможно. Это учение было
            преподано и широко распространено вначале.</p>
        <p>Традиция Великой колесницы, устремленная к цели, выходящей за пределы личного
            Освобождения, таилась подспудно, не получая широкой огласки примерно до I в. н.э. В
            первые века нашей эры учение Великой колесницы получило распространение, сделалось
            открытым, и тексты, переданные через последователей учения от Будды, были записаны. К
            этому периоду относится и появление сутр Праджняпарамиты – «Запредельной мудрости», или
            «Совершенства запредельной мудрости», для восприятия которых требовалось прежде всего
            устремление к Пробуждению ради помощи живым существам (о духовных практиках, ведущих
            подвижников Пробуждения к их цели, говорится в этих сутрах немало), но не только одно
            устремление. Для их восприятия, чтобы вынести отрицание хорошо известных предметов,
            включая священные предметы буддийского учения, бодхисаттвам требовалось особое мужество
            – так называемое «терпение, стойкость» относительно <em>пустоты</em>, отсутствия
            существования
            предметов объективно, по собственной природе.</p>
        <p>«Алмазная» (буквально – ваджрная, молниевая) сутра рассекала, как громовая стрела. И –
            поражая неведение – порождала ведение. Видение реальности.</p>
        <p class="text-right italic text-gray-800 my-4">М.&nbsp;К.</p>
        <h3 class="text-center"><strong>Алмазная сутра</strong><br>
            <em>или сутра о запредельной мудрости, рассекающей, как громовая стрела</em></h3>
        <p class="text-right italic text-sm">Перевод с санскрита О.&nbsp;Ф.&nbsp;Волковой, совместно
            с Л.&nbsp;Мяллем, 1965 г.</p>
        <p><strong>1.</strong> Однажды я слышал так: Бхагават проживал в Шравасти, в лесу Джеты, в
            саду Анатхапиндады, вместе с большой общиной (сангхой) нищенствующих монахов (бхикшу) –
            двенадцатью с половиной сотнями монахов, многочисленными великосущными бодхисаттвами. И
            вот Бхагават в первой половине дня, надев монашеское одеяние и взяв чашу, вошел в
            великий город Шравасти за подаянием. Затем, обойдя великий город Шравасти, после
            получения подаяния и трапезы, отложил в сторону сосуд для подаяния и монашеское одеяние,
            омыл ноги, сел на подготовленное сидение, скрестив ноги и выпрямив тело, и направил
            перед собой свое внимание. И вот многочисленные монахи, приблизившись туда, где был
            Бхагават, приветствовали его, склонившись головой к ногам и трижды обойдя слева направо,
            и уселись в кружок в стороне.</p>
        <p><strong>2.</strong> Тем временем появился в этом собрании достопочтенный Субхути и
            уселся. И вот достопочтенный Субхути, поднявшись с сидения, закинул на одно плечо
            верхнее одеяние, опустился на правое колено на землю, поклонился со сложенными ладонями
            в сторону Бхагавата и так сказал ему: "Удивительно, Бхагават, в высшей степени
            удивительно, Во-Благе-Ушедший (Сугата), что именно Татхагата, архат, совершенный Будда
            высшей помощью помогал великосущным бодхисаттвам. Удивительно, Бхагават, что именно
            Татхагата, архат, Совершенный Будда одарил великосущных бодхисаттв высшим даром. Так как
            же, Бхагават, должен поступать вступивший на стезю бодхисаттвы сын или дочь из хорошей
            семьи, как должен вести себя, как должен владеть мыслью?</p>
        <p>В ответ на это Бхагават так сказал достопочтенному Субхути: "Правильно, правильно,
            Субхути, именно так, как ты говоришь: высшей помощью помогал Татхагата великосущным
            бодхисаттвам, высшим даром одарил Татхагата великосущных бодхисаттв. Поэтому слушай,
            Субхути, хорошо и внимательно запомни, я расскажу тебе, как должен поступать вступивший
            на стезю бодхисаттвы, как должен вести себя, как должен владеть мыслью".</p>
        <p>– Пожалуйста, Бхагават, – ответил достопочтенный Субхути.</p>
        <p><strong>3.</strong> Бхагават сказал так: «В этом мире, Субхути, вступивший на стезю
            бодхисаттвы должен породить в себе такую мысль: сколько ни есть, Субхути, существ в
            сфере существ, объединяемых под абстрактным понятием "существо", рождающихся из яйца,
            рождающихся из лона, рождающихся из пота или рождающихся произвольно, имеющих форму или
            не имеющих форм, обозначенных или необозначенных и не необозначенных, какую бы ни
            представить себе сферу существ, могущую быть представленной, всех их я должен привести в
            сферу Нирваны, Нирваны без субстанции существования. И даже если приведены таким образом
            в Нирвану мириады существ, никакое существо не бывает приведенным в Нирвану. Почему так?
            Если, Субхути, для бодхисаттвы есть понятие "существо" (саттва), нельзя о нем говорить
            "бодхисаттва". Почему так? Нельзя, Субхути, говорить "бодхисаттва" о том, для кого есть
            понятие "душа" (атман), понятие "существо" (саттва), понятие "жизнь" (джива) или понятие
            "индивид" (пудгала).</p>
        <p><strong>4.</strong> Однако, Субхути, бодхисаттва, опирающийся на вещи, не должен давать
            даяние; опирающийся на что-либо, не должен давать даяние; опирающийся на форму, не
            должен давать даяние, чтобы не опираться на понятие, знак. Почему так? Нелегко измерить
            святые заслуги того, Субхути, кто, не опираясь, дает даяние. Как ты думаешь, Субхути,
            легко ли измерить пространство в восточной стороне света?»</p>
        <p>Субхути сказал: "Нет, Бхагават".</p>
        <p>Бхагават сказал: "Точно так же нелегко измерить святые заслуги того бодхисаттвы, Субхути,
            который, не опираясь, дает даяние.</p>
        <p><strong>5.</strong> Как ты думаешь, Субхути, следует ли рассматривать Татхагату с точки
            зрения полноты признаков?</p>
        <p>Субхути сказал: "Нет, Бхагават, нельзя рассматривать Татхагату с точки зрения полноты
            признаков. Почему так? То, Бхагават, о чем Татхагата говорил как о полноте признаков, то
            есть неполнота признаков".</p>
        <p>В ответ на это Бхагават сказал достопочтенному Субхути так: "Поскольку, Субхути, есть
            полнота признаков, постольку есть обман, поскольку есть неполнота признаков, постольку
            нет обмана, ибо следует рассматривать Татхагату с точки зрения признаков –
            непризнаков."</p>
        <p><strong>6.</strong> В ответ на это достопочтенный Субхути так сказал Бхагавату: "Будут
            ли, Бхагават, какие-либо существа в будущем в последующие пять столетий, когда будет
            происходить исчезновение сущей Дхармы, которые создадут истинное понятие, если им
            изложат такого рода высказывания сутр?"</p>
        <p>Бхагават сказал: "Не говори так, Субхути, что будут ли какие-нибудь существа в будущем, в
            последующие пять столетий, когда будет происходить исчезновение сущей Дхармы, которые
            создадут истинное понятие, если им изложат такого рода высказывания сутр. Но конечно,
            Субхути, в будущем, в последующие времена, в последующие пять столетий, когда будет
            происходить исчезновение благой Дхармы, будут великосущные бодхисаттвы, наделенные
            высокими качествами, добродетельные поведением и интуитивным знанием (праджня), которые
            создадут истинное понятие, если им изложат такого рода высказывания сутр.</p>
        <p>Более того, Субхути, этим великосущным бодхисаттвам окажет почитание не один Будда, не
            одним Буддой взращены благие корни, но многие сотни тысяч Будд, Субхути, окажут
            почитание, и от многих сотен тысяч Будд взрастят благие корни те великосущные
            бодхисаттвы, которые, если им изложат такого рода высказывания сутр, обретут веру в
            единую мысль.</p>
        <p>Знает их Татхагата, Субхути, знанием Будды, видит их Татхагата, Субхути, глазом Будды,
            понимает их Татхагата, Субхути. Все они, Субхути, произведут и приобретут неизмеримые
            мириады скоплений святых заслуг. Почему так? Потому что, Субхути, для этих великосущных
            бодхисаттв нет ни понятия "душа", ни понятия "существо", ни понятия "индивид". И также,
            Субхути, нет для них ни "понятия", ни "непонятия". Почему так? Если бы, Субхути, для
            этих великосущных бодхисаттв было понятие "дхарма", то держались бы за "душу", за
            "существо", за "жизнь", за "индивид". Если было бы понятие "не-дхарма", то они также
            держались бы за "душу", "существо", "жизнь", "индивид". Почему так? Великосущный
            бодхисаттва, Субхути, не только не должен держаться "дхармы", но и "не-дхармы". Поэтому
            Татхагата сказал тонкое изречение со скрытым намеком: "Знающие, что рассуждение о
            дхармах подобно плоту, должны оставить дхармы, тем более "не-дхармы".
        </p>
        <p><strong>7.</strong> Затем снова Бхагават сказал так достопочтенному Субхути: «Как ты
            думаешь, Субхути, есть ли какая-либо дхарма, которую Татхагата понимал как "наивысшее
            совершенное просветление" или наставлял бы Татхагата в какой-либо такой дхарме?»</p>
        <p>В ответ на это достопочтенный Субхути сказал Бхагавату так: "Если я, Бхагават, понимаю
            смысл изложенного, то нет какой-либо дхармы, которую Татхагата понимал как "наивысшее
            совершенное просветление", ни такой дхармы, в которой наставлял бы Татхагата. Почему же?
            Та Дхарма, которую понимал и в которой наставлял Татхагата, непостижима и неизрекаема,
            она ни "Дхарма", и ни "не-Дхарма". Почему так? Определенное (самскрита) не влияет на
            благородных индивидов".</p>
        <p><strong>8.</strong> Бхагават сказал: "Как ты думаешь, Субхути, если какой-либо сын или
            дочь из хорошей семьи наполнит семью драгоценностями три тысячи миллионов миров и даст
            их в дар Татхагатам, архатам, совершенным Буддам, то создаст ли по этой причине сын или
            дочь из хорошей семьи огромное скопление святых заслуг?"</p>
        <p>Субхути сказал: "Много, Бхагават, много, Во-Благе-Ушедший, святых заслуг создаст по этой
            причине сын или дочь из хорошей семьи. Почему так? То, Бхагават, о чем Татхагата говорил
            как о скоплении святых заслуг, об этом он также говорил как о не-скоплении. Поэтому
            Татхагата говорил: "Скопление заслуг, скопление заслуг".</p>
        <p>Бхагават сказал: «И еще, Субхути, если какой-либо сын или дочь из хорошей семьи наполнит
            семью драгоценностями три тысячи миллионов миров и даст их в дар Татхагатам, архатам,
            совершенным Буддам, и если он возьмет из изложения Дхармы хотя бы одну четырехстопную
            гатху и покажет и объяснит ее другим, то он создаст по этой причине неизмеримые мириады
            скоплений святых заслуг. Почему так? Потому что ведь не возникало наивысшее совершенное
            просветление у Татхагат, архатов, совершенных Будд, потому что не возникало и
            Будды-Бхагавата. Почему так? Дхармы Будды, Субхути, Татхагата говорил о них как о
            не-дхармах Будды. Поэтому они называются "дхармы Будды".</p>
        <p><strong>9-а.</strong> Как ты думаешь, Субхути, бывает ли у вступившего в поток такая
            мысль: "Я обрел плод вступления в поток?"»</p>
        <p>Субхути сказал: «Нет, Бхагават, не бывает у вступившего в поток такой мысли: "Я обрел
            плод вступления в поток". Почему так? Ибо он, Бхагават, не вступил ни в какую дхарму.
            Поэтому он называется "вступивший в поток". Если бы, Бхагават, у вступившего в поток
            была такая мысль: "Я обрел плод вступления в поток", он бы держался за "душу",
            "существо", за "жизнь", за "индивида".»</p>
        <p><strong>9-б.</strong> Бхагават сказал: «Как ты думаешь, Субхути, бывает ли у не
            возвращающегося такая мысль: "Я обрел плод не возвращающегося"»?</p>
        <p>Субхути сказал: "Нет, Бхагават, не бывает у не возвращающегося такой мысли: "Я обрел плод
            не возвращающегося". Почему так? Ибо он, Бхагават, не вступил ни в какую дхарму, которая
            была бы "невозвращением". Поэтому он называется "невозвращающимся".»</p>
        <p><strong>9-в.</strong> Бхагават сказал: «Как ты думаешь, Субхути, бывает ли у архата такая
            мысль: "Я достиг состояния архата"? »</p>
        <p>Субхути сказал: «Нет, Бхагават, не бывает у архата такой мысли: "Я достиг состояния
            архата". Почему так? Ибо, Бхагават, нет никакой дхармы по имени "архат". Поэтому он
            называется "архат". Если бы у архата была такая мысль: "Я достиг состояния архата", то
            он бы держался за "душу", за "существо", за "жизнь", за "индивида".</p>
        <p><strong>9-г.</strong> Почему так? На меня указал Татхагата, архат, совершенный Будда как
            на первого среди живущих не в скверне. Я есмь Бхагават, архат, лишенный страсти. И я,
            Бхагават, не думаю так: "Я - архат, лишенный страсти". Если бы, Бхагават, у меня
            возникла такая мысль, что я достиг состояния архата, то Татхагата не предсказал бы обо
            мне, что первый среди живущих не в скверне Субхути, сын из хорошей семьи, не живет
            нигде. Поэтому говорят так: "Живущий не в скверне, живущий не в скверне".»</p>
        <p><strong>10-а.</strong> Бхагават сказал: "Как ты думаешь, Субхути, существует ли
            какая-либо дхарма, которую Татхагата взял от Татхагаты, архата, совершенного Будды
            Дипанкары?"</p>
        <p>Субхути сказал: "Нет, Бхагават, нет никакой дхармы, которую Татхагата взял от Татхагаты,
            архата, совершенного Будды Дипанкары".</p>
        <p><strong>10-б.</strong> Бхагават сказал: «Если какой-нибудь бодхисаттва, Субхути, скажет
            так: "Я создам чистые земли Будд", – он скажет не то. Почему так? Чистые земли Будд,
            чистые земли Будд, Субхути, Татхагата говорил о них как о не "чистых землях Будд".
            Поэтому говорят: "Чистые земли Будд".</p>
        <p><strong>10-г.</strong> Поэтому, Субхути, великосущный бодхисаттва таким образом должен
            породить в себе неопирающуюся мысль, которая бы ни на что не опиралась, не опиралась бы
            ни на форму, не опиралась бы на звук, вкус, осязаемость, дхарму. Таким образом, Субхути,
            если будет человек, наделенный телом, великим телом, и таково же будет его личностное
            существование (атмабхава), как царь горы Сумеру, то, как ты думаешь, Субхути, великим ли
            будет его личностное существование?»</p>
        <p>Субхути сказал: "Великим, Бхагават, великим, Во-Благе-Ушедший, будет это личностное
            существование. Бхагават говорил о нем как о не-существовании. Поэтому говорят:
            "личностное существование". Оно, Бхагават, ни существование, ни не-существование.
            Поэтому говорят: "Личностное существование".»</p>
        <p><strong>11.</strong> Бхагават сказал: "Как ты думаешь, Субхути, если было бы столько рек
            Ганг, сколько песчинок в великой реке Ганге, то велико ли было бы скопление песчинок в
            них?</p>
        <p>Субхути сказал: "Этих рек Ганг, Бхагават, было бы очень много, что уж говорить о
            песчинках в этих реках!"</p>
        <p>Бхагават сказал: "Поведаю тебе, Субхути, объясню тебе, что если есть столько миров,
            сколько было бы песчинок в этих реках Гангах, и какая-нибудь женщина или мужчина,
            наполнив семью драгоценностями столько много миров, преподнесет их в дар архатам,
            Татхагатам, совершенным Буддам, и если сын или дочь из хорошей семьи возьмет из
            изложения Дхармы хотя бы одну четырехстопную гатху и покажет и объяснит ее другим, то он
            именно по этой причине создаст многие неизмеримые мириады скоплений святых заслуг.</p>
        <p><strong>12.</strong> И еще, Субхути, та часть земли, где он или она, взяв из изложения
            Дхармы хотя бы одну четырехстопную гатху и покажет и объяснит ее другим, станет святым
            местом для мира богов, людей и асуров, что же говорить о том, кто возьмет это изложение
            Дхармы целиком и полностью прочтет и изучит и объяснит его подробно другим, и
            проникнутся они, Субхути, великим изумлением. В такой части земли, Субхути, живет
            Учитель или какой-нибудь другой, замещающий его, знающий наставник."</p>
        <p><strong>13-а.</strong> В ответ на эти слова достопочтенный Субхути так сказал Бхагавату:
            "Каково же, Бхагават, это изложение Дхармы и как мне воспринять его?"</p>
        <p>После этих слов Бхагават сказал достопочтенному Субхути: «Это изложение Дхармы, Субхути,
            есть "праджняпарамита" – "запредельное интуитивное знание", так и воспринимай его.
            Почему так? То, Субхути, о чем Татхагата говорит как о запредельности интуитивного
            знания, об этом же Татхагата говорил как о не запредельности. Поэтому говорят так:
            "Запредельность интуитивного знания".</p>
        <p><strong>13-б.</strong> Как ты думаешь, Субхути, есть ли какая-либо дхарма, о которой
            говорил Татхагата?»</p>
        <p>Субхути сказал: "Нет, Бхагават, нет никакой дхармы, о которой говорил Татхагата".</p>
        <p><strong>13-в.</strong> Бхагават сказал: "Как ты думаешь, Субхути, сколько пылинок в трех
            тысячах миллионов миров, много ли это?"</p>
        <p>Субхути сказал: «Много, Бхагават, много пылинок, Во-Благе-Ушедший. Почему так? То,
            Бхагават, о чем Татхагата говорил как о пылинках земли, об этом Бхагават, Татхагата
            говорил как о не-пылинках. Поэтому говорят: "Пылинки земли". А также о чем Татхагата
            говорил как о Вселенной, Татхагата говорил как о не Вселенной. Поэтому говорят так:
            "Вселенная".»</p>
        <p><strong>13-г.</strong> Бхагават сказал: "Как ты думаешь, Субхути, можно ли узнать
            Татхагату, архата, совершенного Будду по тридцати двум признакам великого человека?"</p>
        <p>Субхути сказал: "Нет, Бхагават, нельзя узнать Татхагату, архата, совершенного Будду по
            тридцати двум признакам великого человека. Почему так? То, о чем Татхагата говорил как о
            тридцати двух признаках великого человека, об этом Бхагават, Татхагата говорил как о
            не-признаках. Поэтому говорят так: "Тридцать два признака великого человека".</p>
        <p><strong>13-д.</strong> Бхагават сказал: "И еще, Субхути, если женщина или мужчина
            ежедневно будет отрекаться от собственных (будущих) существований, число которых равно
            числу песчинок в реке Ганг, и будет отрекаться от собственных (будущих) существований в
            течение кальп, число которых равно числу песчинок в реке Ганг, и если возьмет из
            изложения Дхармы хотя бы одну четырехстопную гатху и покажет и объяснит ее другим, то он
            или она именно по этой причине создаст многие неизмеримые мириады скоплений святых
            заслуг".</p>
        <p><strong>14-а.</strong> И вот достопочтенный Субхути пролил слезы, исторгнутые силой
            Дхармы, и, вытерев слезы, так сказал Бхагавату: «Удивительно, Бхагават, в высшей степени
            удивительно, Во-благе Ушедший, что Татхагата поведал это изложение Дхармы ради существ,
            опирающихся на высшую колесницу, опирающихся на лучшую колесницу, благодаря чему,
            Бхагават, у меня родилась джняна. Я, Бхагават, никогда раньше не слышал изложение Дхармы
            в такой форме. Великим удивлением проникнутся бодхисаттвы, которые услышат произносимые
            здесь сутры и обретут истинное понятие. Почему так? То, Бхагават, что есть истинное
            понятие, что есть истинное понятие, то есть не истинное понятие. Поэтому Татхагата
            говорит: "Истинное понятие, истинное понятие".</p>
        <p><strong>14-б.</strong> Мне нетрудно будет, Бхагават, уверовать и стать преданным этому
            изложению Дхармы. Те существа, которые будут в будущем, в последующие времена, в
            последующие пять столетий, когда будет происходить исчезновение сущей Дхармы, и которые
            это изложение Дхармы, Бхагават, возьмут, воспримут, прочтут и изучат и подробно объяснят
            другим, они проникнутся великим удивлением.</p>
        <p><strong>14-в.</strong> И еще, Бхагават, для них не будет понятий "душа", "существо",
            "жизнь", "индивид" и не будет для них никакого понятия, ни не-понятия. Почему так?
            Бхагават, что есть понятия "существо", "жизнь", "индивид", то суть не-понятия. Почему
            так? У Будд, бодхисаттв отсутствуют все понятия.»</p>
        <p><strong>14-г.</strong> В ответ на эти слова Бхагават так сказал достопочтенному Субхути:
            «Это так, Субхути, это так. Великим удивлением проникнутся те существа, которые,
            Субхути, при произнесении этой сутры не убоятся, не испугаются и не устрашатся. Почему
            так? Татхагата говорил о ней как о высшей запредельности, Субхути, а также как о
            не-запредельности. То, Субхути, что Татхагата называет высшей запредельностью, то
            беспредельным также называют Будды-Бхагаваты, поэтому говорят так: "Высшая
            запредельность".</p>
        <p><strong>14-д.</strong> И еще, Субхути, то, что запредельность терпимости Татхагаты, то
            есть не-запредельность. Почему так? Когда царь Калинги пожелал плоти от моего тела, в то
            время у меня не было понятия "душа" или "существо", или "жизнь", или "индивид", не было
            никакого понятия, ни не-понятия. Почему так? Если бы у меня в то время появилось бы
            понятие "душа", то у меня в то же время появилось бы понятие "злобность". Если бы у меня
            появилось понятие "существо", "жизнь", "индивид", то в то же время у меня появилось бы
            понятие "злобность". Почему так? Знаю я, Субхути, что пять сотен рождений назад, в
            прошлом, я был риши Кшантивадином – проповедовавшим терпимость. Тогда у меня не было
            понятия "душа", "существо", "жизнь", "индивид". Поэтому в таком случае, Субхути,
            великосущный бодхисаттва, отринув все понятия, должен породить мысль о наивысшем
            совершенном просветлении. Он не должен породить мысль, опирающуюся на дхарму, он не
            должен породить мысль, опирающуюся на дхарму, он не должен породить мысль, опирающуюся
            на что-нибудь. Почему так? Что опирается, то именно не опирается. Поэтому так говорит
            Татхагата: "Бодхисаттва должен давать дар, не опираясь. Не должно давать дар, опираясь
            на форму, звук, запах, вкус, осязание, дхарму.</p>
        <p><strong>14-е.</strong> И еще, Субхути, Бодхисаттва должен таким образом отказаться от
            дарения ради всех существ. Почему так? То, что есть понятие "существо", то есть
            не-понятие. Те именно, о ком Татхагата говорил как о всех существах, те суть не
            существа. Почему так? Татхагата говорит правильно, Субхути, говорит истину, говорит так,
            как надо. Татхагата не говорит по-другому. Не говорит ложно Татхагата.</p>
        <p><strong>14–ж.</strong> И еще, Субхути, та Дхарма, которую понимал и в которой наставлял
            Татхагата, – в ней нет ни истины, ни лжи. Это именно так же, Субхути, как вошедший в
            темноту человек ничего не увидит. Так следует смотреть на Бодхисаттву, оказавшегося
            среди вещей, который отказывается от дарения. Однако, Субхути, зрячий человек видит
            различные формы на исходе ночи, при восходе солнца. Так следует смотреть на бодхисаттву,
            не оказывающегося среди вещей, который отказывается от дарения.</p>
        <p><strong>14-з.</strong> И еще, Субхути, если сыновья или дочери из хорошей семьи это
            изложение Дхармы возьмут, воспримут, прочтут и изучат и подробно объяснят другим, то
            знает их Татхагата, Субхути, знанием Будды, видит их Татхагата, Субхути, глазом Будды,
            понимает их Татхагата. Все те существа, Субхути, произведут и приобретут несоизмеримые
            мириады скоплений святых заслуг.</p>
        <p><strong>15-а.</strong> И еще, Субхути, та женщина или тот мужчина, что утром будет
            отрекаться от собственных (будущих) существований, число которых равно числу песчинок в
            реке Ганг, кто в середине дня будут отрекаться от собственных (будущих) существований,
            число которых равно числу песчинок в реке Ганг, кто вечером будет отрекаться от
            собственных (будущих) существований, число которых равно числу песчинок в реке Ганг, и
            таким образом будет отрекаться от собственных (будущих) существований в течение сотен
            тысяч мириадов кальп, если сравнить с ним (нею) того, кто, услышав это изложение Дхармы,
            не отбросит его, то именно этот последний (эта последняя) по этой причине произведет
            незмеримые мириады скоплений святых заслуг. Что же говорить о том, кто, записав его,
            воспримет и изучит и подробно объяснит другим!</p>
        <p><strong>15-б.</strong> И еще, Субхути, это изложение Дхармы немыслимо, несравнимо. И это
            изложение Дхармы, Субхути, Татхагата говорил для существ, стоящих на первой колеснице,
            стоящих на лучшей колеснице, которые это изложение Дхармы возьмут, воспримут, прочтут и
            изучат и подробно объяснят другим. Знает их Татхагата, Субхути, знанием Будды, видит их
            Татхагата, Субхути, глазом Будды, понимает их Татхагата. Все эти существа, Субхути,
            будут наделены немыслимыми, несравнимыми, безмерными, безграничными скоплениями святых
            заслуг. Все эти существа, Субхути, во плоти воспримут просветление. Почему так? Ибо
            невозможно, Субхути, чтобы слышали это изложение Дхармы ни существа, склонные к высшей
            цели, ни придерживающиеся взгляда о душе, ни придерживающиеся взгляда о жизни, ни
            придерживающиеся взгляда об индивиде. Невозможно, чтобы существа, не давшие обета
            бодхисаттвы, это изложение Дхармы слушали бы, взяли бы, восприняли бы и изучили. Такого
            не может быть.</p>
        <p><strong>15-в.</strong> И еще, Субхути, тот край земли, где эту сутру будут объяснять,
            заслуживает почитания в мире богов, людей и асуров, этот край земли заслуживает почтения
            и почтительного обхода, святым местом станет этот край земли.</p>
        <p><strong>16-а.</strong> Однако, Субхути, те сыновья и дочери из хорошей семьи, кто такого
            рода сутры прочтут, изучат и основательно запомнят и подробно объяснят другим, те станут
            смиренными, станут очень смиренными. Почему так? Те неблагие деяния этих существ,
            ведущие в ад, которые они сотворили в прошлых рождениях, благодаря этому смирению, как
            только они узрят Дхарму, эти их неблагие деяния прошлых рождений будут уничтожены, и они
            достигнут просветления Будды.</p>
        <p><strong>16-б.</strong> Почему так? Знаю я, Субхути, что в прошлые времена, в течение
            неизмеримых мириад кальп, задолго до Татхагаты совершенного Будды Дипанкары, восемьдесят
            четыре сотни тысяч миллионов миллиардов Будд я почитал, и, почитаемые мною, они не
            отвратились от меня. И (если посмотреть на) то, что я, Субхути, почитал тех
            Будд-Бхагаватов и, почитаемые мною, они не отвратились от меня, а также (на) то, что в
            последующие времена, в последующие пять столетий, когда будет происходить исчезновение
            сущей Дхармы, такого рода сутры возьмут, воспримут, прочтут и изучат и подробно объяснят
            другим, то, по сравнению с этим скоплением святых заслуг, то прошлое скопление заслуг не
            составит даже сотой части, даже тысячной, даже стотысячной, даже миллионной, даже
            стомиллионной, даже миллиардной, поскольку это невозможно сосчитать, сравнить,
            сопоставить.</p>
        <p><strong>16-в.</strong> Если бы, опять-таки, Субхути, я сказал о скоплении святых заслуг
            тех сыновей или дочерей из хорошей семьи, ибо те сыновья и дочери из хорошей семьи в то
            время будут еще производить и приобретать скопления святых заслуг, то существа бы сошли
            с ума, впали бы в безумие. И еще, Субхути, немыслимо это изложение Дхармы, сказанное
            Татхагатой, и именно к немыслимому его результату следует стремиться».</p>
        <p><strong>17-а.</strong> И вот, достопочтенный Субхути так сказал Бхагавату: "Как,
            Бхагават, должен поступать вступивший на стезю бодхисаттвы, как должен вести себя, как
            владеть мыслью?"</p>
        <p>Бхагават сказал: «В этом мире, Субхути, вступивший на стезю бодхисаттва должен породить
            такую мысль: все существа я должен привести в сферу нирваны без субстрата существования.
            И даже если приведены в нирвану существа, ни одно существо не бывает приведенным в
            нирвану. Почему так? Если для бодхисаттвы есть понятие "существо", то нельзя о нем
            говорить "бодхисаттва". Почему так? Или есть понятие "жизнь", понятие "индивид", нельзя
            о нем говорить "бодхисаттва". Почему так? Нет никакой дхармы, Субхути, которая
            называлась бы "вступивший на стезю бодхисаттвы".</p>
        <p><strong>17-б.</strong> "Как ты думаешь, Субхути, есть ли какая-нибудь Дхарма, которую
            Татхагата узнал бы от Татхагаты Дипанкары как наивысшее совершенное просветление?»</p>
        <p>В ответ на это достопочтенный Субхути так сказал Бхагавату: "Если я понимаю, Бхагават,
            смысл сказанного Бхагаватом, то нет, Бхагават, никакой дхармы, которую Татхагата узнал
            бы от Татхагаты, архата, совершенного Будды Дипанкары как наивысшее совершенное
            просветление".</p>
        <p>В ответ на это Бхагават так сказал достопочтенному Субхути: «Это так, Субхути, это так,
            нет никакой дхармы, которую Татхагата узнал бы от Татхагаты, архата, совершенного Будды
            Дипанкары как наивысшее совершенное просветление. Опять-таки, Субхути, если бы Татхагата
            узнал какую-нибудь дхарму, то Татхагата Дипанкара не предсказал бы обо мне: "Ты будешь,
            юноша, в будущие дни Татхагатой, архатом, совершенным Буддой по имени Шакьямуни."
            Поскольку тогда, Субхути, Татхагата, архат, совершенный Будда понимал, что нет никакой
            дхармы, которая была бы наивысшим совершенным просветлением, постольку обо мне
            предсказал Татхагата Дипанкара: "Ты будешь, юноша, в будущие дни Татхагатой, архатом,
            совершенным Буддой по имени Шакьямуни."</p>
        <p><strong>17-в.</strong> Почему так? Татхагата – это, Субхути, обозначение для истинной
            таковости (бхутататхата).</p>
        <p><strong>17-г.</strong> Тот, кто скажет так, Субхути: "Татхагата, архат, совершенный Будда
            понимает наивысшее просветление", тот скажет не то, ложно отемнит он меня, Субхути,
            из-за приятия того, чего нет. Почему так? Нет, Субхути, никакой дхармы, которую
            Татхагата понимал бы как наивысшее совершенное просветление. В той Дхарме, Субхути,
            которую Татхагата понимал или в которой наставлял, там нет ни истины, ни лжи. Поэтому
            Татхагата говорит: "Все дхармы суть дхармы Будды." Почему так? Все дхармы, Субхути, –
            Татхагата говорил о них как о не-дхармах. Поэтому говорят: "Все Дхармы суть дхармы
            Будды."</p>
        <p><strong>17-д.</strong> Это так же, Субхути, как если бы был человек, наделенный телом,
            великим телом.»</p>
        <p>Достопочтенный Субхути сказал: «То, Бхагават, о чем Татхагата говорил как о человеке,
            наделенном телом, великим телом, о нем Бхагават, Татхагата говорил как о не-теле.
            Поэтому говорят: "Наделенный телом, великим телом".»</p>
        <p><strong>17-е.</strong> Бхагават сказал: "Это так, Субхути. Если бодхисаттва скажет: я
            приведу существ в нирвану, его не должно называть бодхисаттвой. Почему так? Есть ли,
            Субхути, какая-нибудь дхарма, которая была бы бодхисаттвой?"</p>
        <p>Субхути сказал: "Нет, Бхагават, нет никакой дхармы, которая была бы бодхисаттвой".</p>
        <p>Бхагават сказал: «Существа, существа, Субхути, Татхагата говорил о них как о
            не-существах, поэтому говорят: "Существа". Поэтому Татхагата говорит: "Все дхармы суть
            без "души", без "существа", без "жизни", без "индивида", все дхармы".</p>
        <p><strong>17-ж.</strong> Если, Субхути, бодхисаттва скажет: "Я создам чистые земли Будд", о
            нем должно говорить так же. Почему так? Чистые земли Будд, чистые земли Будд, Субхути,
            Татхагата говорил о них как о не "чистых землях Будд", поэтому говорят: "Чистые земли
            Будд".</p>
        <p><strong>17-з.</strong> Если, Субхути, бодхисаттва верует, что дхармы без "души", то
            Татхагата, архат, совершенный Будда называют его великосущным бодхисаттвой.»</p>
        <p><strong>18-а.</strong> Бхагават сказал: "Как ты думаешь, Субхути, существует ли телесный
            глаз у Татхагаты?"</p>
        <p>Субхути сказал: "Это так, Бхагават, телесный глаз у Татхагаты существует."</p>
        <p>Бхагават сказал: "Как ты думаешь, Субхути, существует ли дивный глаз у Татхагаты?"</p>
        <p>Субхути сказал: "Да, Бхагават, дивный глаз у Татхагаты существует."</p>
        <p>Бхагават сказал: "Как ты думаешь, Субхути, существует ли глаз интуиции (праджни) у
            Татхагаты?"</p>
        <p>Субхути сказал: "Да, Бхагават, у Татхагаты есть глаз интуиции."</p>
        <p>Бхагават сказал: "Как ты думаешь, Субхути, есть ли у Татхагаты глаз Дхармы?"</p>
        <p>Субхути сказал: "Да, Бхагават, у Татхагаты есть глаз Дхармы."</p>
        <p>Бхагават сказал: "Как ты думаешь, Субхути, есть ли у Татхагаты глаз Будды?"</p>
        <p>Субхути сказал: "Да, Бхагават, у Татхагаты есть глаз Будды."</p>
        <p><strong>18-б.</strong> Бхагават сказал: "Как ты думаешь, Субхути, сколько ни есть в
            великой реке Ганг песчинок, говорил ли Татхагата об этих песчинках?"</p>
        <p>Субхути сказал: "Да, Бхагават, да, Во-Благе-Ушедший, Татхагата говорил о песчинках."</p>
        <p>Бхагават сказал: "Как ты думаешь, Субхути, сколько ни есть в великой реке Ганг песчинок,
            сколько может быть рек Ганг, столько может быть миров, сколько в них песчинок, – много
            ли этих миров?"</p>
        <p>Субхути сказал: "Да, Бхагават, да, Во-Благе-Ушедший, много может быть этих миров".
            Бхагават сказал: "Сколько ни есть, Субхути, в этих мирах существ, я знаю их различные
            потоки мысли. Почему так? Поток мысли, поток мысли, Субхути, Татхагата говорил о нем как
            о не-потоке. Потому говорят: "Поток мысли". Почему так? Нельзя, Субхути, обнаружить
            прошлой мысли, нельзя обнаружить будущей мысли.</p>
        <p><strong>19.</strong> Как ты думаешь, Субхути, если какой-либо сын или дочь из хорошей
            семьи наполнит семью драгоценностями три тысячи миллионов миров и преподнесет их в дар
            Татхагатам, архатам, совершенным Буддам, то создаст ли по этой причине сын или дочь из
            хорошей семьи огромное скопление святых заслуг?</p>
        <p>Субхути сказал: "Огромное, Во-Благе-Ушедший."</p>
        <p>Бхагават сказал: «Да, Субхути, сын или дочь из хорошей семьи создаст по этой причине
            огромные скопления святых заслуг. Почему так? Скопление святых заслуг, Татхагата говорил
            о них как о не-скоплении. Поэтому говорят: "Скопление святых заслуг". Если бы, Субхути,
            не было скопления святых заслуг, то Татхагата не говорил бы: "Скопление святых заслуг,
            скопление святых заслуг".</p>
        <p><strong>20-а.</strong> Как ты думаешь, Субхути, должно ли рассматривать Татхагату с точки
            зрения совершенства оформленного тела (рупакая)?»</p>
        <p>Субхути сказал: «Нет, Бхагават, не должно рассматривать Татхагату с точки зрения
            совершенства оформленного тела. Почему так? Совершенство оформленного тела, Бхагават
            говорил о нем как о не-совершенстве. Поэтому говорят: "Совершенство оформленного
            тела".»</p>
        <p><strong>20-б.</strong> Бхагават сказал: "Как ты думаешь, Субхути, должно ли рассматривать
            Татхагату с точки зрения полноты признаков?"</p>
        <p>Субхути сказал: «Нет, Бхагават, не должно рассматривать Татхагату с точки зрения полноты
            признаков. Почему так? Бхагават, о чем Татхагата говорил как о полноте признаков, об
            этом Татхагата говорил как о не-полноте. Поэтому говорят: "Полнота признаков".»</p>
        <p><strong>21-а.</strong> Бхагават сказал: «Как ты думаешь, Субхути, бывает ли у Татхагаты
            такая мысль: "Я показал Дхарму"?»</p>
        <p>Субхути сказал: «Нет, Бхагават, не бывает у Татхагаты такой мысли: "Я показал
            Дхарму".»</p>
        <p>Татхагата сказал: "Тот, Субхути, кто скажет так: Татхагата показал Дхарму, тот скажет не
            то, ложно обвинит меня он из-за принятия того, чего нет. Почему так? Показание Дхармы,
            показание Дхармы, Субхути, нет никакой Дхармы, которая была бы показанием Дхармы.»</p>
        <p><strong>21-б.</strong> В ответ на эти слова достопочтенный Субхути так сказал Бхагавату:
            "Будут ли существа, Бхагават, в будущем, в последующие времена, в последующие пять
            столетий, когда будет происходить исчезновение сущей Дхармы, которые, услышав о такого
            рода Дхармах, уверуют?"</p>
        <p>Бхагават сказал: «Они, Субхути, ни существа, ни не-существа. Почему так? Существа,
            существа, Субхути, обо всех них Татхагата говорил как о не-существах. Поэтому говорят:
            "Существа".</p>
        <p><strong>22.</strong> Как ты думаешь, Субхути, есть ли какая-нибудь дхарма, которую
            Татхагата понимал как наивысшее совершенное просветление?»</p>
        <p>Достопочтенный Субхути сказал: "Нет, Бхагават. Нет, Бхагават, никакой дхармы, которую
            Татхагата понимал как наивысшее совершенное просветление."</p>
        <p>Бхагават сказал: «Да, Субхути, там нет даже малейшей дхармы, поэтому говорят: "Наивысшее
            совершенное просветление."</p>
        <p><strong>23.</strong> И еще, Субхути, это равная дхарма, и там нет ничего неравного,
            поэтому говорят: наивысшее совершенное просветление. Это наивысшее совершенное
            просветление равно отсутствию души, отсутствию существа, отсутствию жизни, отсутствию
            индивида и познается при помощи всех благих дхарм. Почему так? Благие дхармы, благие
            дхармы, Субхути, Татхагата говорил о них как о не-дхармах. Поэтому говорят: благие
            дхармы.</p>
        <p><strong>24.</strong> И еще, Субхути, если женщина или мужчина соберет столько царей гор
            Сумеру из семи драгоценностей, сколько ни есть этих гор в трех миллионах миров, и их
            отдаст в дар Татхагатам, архатам, совершенным Буддам, а этот сын или дочь из хорошей
            семьи возьмет хоть одну четырехстопную гатху из изложения Дхармы запредельной интуиции и
            покажет другим, то первое скопление святых заслуг не составит даже сотой части этого
            скопления святых заслуг, поскольку нельзя даже сравнивать.»</p>
        <p><strong>25.</strong> Бхагават сказал: «Как ты думаешь, Субхути, бывает ли у Татхагаты
            такая мысль: "Я освободил существ"? Но, конечно, Субхути, нельзя рассматривать так.
            Почему так? Нет, Субхути, никакого существа, которого освободил бы Татхагата. Если же,
            Субхути, было бы какое-нибудь существо, которое освободил Татхагата, то у Татхагаты было
            бы представление "душа", было бы представление "существо", было бы представление
            "жизнь", было бы представление "индивид". Представление "душа", Субхути, Татхагата
            говорил о нем как о не-представлении. Это представление создано неразумными
            обыкновенными людьми. Неразумные обыкновенные люди, Субхути, Татхагата говорил о них как
            о не-людях. Поэтому говорят: "Неразумные обыкновенные люди".»</p>
        <p><strong>26-а.</strong> Бхагават сказал: "Как ты думаешь, Субхути, должно ли рассматривать
            Татхагату с точки зрения полноты признаков?"</p>
        <p>Субхути сказал: "Нет, Бхагават, если я понимаю смысл сказанного Бхагаватом, то Татхагату
            не должно рассматривать с точки зрения полноты признаков".</p>
        <p>Бхагават сказал: "Правильно, Субхути, это именно так, как ты говоришь: не должно
            рассматривать с точки зрения полноты признаков. Почему так? Если бы Татхагату можно было
            бы рассматривать с точки зрения полноты признаков, то и царь, император был бы
            Татхагатой. Поэтому Татхагату не должно рассматривать с точки зрения полноты
            признаков".</p>
        <p>Достопочтенный Субхути сказал Бхагавату так: "Если я понимаю смысл сказанного Бхагаватом,
            то Татхагату не должно рассматривать с точки зрения полноты признаков.</p>
        <p>И в это время Бхагават произнес такие стихи:</p>
        <blockquote class="border-l-4 border-gray-500 pl-6 my-6 text-gray-800 text-lg italic">
            "Кто смотрел на мою форму,<br>
            Кто следовал за моим голосом,<br>
            Движимые ложным стремлением,<br>
            Эти люди не увидят меня."
        </blockquote>
        <p><strong>26-б.</strong></p>
        <blockquote class="border-l-4 border-gray-500 pl-6 my-6 text-gray-800 text-lg italic">
            С точки зрения Дхармы следует смотреть на Будд,<br>
            Ибо тела Дхармы есть водители,<br>
            Не следует распознавать природу Дхармы,<br>
            Ибо ее нельзя распознать.
        </blockquote>
        <p><strong>27.</strong> Как ты думаешь, Субхути, понимал ли Татхагата наивысшее совершенное
            просветление с точки зрения полноты признаков? Ты не должен, Субхути, смотреть таким
            образом. Почему так? Ибо не мог, Субхути, Татхагата понимать наивысшее совершенное
            просветление с точки зрения полноты признаков.</p>
        <p>И пусть никто не скажет тебе так, Субхути: вступившие на стезю бодхисаттвы учили об
            уничтожении какой-либо дхармы или исчезновению. Ты, Субхути, не должен так смотреть.
            Почему так? Вступившие на стезю бодхисаттвы не учили об уничтожении какой-либо дхармы
            или исчезновению.</p>
        <p><strong>28.</strong> И еще, Субхути, если какой-нибудь сын или дочь из хорошей семьи
            наполнит семью драгоценностями миры, число которых равно числу песчинок в великой реке
            Ганг, и преподнесет их в дар Татхагатам, архатам, совершенным Буддам, а какой-нибудь
            бодхисаттва обретет (совершенство) терпения, (основанное на том), что дхармы не имеют
            души и не возникают, то по этой причине (именно) он создаст неизмеримые мириады
            скоплений святых заслуг. Но великосущный бодхисаттва, Субхути, не должен приобретать
            скопление святых заслуг."</p>
        <p>Достопочтенный Субхути сказал: "Разве бодхисаттва не должен, Бхагават, приобретать
            скопление святых заслуг?"</p>
        <p>Бхагават сказал: «Должен приобретать, Субхути, но не должен держаться. Поэтому говорят:
            должен приобретать.</p>
        <p><strong>29.</strong> И еще, Субхути, если кто-нибудь скажет так: "Татхагата уходит или
            приходит или сидит или лежит", он не понимает, Субхути, смысл сказанного мною. Почему
            так? Татхагата, Субхути, никуда не ушел и ниоткуда не пришел. Поэтому говорят:
            Татхагата, архат, совершенный Будда.»</p>
